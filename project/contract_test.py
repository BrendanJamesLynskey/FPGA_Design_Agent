"""The contract-test generator: from ``contract.yaml`` to a cocotb test, mechanically (no model writes or reads it).

For a module directory it writes two files:

- ``tests/contract_tb.py``: the cocotb tests, one per applicable check, with the contract embedded as data and the
  checks imported from :mod:`project.contract_bench`;
- ``tests/test_contract_rtl.py``: the pytest runner (``flow/cocotb_run.py``, Icarus by default) over ``rtl/*.sv`` and
  ``rtl/*.v`` with the contract's parameters and the design's overrides.

Both start with the SHA-256 of the contract they were made from, so a stale generated test is visible. The tests run
before any role-written test (docs/design_environment.md, section 2). Which checks are generated:

| Contract content | Test |
|---|---|
| ``ports`` | ``contract_ports`` (every port, with its width) |
| always | ``contract_reset`` |
| an AXI4-Stream slave | ``contract_axis_slave_<interface>`` |
| an AXI4-Stream master | ``contract_axis_master_<interface>`` |
| each ``latency`` entry | ``contract_latency_<n>_<from>_<to>`` |
| each ``throughput`` entry with ``out_per_in`` | ``contract_throughput_<n>_<interface>`` |
| ``registers`` on an AXI4-Lite or shell-window bus | ``contract_registers`` (``bus: top`` is checked at integration) |

    python -m project gen-tests <project> [--module M]
"""

from __future__ import annotations

import hashlib
import json
import pprint
from pathlib import Path
from typing import Any

from project.schema import check_contract, iface_map, params_of

TB_NAME = "contract_tb"
RUNNER_NAME = "test_contract_rtl.py"


def tests_for(c: dict[str, Any]) -> list[tuple[str, str]]:
    """(test name, the bench call) for every check that applies to this contract."""
    out = [("contract_ports", "cb.check_ports(dut, CONTRACT, PARAMS)"),
           ("contract_reset", "cb.check_reset(dut, CONTRACT, PARAMS)")]
    for f in c.get("interfaces") or []:
        if f.get("protocol") != "axi4-stream":
            continue
        kind = "slave" if f["role"] == "slave" else "master"
        out.append((f"contract_axis_{kind}_{f['name']}", f"cb.check_axis_{kind}(dut, CONTRACT, PARAMS, {f['name']!r})"))
    for i, L in enumerate(c.get("latency") or []):
        out.append((f"contract_latency_{i}_{L['from']}_{L['to']}", f"cb.check_latency(dut, CONTRACT, PARAMS, {i})"))
    for i, t in enumerate(c.get("throughput") or []):
        if "out_per_in" in t:
            out.append((f"contract_throughput_{i}_{t['interface']}", f"cb.check_throughput(dut, CONTRACT, PARAMS, {i})"))
    regs = c.get("registers")
    if isinstance(regs, dict) and regs.get("bus") in iface_map(c):
        out.append(("contract_registers", "cb.check_registers(dut, CONTRACT, PARAMS)"))
    return out


def _sha(c_text: str) -> str:
    return hashlib.sha256(c_text.encode()).hexdigest()


def generate(contract_text: str, overrides: dict[str, Any] | None = None) -> dict[str, str]:
    """{file name under tests/: content}. Raises ValueError when the contract does not pass its checker."""
    import yaml
    c = yaml.safe_load(contract_text)
    errs = check_contract(c)
    if errs:
        raise ValueError("contract.yaml has problems; fix them first:\n  " + "\n  ".join(errs))
    params = params_of(c, overrides)
    sha = _sha(contract_text)
    tests = tests_for(c)
    data = pprint.pformat(c, width=110, sort_dicts=True)
    body = [f'"""Contract test of {c["module"]}, generated by `python -m project gen-tests` from contract.yaml',
            f"(sha256 {sha}).", "Mechanical: no model wrote it. Do not edit; regenerate after a contract change.",
            '"""', "", "import cocotb", "", "from project import contract_bench as cb", "",
            f"CONTRACT_SHA256 = {sha!r}",
            f"PARAMS = {json.dumps(params, sort_keys=True)}",
            "CONTRACT = " + data, ""]
    for name, call in tests:
        body += ["", "@cocotb.test()", f"async def {name}(dut):", f"    await {call}", ""]
    top = c.get("hdl_top") or c["module"]
    runner = [f'"""Runs the generated contract test of {c["module"]} on rtl/ with Icarus (contract.yaml sha256',
              f'{sha}). Generated by `python -m project gen-tests`; do not edit."""', "",
              "from pathlib import Path", "", "from flow import cocotb_run", "",
              "HERE = Path(__file__).parent",
              f"PARAMS = {json.dumps(params, sort_keys=True)}", "", "",
              "def test_contract(tmp_path: Path) -> None:",
              '    rtl = sorted((HERE.parent / "rtl").glob("*.sv")) + sorted((HERE.parent / "rtl").glob("*.v"))',
              '    assert rtl, "no RTL in rtl/ yet: the contract test runs once the module has RTL"',
              f'    cocotb_run.run("contract_{c["module"]}", {top!r}, rtl, {TB_NAME!r}, HERE, parameters=PARAMS, '
              "seed=1, build_root=tmp_path)", ""]
    return {f"{TB_NAME}.py": "\n".join(body).replace("\n\n\n\n", "\n\n\n"), RUNNER_NAME: "\n".join(runner)}


def write(module_dir: Path, overrides: dict[str, Any] | None = None) -> list[Path]:
    files = generate((module_dir / "contract.yaml").read_text(), overrides)
    out = []
    (module_dir / "tests").mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        p = module_dir / "tests" / name
        p.write_text(text)
        out.append(p)
    return out
