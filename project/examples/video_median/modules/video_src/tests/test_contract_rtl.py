from pathlib import Path

from flow import cocotb_run

HERE = Path(__file__).parent
PARAMS = {"H_ACTIVE": 1280, "H_BP": 220, "H_FP": 110, "H_SYNC": 40, "V_ACTIVE": 720, "V_BP": 20, "V_FP": 5, "V_SYNC": 5}


def test_contract(tmp_path: Path) -> None:
    rtl = sorted((HERE.parent / "rtl").glob("*.sv")) + sorted((HERE.parent / "rtl").glob("*.v"))
    assert rtl, "no RTL in rtl/ yet: the contract test runs once the module has RTL"
    cocotb_run.run("contract_video_src", 'video_src', rtl, 'contract_tb', HERE, parameters=PARAMS, seed=1, build_root=tmp_path)
