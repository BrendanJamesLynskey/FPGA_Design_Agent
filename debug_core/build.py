"""Debug builds for a plan: one ILA build per probe set, kept and reused (brief 50A).

A plan's probes become a ``probes.yaml`` in an overlay design directory ``<design>/build/debug/<probeset>/``. The overlay's
``build.yaml`` is the design's with ``probes`` pointing at that file; every other design file (spec, architecture, data)
is a symbolic link to the design's own, so ``flow/run_vivado.sh <overlay> ila`` is the normal ILA build (brief 48's ILA IP
insertion, packed ports, ``flow/ltx_fix.py``, all gates) with its normal build cache. ``build/base`` links to the design's
base build, so the ILA build can start from its synthesis checkpoint when the synthesis inputs are the same.

``find_build(plan)`` looks for a finished debug build that already holds every probe of the plan (by pins), on the same
clock, at least as deep: then no rebuild is needed (the trigger and the window are run-time settings).
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

from debug_core.plan import probes_yaml
from debug_core.rtl_index import ROOT

SKIP = {"build", "build.yaml", "probes.yaml"}


def design_dir(plan: dict[str, Any]) -> Path:
    d = Path(plan["design"])
    return d if d.is_absolute() else ROOT / d


def overlay_dir(plan: dict[str, Any]) -> Path:
    return design_dir(plan) / "build" / "debug" / plan["probeset"]


def make_overlay(plan: dict[str, Any]) -> Path:
    design = design_dir(plan)
    ov = overlay_dir(plan)
    ov.mkdir(parents=True, exist_ok=True)
    (ov / "probes.yaml").write_text(probes_yaml(plan))
    cfg = yaml.safe_load((design / "build.yaml").read_text())
    cfg["probes"] = str((ov / "probes.yaml").relative_to(ROOT))
    (ov / "build.yaml").write_text("# generated by debug_core/build.py: the design's build.yaml with the debug plan's probes\n"
                                   + yaml.safe_dump(cfg, sort_keys=False))
    for entry in design.iterdir():
        if entry.name in SKIP or entry.name.startswith("."):
            continue
        link = ov / entry.name
        if not link.exists() and not link.is_symlink():
            link.symlink_to(entry.resolve())
    (ov / "build").mkdir(exist_ok=True)
    base = design / "build" / "base"
    if base.is_dir() and not (ov / "build" / "base").exists():
        (ov / "build" / "base").symlink_to(base.resolve())
    (ov / "plan.json").write_text(json.dumps(plan, indent=1) + "\n")
    return ov


def build_state(ov: Path) -> dict[str, Any]:
    b = ov / "build" / "ila"
    prep = b / "prepare.json"
    if not prep.is_file():
        return {"built": False}
    top = json.loads(prep.read_text())["top"]
    ok = (b / f"{top}.bit").is_file() and (b / f"{top}.ltx").is_file() and (b / "probe_map.txt").is_file()
    gates = json.loads((b / "gates.json").read_text()) if (b / "gates.json").is_file() else {}
    return {"built": ok, "dir": str(b), "top": top, "gates_pass": gates.get("pass"),
            "run": json.loads((b / "run.json").read_text()) if (b / "run.json").is_file() else {}}


def tree_stamp(design: Path) -> str:
    """The build stamp the design's sources have now (flow/prepare.py: hash of every source, constraint and data file)."""
    import tempfile
    with tempfile.TemporaryDirectory() as t:
        r = subprocess.run([sys.executable, str(ROOT / "flow" / "prepare.py"), str(design), "--variant", "base", "--out", t],
                           capture_output=True, text=True, check=True, cwd=ROOT)
    return json.loads(r.stdout)["build_stamp"]


def build_ports(ov: Path) -> dict[int, list[str]]:
    """port -> probe names, from the build's own probe_map.txt (what was really built, not what a plan says)."""
    from flow import ila
    ports: dict[int, list[str]] = {}
    for name, port, _off, _w in ila.read_probe_slices(ov / "build" / "ila" / "probe_map.txt"):
        ports.setdefault(port, []).append(name)
    return ports


def or_layout_ok(plan: dict[str, Any], ports: dict[int, list[str]], labels: dict[str, str]) -> bool:
    """An OR plan with more than one term needs each term alone on its port: the Basic tier's ILA has one comparator per
    port and refuses OR compares that share one (measured, Labtools 27-3239/27-3241)."""
    conds = plan["trigger"]["conditions"]
    if plan["trigger"]["combine"] != "OR" or len(conds) < 2:
        return True
    where = {n: p for p, names in ports.items() for n in names}
    seen = set()
    for c in conds:
        port = where.get(labels.get(c["probe"], c["probe"]))
        if port is None or port in seen:
            return False
        seen.add(port)
    return True


def find_build(plan: dict[str, Any], stamp: str | None = None) -> tuple[Path, dict[str, str]] | None:
    """A finished debug build that can serve the plan. Returns (overlay, {plan label: build label}).

    A candidate must: hold every probe of the plan (by pins), on the same clock net, at least as deep; have been built
    from the sources the design has now (its build stamp equals ``stamp``, computed from the tree when not given); and,
    for an OR plan, have each OR term alone on its port in the build's own probe_map.txt. Among the candidates the
    smallest (probe bits, then ports, then probe set id) is chosen; correctness never depends on that order."""
    root = design_dir(plan) / "build" / "debug"
    if not root.is_dir():
        return None
    want = {p["pins"]: p["label"] for p in plan["probes"]}
    cands = []
    for ov in sorted(root.iterdir()):
        pj = ov / "plan.json"
        st = build_state(ov) if pj.is_file() else {"built": False}
        if not st["built"]:
            continue
        old = json.loads(pj.read_text())
        have = {p["pins"]: p["label"] for p in old["probes"]}
        if not (set(want) <= set(have) and old["clock"].get("net") == plan["clock"].get("net")
                and old["window"]["depth"] >= plan["window"]["depth"]):
            continue
        labels = {want[k]: have[k] for k in want}
        ports = build_ports(ov)
        if not or_layout_ok(plan, ports, labels):
            continue
        if stamp is None:
            stamp = tree_stamp(design_dir(plan))
        built = json.loads((ov / "build" / "ila" / "prepare.json").read_text()).get("build_stamp")
        if built != stamp:
            continue                       # stale: the design's sources changed since this build
        cands.append(((sum(p["width"] for p in old["probes"]), len(ports), ov.name), ov, labels))
    if not cands:
        return None
    cands.sort(key=lambda c: c[0])
    refresh_overlay(cands[0][1])
    return cands[0][1], cands[0][2]


def refresh_overlay(ov: Path) -> None:
    """Rewrite the overlay's build.yaml from the design's current one (keeping the overlay's probes)."""
    design = ov.parents[2]
    cfg = yaml.safe_load((design / "build.yaml").read_text())
    pf = ov / "probes.yaml"
    cfg["probes"] = str(pf.relative_to(ROOT)) if pf.is_relative_to(ROOT) else str(pf)
    (ov / "build.yaml").write_text("# generated by debug_core/build.py: the design's build.yaml with the debug plan's probes\n"
                                   + yaml.safe_dump(cfg, sort_keys=False))


def run_build(plan: dict[str, Any], log: Path | None = None, timeout_s: int = 3600) -> dict[str, Any]:
    """flow/run_vivado.sh <overlay> ila. The caller holds a heavy slot (house rules); this function does not take one."""
    ov = make_overlay(plan)
    log = log or ov / "build_ila.log"
    with open(log, "w") as f:
        r = subprocess.run(["bash", str(ROOT / "flow" / "run_vivado.sh"), str(ov), "ila"], cwd=ROOT, stdout=f,
                           stderr=subprocess.STDOUT, timeout=timeout_s, env=dict(os.environ))
    st = build_state(ov)
    st.update({"returncode": r.returncode, "log": str(log), "overlay": str(ov)})
    return st
