#!/usr/bin/env python3
"""Cross-check the Lean transcription of tcp_fast.sv's checksum equations against brief 119's own Python reference.

119's software reference (designs/b119_tcp_fast/model/tcpref.py, checksum() and the frame builders) was itself checked against the RTL
in 119's cocotb tests. This script draws random connections, orders and payloads, builds the real IPv4 header and TCP segment with
that reference, and writes Cksum/CrossCheck.lean: one `#guard` per vector comparing the Lean RTL equations (rtlIpCsum, rtlTcpCsum)
with the reference's checksum field. A mismatch fails `lake build`. This is a test of the transcription (the manual step), not a proof.

  python3 formal/lean/tools/crosscheck_b119.py --b119 <path to designs/b119_tcp_fast> [--n 300] [--seed 124]
"""
import argparse
import random
import sys
from pathlib import Path

LEAN = Path(__file__).resolve().parent.parent
PAYLEN = 59   # the RTL's fixed payload length (OUCH Enter Order); total length 99 = 20 + 20 + 59


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--b119", required=True)
    ap.add_argument("--n", type=int, default=300)
    ap.add_argument("--seed", type=int, default=124)
    a = ap.parse_args()
    sys.path.insert(0, str(Path(a.b119).resolve().parent))
    from b119_tcp_fast.model import tcpref as T
    rnd = random.Random(a.seed)
    out = ["import Cksum.Spec", "",
           "/-! Generated by tools/crosscheck_b119.py: vectors from designs/b119_tcp_fast/model/tcpref.py (brief 119). Do not edit. -/",
           "open Cksum", ""]
    for _ in range(a.n):
        c = T.Conn(sip=rnd.getrandbits(32), dip=rnd.getrandbits(32), sport=rnd.getrandbits(16), dport=rnd.getrandbits(16),
                   ttl=rnd.getrandbits(8))
        seq, ack, win, ident = rnd.getrandbits(32), rnd.getrandbits(32), rnd.getrandbits(16), rnd.getrandbits(16)
        payload = bytes(rnd.getrandbits(8) for _ in range(PAYLEN))
        seg = T.tcp_segment(c.sip, c.dip, c.sport, c.dport, seq, ack, 0x18, win, payload)
        assert len(seg) == 20 + PAYLEN
        ip = T.ip_header(c, ident, 20 + len(seg))
        assert int.from_bytes(ip[2:4], "big") == 99
        ipcs, tcs = int.from_bytes(ip[10:12], "big"), int.from_bytes(seg[16:18], "big")
        pad = payload + b"\0"
        pw = ", ".join(f"0x{(pad[i] << 8) | pad[i + 1]:04x}#16" for i in range(0, len(pad), 2))
        out.append(f"#guard rtlIpCsum 0x{c.ttl:02x}#8 0x{c.sip:08x}#32 0x{c.dip:08x}#32 0x{ident:04x}#16 == 0x{ipcs:04x}#16")
        out.append(f"#guard rtlTcpCsum 0x{c.sip:08x}#32 0x{c.dip:08x}#32 0x{c.sport:04x}#16 0x{c.dport:04x}#16 0x{seq:08x}#32 0x{ack:08x}#32 "
                   f"0x{win:04x}#16 [{pw}] == 0x{tcs:04x}#16")
    (LEAN / "Cksum" / "CrossCheck.lean").write_text("\n".join(out) + "\n")
    print(f"wrote {2 * a.n} guards")
    return 0


if __name__ == "__main__":
    sys.exit(main())
