#!/usr/bin/env python3
"""Cross-check the Lean transcriptions of the arithmetic library's recurrences against the Python bit-exact models (brief 139b).

Writes Arith/CrossCheck.lean: one `#guard` per case comparing a Lean function with the value the Python model computes (the divider's
restoring and non-restoring recurrences, the square-root restoring and radix-4 recurrences, the convergent carry-in form, the leading-zero tree). The Python
models in arith/*/model.py are written from the specs and are tied to the RTL by the simulation tests, so a `lake build` that passes shows
the Lean text computes what the model computes; it is a test of the transcription, not a proof about the RTL.

  python3 formal/lean/tools/crosscheck_arith.py
"""
import sys
from pathlib import Path

LEAN = Path(__file__).resolve().parent.parent
ROOT = LEAN.parents[1]
sys.path.insert(0, str(ROOT))
from arith.divider import model as DM            # noqa: E402
from arith.fxp_round import model as FM          # noqa: E402
from arith.isqrt import model as SM              # noqa: E402
from arith.lzc_norm import model as LM           # noqa: E402
from arith.sqrt_r4 import model as RM            # noqa: E402


def render() -> str:
    o = ["import Arith.Divide", "import Arith.Rounding", "import Arith.Isqrt", "import Arith.Lzc", "import Arith.SqrtR4", "",
         "/-! Generated by tools/crosscheck_arith.py from arith/*/model.py. Do not edit. -/", "open Arith", ""]
    # divider: restoring (quotient, remainder) for every n, d of widths 2 to 5; non-restoring (signed remainder before correction, quotient bits) for d > 0
    for w in range(2, 6):
        for d in range(1 << w):
            ex = [DM.restoring_trace(n, d, w)[-1] for n in range(1 << w)]
            o.append(f"#guard ((List.range {1 << w}).map fun n => Divide.restDiv {d} {w} n) == [" + ", ".join(f"({q}, {p})" for p, q in ex) + "]")
            if d:
                nr = [DM.nonrestoring_trace(n, d, w)[0][-1] for n in range(1 << w)]
                o.append(f"#guard ((List.range {1 << w}).map fun n => Divide.nrRun {d} {w} n) == [" + ", ".join(f"({p}, {q})" for p, q in nr) + "]")
    # square root: (root, remainder) of the restoring recurrence, w pairs, every radicand of 2w bits for w up to 5
    for w in range(1, 6):
        ex = [SM.restoring_trace(x, 2 * w)[-1] for x in range(1 << (2 * w))]
        o.append(f"#guard ((List.range {1 << (2 * w)}).map fun x => Isqrt.rsqrt {w} x) == [" + ", ".join(f"({q}, {p})" for p, q in ex) + "]")
    # radix-4 square root (brief 139c): (root, remainder) of the radix-4 recurrence, n nibbles, every radicand of 8 bits (n = 2) and every 17th of 12 bits (n = 3)
    ex = [RM.r4_trace(x, 8)[1] for x in range(256)]
    o.append("#guard ((List.range 256).map fun x => SqrtR4.r4sqrt 2 x) == [" + ", ".join(f"({q}, {p})" for q, p in ex) + "]")
    ex = [RM.r4_trace(x, 12)[1] for x in range(0, 4096, 17)]          # n = 3: every 17th radicand (a list of 4096 literals is too deep for the code generator)
    o.append("#guard (((List.range 4096).filter fun x => x % 17 = 0).map fun x => SqrtR4.r4sqrt 3 x) == [" + ", ".join(f"({q}, {p})" for q, p in ex) + "]")
    # rounding: the carry-in form with h = 2**(s-1), for s = 1 to 4 and every x of 8 bits (signed)
    for s in range(1, 5):
        ex = [FM.fold_add(x, s, 2) for x in range(-128, 128)]
        o.append(f"#guard ((List.range 256).map fun (i : Nat) => Rounding.convFold {1 << (s - 1)} ((i : Int) - 128)) == [" + ", ".join(str(v) for v in ex) + "]")
        ex1 = [FM.rnd(x, s, 1) for x in range(-128, 128)]
        o.append(f"#guard ((List.range 256).map fun (i : Nat) => Rounding.halfUp {1 << (s - 1)} ((i : Int) - 128)) == [" + ", ".join(str(v) for v in ex1) + "]")
    # leading zeros: tree of 2^k bits (k up to 3: 8-bit words), every word; the count is only defined for a non-zero word
    for k in range(0, 4):
        w, n = 1 << k, 1 << (1 << k)
        if w < 2:
            ex = [(0, x != 0) for x in range(n)]
        else:
            ex = [((LM.lzc_norm(x, w)[0] if x else 0), x != 0) for x in range(n)]
        o.append(f"#guard ((List.range {n}).map fun x => (Lzc.lzcTree {k} x).1) == [" + ", ".join(str(c) for c, _ in ex) + "]"
                 if k == 0 else
                 f"#guard ((List.range {n}).map fun x => if x = 0 then 0 else (Lzc.lzcTree {k} x).1) == [" + ", ".join(str(c) for c, _ in ex) + "]")
        o.append(f"#guard ((List.range {n}).map fun x => (Lzc.lzcTree {k} x).2) == [" + ", ".join("true" if nz else "false" for _, nz in ex) + "]")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    (LEAN / "Arith" / "CrossCheck.lean").write_text(render())
    print("wrote", LEAN / "Arith" / "CrossCheck.lean")
