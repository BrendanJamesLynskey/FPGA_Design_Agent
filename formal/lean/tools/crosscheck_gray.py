#!/usr/bin/env python3
"""Cross-check the Lean transcription of the gray encoder and decoder against the repository's behavioural model of xpm_cdc_gray (brief 125).

Runs flow/cdc_models/xpm_cdc_models.sv (the repository's model of AMD's macro, written from UG974) in Icarus Verilog for widths 1 to 8, drives
every binary value, reads the gray value the model registers (`dut.g`) and the binary value it decodes on the far side (`dest_out_bin`), and
writes Gray/CrossCheck.lean: one `#guard` per value for the encoder and one for the decoder. A mismatch fails `lake build`. It also checks that
the model round-trips every value. This tests the transcription (a manual step) against a simulation model; it does not test AMD's macro itself.

  python3 formal/lean/tools/crosscheck_gray.py [--max-width 8]
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

LEAN = Path(__file__).resolve().parent.parent
ROOT = LEAN.parents[1]
MODELS = ROOT / "flow" / "cdc_models"
TB = """module tb;
  logic clk = 0; always #5 clk = ~clk;
  parameter W = 4;
  logic [W-1:0] b = '0; wire [W-1:0] o;
  xpm_cdc_gray #(.DEST_SYNC_FF(2), .WIDTH(W)) dut (.src_clk(clk), .src_in_bin(b), .dest_clk(clk), .dest_out_bin(o));
  initial begin
    for (int v = 0; v < 2**W; v++) begin
      b = v; repeat (5) @(posedge clk); #1;
      $display("%0d %0d %0d %0d", W, v, dut.g, o);
    end
    $finish;
  end
endmodule
"""


def rows(max_width: int) -> list[tuple[int, int, int, int]]:
    out = []
    with tempfile.TemporaryDirectory() as td:
        tb = Path(td) / "tb.sv"
        tb.write_text(TB)
        for w in range(1, max_width + 1):
            vvp = Path(td) / f"t{w}.vvp"
            subprocess.run(["iverilog", "-g2012", f"-Ptb.W={w}", "-o", str(vvp), str(MODELS / "cdc_inj_pkg.sv"), str(MODELS / "xpm_cdc_models.sv"), str(tb)],
                           check=True, capture_output=True, text=True)
            r = subprocess.run(["vvp", str(vvp)], check=True, capture_output=True, text=True)
            for ln in r.stdout.splitlines():
                p = ln.split()
                if len(p) == 4 and all(x.isdigit() for x in p):
                    out.append(tuple(int(x) for x in p))
    return out


def render(max_width: int = 8) -> str:
    rs = rows(max_width)
    assert len(rs) == sum(2 ** w for w in range(1, max_width + 1)), "the simulation printed the wrong number of rows"
    for w, v, g, o in rs:
        assert o == v, f"the behavioural model does not round-trip width {w} value {v}: decoded {o}"
    out = ["import Gray.Spec", "",
           "/-! Generated by tools/crosscheck_gray.py: values from flow/cdc_models/xpm_cdc_models.sv (xpm_cdc_gray), run in Icarus Verilog. Do not edit. -/",
           "open Gray", ""]
    for w, v, g, o in rs:
        out.append(f"#guard (bin2gray ({v}#{w})).toNat == {g}")
        out.append(f"#guard (gray2bin ({g}#{w})).toNat == {v}")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--max-width", type=int, default=8)
    a = ap.parse_args()
    t = render(a.max_width)
    (LEAN / "Gray" / "CrossCheck.lean").write_text(t)
    print(f"wrote {t.count('#guard')} guards for widths 1 to {a.max_width}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
