#!/usr/bin/env python3
"""Write fft_common/fft_cos_rom.sv: the master quarter-wave cosine table of fft_ref.COS_MASTER as a two-read-port synchronous ROM (brief 148).

    python3 -m arith.fft_common.gen_cos_rom [--check]"""
from __future__ import annotations

import sys
from pathlib import Path

from arith.fft_common import fft_ref

OUT = Path(__file__).with_name("fft_cos_rom.sv")


def text() -> str:
    t = ["// fft_cos_rom: cos(2 pi i / 4096) for i = 0 .. 1024, 30 fractional bits (31-bit words: the first entry is 2**30), correctly rounded (arith brief 148; generated by fft_common/gen_cos_rom.py, do not edit).",
         "// Two synchronous read ports (one clock), so one quarter-wave table gives cosine and sine at once. The values are the model's (fft_ref.COS_MASTER).",
         "// Intended primitive use (not yet measured): one 1025 x 31 ROM per port, LUT-based or one RAMB18 depending on the tool; no reset.",
         "module fft_cos_rom (",
         "    input  logic        clk,",
         "    input  logic [10:0] a0,",
         "    input  logic [10:0] a1,",
         "    output logic [30:0] d0,",
         "    output logic [30:0] d1",
         ");",
         "    function automatic logic [30:0] rom(input logic [10:0] a);",
         "        case (a)"]
    for i, v in enumerate(fft_ref.COS_MASTER):
        t.append(f"            11'd{i}: rom = 31'h{v:08x};")
    t += ["            default: rom = 31'h0;", "        endcase", "    endfunction",
          "    always_ff @(posedge clk) begin", "        d0 <= rom(a0);", "        d1 <= rom(a1);", "    end", "endmodule", ""]
    return "\n".join(t)


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text() else 1)
    OUT.write_text(text())
