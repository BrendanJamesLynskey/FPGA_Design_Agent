"""The fast-convolution model against numpy.convolve, the FFT-suite models it is built from and the contract's statements (arith brief 161)."""
from __future__ import annotations

import json
import math
import random
import subprocess
import sys

import numpy as np
import pytest

from arith.fft_common import fastconv
from arith.fft_fastconv import model
from arith.tools import arith_common as ac

P = dict(LOGN=6, L=17, W=16, TW=18, WH=24, FH=14, GB=1, RND=1)


def stream(n, rng, amp=0.5, w=16):
    a = int(amp * (1 << (w - 1)))
    return [(rng.randrange(-a, a + 1), rng.randrange(-a, a + 1)) for _ in range(n)]


def lowpass(ll, fc=0.15):
    h = [(math.sin(2 * math.pi * fc * (i - (ll - 1) / 2)) / (math.pi * (i - (ll - 1) / 2)) if i != (ll - 1) / 2 else 2 * fc) * (0.54 - 0.46 * math.cos(2 * math.pi * i / max(1, ll - 1))) for i in range(ll)]
    return [v * min(1.0, 1.8 / sum(abs(u) for u in h)) for v in h]


@pytest.mark.parametrize("logn,ll", [(5, 9), (6, 17), (6, 33), (7, 65), (8, 129), (8, 193)])
def test_equals_numpy_convolve_within_the_stated_bound(logn, ll):
    p = dict(P, LOGN=logn, L=ll)
    rng = random.Random(logn * 1000 + ll)
    h = lowpass(ll)
    hq = model.filter_spectrum(h, 1 << logn, 24, 14)
    d = model.derived(p)
    x = stream(3 * d["B"], rng)
    y, sat = model.process(p, hq, x)
    assert sat == 0 and len(y) == 3 * d["B"]
    ref = np.convolve(np.array([a + 1j * b for a, b in x]), np.array(h))[:len(y)]
    err = np.array([a + 1j * b for a, b in y]) - ref
    assert float(np.max(np.maximum(np.abs(err.real), np.abs(err.imag)))) <= 8.0


def test_a_delta_filter_delays_the_stream():
    p = dict(P, LOGN=5, L=9, W=12, TW=14, WH=16, FH=10)
    h = [0.0] * 9
    h[3] = 1.0
    hq = model.filter_spectrum(h, 32, 16, 10)
    x = stream(24 * 4, random.Random(2), amp=0.4, w=12)
    y, _ = model.process(p, hq, x)
    assert all(max(abs(a - b[0]), abs(c - b[1])) <= 2 for (a, c), b in zip(y[3:], x[:len(y) - 3]))
    assert all(v == (0, 0) or max(abs(v[0]), abs(v[1])) <= 2 for v in y[:3])


def test_the_stream_object_equals_one_call_and_chunks_do_not_matter():
    rng = random.Random(5)
    h = lowpass(17)
    hq = model.filter_spectrum(h, 64, 24, 14)
    x = stream(48 * 3 + 7, rng)
    one, _ = model.process(P, hq, x)
    st = model.Stream(P)
    for i in range(0, len(x), 11):
        st.feed(hq, x[i:i + 11])
    assert st.out == one and len(one) == 48 * 3 and len(st.buf) == 7


def test_the_overlap_save_model_of_phase_0_gives_the_same_samples():
    """arith/fft_common/fastconv.py (phase 0) takes the same blocks through the same FFT models: at gain below 1 the two agree sample for sample."""
    rng = random.Random(6)
    ll = 17
    h = [v * 0.5 for v in lowpass(ll)]
    hq = model.filter_spectrum(h, 64, 24, 14)
    x = stream(48 * 2, rng)
    y, _ = model.process(dict(P, GB=1), hq, x)
    z = fastconv.overlap_save(x, h, 6, 16, 18, 24, 14, "sdf")
    assert [tuple(v) for v in z[:len(y)]] == y


def test_l_equals_one_is_a_gain():
    p = dict(P, L=1, GB=0)
    hq = model.filter_spectrum([0.5], 64, 24, 14)
    x = stream(64 * 2, random.Random(1))
    y, _ = model.process(p, hq, x)
    assert all(max(abs(a - b[0] / 2), abs(c - b[1] / 2)) <= 3 for (a, c), b in zip(y, x))


def test_saturation_clamps_and_counts():
    p = dict(P, LOGN=5, L=9, W=8, TW=10, WH=12, FH=8, GB=1)
    h = [0.0] * 9
    h[0] = 1.9
    hq = model.filter_spectrum(h, 32, 12, 8)
    x = [(120, -120)] * 48
    y, sat = model.process(p, hq, x)
    assert sat > 0 and all(-128 <= a <= 127 and -128 <= b <= 127 for a, b in y)
    assert y[-1] == (127, -128)


def test_only_complete_blocks_are_processed():
    hq = model.filter_spectrum(lowpass(17), 64, 24, 14)
    y, _ = model.process(P, hq, stream(47, random.Random(0)))
    assert y == []


def test_the_latency_formula_is_the_specs():
    spec = ac.load_spec("fft_fastconv")
    for pt in spec["variants"]["os"]["exhaustive_points"]:
        p = ac.merged_params(spec, "os", pt)
        assert model.latency(p) == ac.latency_of(spec, "os", p)


def test_the_recorded_accuracy_is_what_the_models_give_today(tmp_path):
    """verif/results/accuracy.json is regenerated by arith/tools/fft_fastconv_accuracy.py; the test reruns it and compares every number (the date is not compared)."""
    out = tmp_path / "accuracy.json"
    r = subprocess.run([sys.executable, "-m", "arith.tools.fft_fastconv_accuracy", "--out", str(out)], cwd=ac.ROOT, capture_output=True, text=True)
    assert r.returncode == 0, r.stderr[-400:]
    now = json.loads(out.read_text())
    rec = json.loads((ac.ARITH / "fft_fastconv" / "verif" / "results" / "accuracy.json").read_text())
    now.pop("date"), rec.pop("date")
    assert now == rec, "arith/fft_fastconv/verif/results/accuracy.json is out of date: run python -m arith.tools.fft_fastconv_accuracy"
    assert rec["worst_lsb_max"] <= 8.0 and rec["points"] >= 16 and rec["saturated_max"] == 0
