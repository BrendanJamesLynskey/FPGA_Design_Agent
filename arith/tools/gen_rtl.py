#!/usr/bin/env python3
"""Write the RTL of the elementary-function variants (arith brief 139d): exp2, log2, sincos, atan2_mag.

    python3 -m arith.tools.gen_rtl [--check]

The constants of a variant (the break-point tables of the table-plus-polynomial variants, the CORDIC angle and gain constants) come from arith/tools/fxlib.py,
the same functions the models use, so a table in the RTL cannot differ from the model's. Everything else is the text below. The generated files
arith/<fn>/rtl/*.sv are committed and carry the notice "generated, edit the generator"; ``--check`` fails if one is out of date (a test and CI do the same)."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from arith.tools import arith_common as ac
from arith.tools import fxlib as fx

NOTE = "// Generated by arith/tools/gen_rtl.py (arith brief 139d) from arith/tools/fxlib.py's constants: edit the generator, not this file.\n"


# ---- constant tables ------------------------------------------------------------------------------------------------------------------------
def rom_direct_fn(f: str) -> str:
    return fx.sv_case_function("rom_d", fx.CF, 8, list(enumerate(fx.rom_direct(f))))


def rom_lerp_fns(f: str, tag: str) -> str:
    c0 = [((sb << 6) | i, v) for sb in fx.SB_LERP for i, v in enumerate(fx.rom_lerp(f, sb)[0])]
    s1 = [((sb << 6) | i, v) for sb in fx.SB_LERP for i, v in enumerate(fx.rom_lerp(f, sb)[1])]
    return fx.sv_case_function(f"rom_c0{tag}", 22, 9, c0, True) + "\n" + fx.sv_case_function(f"rom_s1{tag}", 22, 9, s1, True)


def rom_poly_fns(f: str, tag: str) -> str:
    out = []
    for j in range(3):
        items = [((sb << 6) | i, v) for sb in fx.SB_POLY for i, v in enumerate(fx.rom_poly(f, sb)[j])]
        out.append(fx.sv_case_function(f"rom_a{j}{tag}", 22, 9, items, True))
    return "\n".join(out)


def atan_turn_fn() -> str:
    return fx.sv_case_function("atan_q", fx.TQ, 5, [(i, fx.atan_turn_q(i)) for i in range(24)])


def atanh_fn() -> str:
    return fx.sv_case_function("atanh_q", fx.TQ, 5, [(i, fx.atanh_q(i)) for i in range(1, 24)])


def hseq_fn(maxn: int = 24) -> str:
    return fx.sv_case_function("hshift", 5, 5, list(enumerate(fx.hyp_seq(maxn))))


def kinv_circ_fn(bits: int) -> str:
    return fx.sv_case_function("kinv", bits + 1, 5, [(n, fx.kinv_circ(n, bits)) for n in range(4, 25)])


def kinv_hyp_fn() -> str:
    return fx.sv_case_function("kinv", fx.TQ + 3, 5, [(n, fx.kinv_hyp(n, fx.TQ)) for n in range(4, 25)])


# ---- shared text --------------------------------------------------------------------------------------------------------------------------
