def e_cordic() -> str:
    return header("exp2", "exp2_cordic", "cordic", "2**x for x in [0, 1) by hyperbolic CORDIC in rotation mode, z = x ln 2", "NIT + 1",
                  "no BRAM; a constant multiplier x * ln 2 (IW x 21 bits: Vivado builds it from LUT adders or a DSP48), then NIT stages of two add/subtract with a shifted operand and one of an angle constant "
                  "(carry chains, no DSP); the repeated iterations at shifts 4 and 13 are stages like any other; the constant tables are LUT logic.") + f"""module exp2_cordic #(
    parameter int IW  = 12,
    parameter int OW  = 12,
    parameter int NIT = 16,
    parameter int G   = 5
) (
    input  logic                clk,
    input  logic [IW-1:0]       x,
    output logic [OW-1:0]       y
);
{atanh_fn()}
{hseq_fn()}
{kinv_hyp_fn()}

    localparam int DF = OW + G;
    localparam int DW = DF + 3;
    localparam int ZW = DF + 2;
    localparam logic signed [DW-1:0] X0 = DW'((kinv(5'(NIT)) + ({fx.TQ + 3}'(1) << ({fx.TQ} - DF - 1))) >> ({fx.TQ} - DF));
    localparam int LN2Q = {fx.fl(__import__('math').log(2.0), fx.CQ)};          // ln 2 with {fx.CQ} fractional bits
    // stage 0: z = x ln 2 in units of 2**-DF
    logic signed [ZW-1:0] z0_n, z0;
    logic signed [DW-1:0] x0;
    logic [{fx.CQ + 22 - 1}:0]         zp;
    assign zp   = (IW + {fx.CQ})'(x) * {fx.CQ + 1}'(LN2Q);
    assign z0_n = ZW'((zp + ({fx.CQ + 22}'(1) << (IW + {fx.CQ} - DF - 1))) >> (IW + {fx.CQ} - DF));
    always_ff @(posedge clk) z0 <= z0_n;
    assign x0 = X0;
    for (genvar k = 0; k < NIT; k++) begin : g_it
        // verilator lint_off UNUSEDSIGNAL
        logic signed [DW-1:0] xi, yi, xr, yr;       // the last stage's unused registers are dropped by synthesis
        logic signed [ZW-1:0] zi, zr;
        // verilator lint_on UNUSEDSIGNAL
        logic signed [ZW-1:0] ang;
        localparam int SHI = int'(hshift(5'(k)));
        assign ang = ZW'((atanh_q(5'(SHI)) + ({fx.TQ}'(1) << ({fx.TQ} - DF - 1))) >> ({fx.TQ} - DF));
        if (k == 0) begin : g_first
            assign xi = x0;
            assign yi = '0;
            assign zi = z0;
        end else begin : g_next
            assign xi = g_it[k-1].xr;
            assign yi = g_it[k-1].yr;
            assign zi = g_it[k-1].zr;
        end
        wire dpos = ~zi[ZW-1];
        always_ff @(posedge clk) begin
            xr <= dpos ? xi + (yi >>> SHI) : xi - (yi >>> SHI);
            yr <= dpos ? yi + (xi >>> SHI) : yi - (xi >>> SHI);
            zr <= dpos ? zi - ang : zi + ang;
        end
    end
    logic signed [DW-1:0] e, ev;
    assign e  = g_it[NIT-1].xr + g_it[NIT-1].yr - (DW'(1) <<< DF);        // e**z - 1 in units of 2**-DF
    assign ev = (e + (DW'(1) <<< (G - 1))) >>> G;
    assign y  = (ev < 0) ? '0 : (ev > DW'((1 << OW) - 1)) ? '1 : ev[OW-1:0];
endmodule
"""


