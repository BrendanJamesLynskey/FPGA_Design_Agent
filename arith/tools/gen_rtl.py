                  "one DSP48E1 (25 x 18 signed; DSP48E2 on the K26) for the slope times the position inside the segment (22 x DB bits), a 2**SB-entry coefficient ROM of two 22-bit words "
                  "(distributed RAM for SB <= 5, possibly a BRAM at SB = 6), an adder for the break-point value; stage 1 registers the ROM output (a BRAM output register), stage 2 the sum "
