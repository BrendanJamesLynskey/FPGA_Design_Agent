def sc_cordic() -> str:
    return header("sincos", "sincos_cordic", "cordic", "sine and cosine of a phase by CORDIC in rotation mode", "NIT",
                  "no DSP and no BRAM: NIT stages of two add/subtract with a shifted operand and one add/subtract of an angle constant (all in carry chains, about 3 x (OW + G + 2) LUTs and "
                  "2 x (OW + G + 2) + PH + G + 2 FFs per stage); the angle constants and the gain are constant tables (LUT logic); the quadrant map as a short conditional negation after the last stage.") + f"""module sincos_cordic #(
    parameter int PH  = 14,
    parameter int OW  = 14,
    parameter int NIT = 14,
    parameter int G   = 4
) (
{sincos_ports()}
);
{atan_turn_fn()}
{kinv_circ_fn(fx.TQ)}

    localparam int DF = OW - 1 + G;                        // fractional bits of x and y
    localparam int ZF = PH + G;                            // fractional bits of the angle z, in turns
    localparam int DW = DF + 3;                            // signed width of x and y
    localparam int ZW = ZF + 2;                            // signed width of z
    localparam int FB = OW - 1;
    localparam logic signed [DW-1:0] X0 = DW'((kinv(5'(NIT)) + ({fx.TQ + 1}'(1) << ({fx.TQ} - DF - 1))) >> ({fx.TQ} - DF));
    logic [1:0]           q;
    logic [PH-3:0]        o;
    logic signed [ZW-1:0] z0;
    assign {{q, o}} = phase;
    assign z0 = ZW'(signed'({{1'b0, o}})) <<< (ZF - PH);                // o / 2**PH turns
    for (genvar k = 0; k < NIT; k++) begin : g_it
        // verilator lint_off UNUSEDSIGNAL
        logic signed [DW-1:0] xi, yi, xr, yr;       // the last stage's unused registers are dropped by synthesis
        logic signed [ZW-1:0] zi, zr;
        // verilator lint_on UNUSEDSIGNAL
        logic [1:0]           qi, qr;
        logic signed [ZW-1:0] ang;
        assign ang = ZW'((atan_q(5'(k)) + ({fx.TQ}'(1) << ({fx.TQ} - ZF - 1))) >> ({fx.TQ} - ZF));
        if (k == 0) begin : g_first
            assign xi = X0;
            assign yi = '0;
            assign zi = z0;
            assign qi = q;
        end else begin : g_next
            assign xi = g_it[k-1].xr;
            assign yi = g_it[k-1].yr;
            assign zi = g_it[k-1].zr;
            assign qi = g_it[k-1].qr;
        end
        wire dpos = ~zi[ZW-1];                             // z >= 0: rotate by +atan(2**-k)
        always_ff @(posedge clk) begin
            xr <= dpos ? xi - (yi >>> k) : xi + (yi >>> k);
            yr <= dpos ? yi + (xi >>> k) : yi - (xi >>> k);
            zr <= dpos ? zi - ang : zi + ang;
            qr <= qi;
        end
    end
    localparam int HG = (G > 0) ? G : 1;
    logic signed [DW-1:0] xo, yo, xs, ys;
    logic [FB-1:0]        s_r, c_r;
    logic [1:0]           q_o;
    assign xo  = g_it[NIT-1].xr;
    assign yo  = g_it[NIT-1].yr;
    assign q_o = g_it[NIT-1].qr;
    assign xs  = (xo + (DW'(1) <<< (HG - 1))) >>> G;
    assign ys  = (yo + (DW'(1) <<< (HG - 1))) >>> G;
    assign s_r = (ys < 0) ? '0 : (ys > DW'((1 << FB) - 1)) ? FB'((1 << FB) - 1) : ys[FB-1:0];
    assign c_r = (xs < 0) ? '0 : (xs > DW'((1 << FB) - 1)) ? FB'((1 << FB) - 1) : xs[FB-1:0];
{QMAP}
endmodule
"""


