def header(fn, mod, variant, fn_text, latency, use) -> str:
    return (f"// {mod}: {fn_text} (arith brief 139d, variant \"{variant}\").\n"
            f"// Function and bit-exact behaviour: arith/{fn}/spec.md and arith/{fn}/model.py. Latency {latency}; one result per clock; no reset (data only).\n"
            f"//\n// Intended primitive use (stated before any Vivado run; not yet measured): {use}\n" + NOTE)


# ---- exp2 / log2: table, lerp, poly2 --------------------------------------------------------------------------------------------------------
def fn_table(fn: str) -> str:
    what = {"exp2": "2**x for x in [0, 1)", "log2": "log2 of a mantissa in [1, 2)"}[fn]
    mod = f"{fn}_table"
    return header(fn, mod, "table", f"{what}, read from a {1 << fx.DIRECT_BITS}-entry table", "REG (0 or 1)",
                  "a 256 x 20 ROM (one 36 Kb BRAM or distributed-RAM LUTs, Vivado's choice; a narrower IW uses every 2**(8-IW)-th entry), no DSP; REG = 1 puts the register at the ROM output, "
                  "which lets a BRAM absorb it (an output register, not an extra latency of the table). The rounding adder after the ROM is a short carry chain.") + f"""module {mod} #(
    parameter int IW  = 8,
    parameter int OW  = 12,
    parameter int REG = 1
) (
    // verilator lint_off UNUSEDSIGNAL
    input  logic                clk,
    // verilator lint_on UNUSEDSIGNAL
    input  logic [IW-1:0]       x,
    output logic [OW-1:0]       y
);
{rom_direct_fn(fn)}

    localparam int SH = {fx.CF} - OW;                      // fractional bits dropped by the final rounding (>= 4 for OW <= 16)
    logic [7:0]            idx;
    logic [{fx.CF - 1}:0]            r;
    logic [{fx.CF}:0]            sum;
    logic [{fx.CF}:0]            v;
    logic [OW-1:0]         y_n;
    assign idx = 8'(x) << (8 - IW);                        // entry x / 2**IW of the 256-entry table
    assign r   = rom_d(idx);
    assign sum = {{1'b0, r}} + ({fx.CF + 1}'(1) << (SH - 1));        // round to nearest, ties upward
    assign v   = sum >> SH;
    assign y_n = (v > {fx.CF + 1}'((1 << OW) - 1)) ? '1 : v[OW-1:0];
    if (REG != 0) begin : g_reg
        always_ff @(posedge clk) y <= y_n;
    end else begin : g_comb
        assign y = y_n;
    end
endmodule
"""


def engine_lerp(lanes: list[tuple[str, str]], fb: str, ib: str) -> str:
    """Stage 1 (ROM registers) and stage 2 (multiply, add, round) of one or more lanes; ``lanes`` is (name, rom tag); fb: the output fractional bits; ib: input bits."""
    L = []
    for n, t in lanes:
        L.append(f"    logic signed [21:0] c0_{n}, s1_{n};                         // stage 1 registers: the segment's break-point value and slope")
    L.append("    always_ff @(posedge clk) begin")
    L.append("        d_q <= d;")
    for n, t in lanes:
        L.append(f"        c0_{n} <= rom_c0{t}({{3'(SB), 6'(idx)}});")
        L.append(f"        s1_{n} <= rom_s1{t}({{3'(SB), 6'(idx)}});")
    L.append("    end")
    for n, t in lanes:
        L.append(f"    logic signed [DB+23:0]    prod_{n};")
        L.append(f"    logic signed [ACCW-1:0]   acc_{n}, sh_{n};")
        L.append(f"    assign prod_{n} = s1_{n} * $signed({{1'b0, d_q}});")
        L.append(f"    assign acc_{n}  = (ACCW'(c0_{n}) <<< DB) + ACCW'(prod_{n});")
        L.append(f"    assign sh_{n}   = (acc_{n} + HALF) >>> RS;")
        L.append(f"    always_ff @(posedge clk) {n}_r <= (sh_{n} < 0) ? '0 : (sh_{n} > MAXV) ? MAXV[{fb}-1:0] : sh_{n}[{fb}-1:0];")
    return "\n".join(L)


