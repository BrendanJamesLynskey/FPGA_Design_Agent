# ---- sincos -------------------------------------------------------------------------------------------------------------------------------
QMAP = """    // quadrant map of the first-quadrant values S, C (non-negative, FB bits): 0: (S, C); 1: (C, -S); 2: (-S, -C); 3: (-C, S)
    logic [OW-1:0] sp, cp;
    assign sp = {1'b0, s_r};
    assign cp = {1'b0, c_r};
    always_comb begin
        case (q_o)
            2'd0:    begin s = sp;        c = cp;        end
            2'd1:    begin s = cp;        c = OW'(-sp);  end
            2'd2:    begin s = OW'(-sp);  c = OW'(-cp);  end
            default: begin s = OW'(-cp);  c = sp;        end
        endcase
    end"""


