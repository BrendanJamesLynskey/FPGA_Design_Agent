#!/usr/bin/env python3
"""Write the out-of-context wrappers and the per-variant build.yaml files of an arithmetic function (arith brief 139a), from its spec.yaml.

    python3 -m arith.tools.gen_build [adder multiplier mac] [--check]

The wrapper arith/<fn>/ooc/<module>_ooc.sv registers every input and every output of a variant (so the timing is register to register, with no pad or
port delay) and passes the parameters through. The file arith/<fn>/build/<variant>/build.yaml is in the format flow/prepare.py reads (top, part, sources,
generics) plus the keys of an out-of-context characterisation run (flow/ipchar.tcl): ``ooc`` (clock port and target clocks per part), ``points`` (the parameter
sets to run), ``expected_primitives`` and ``status``. Nothing here runs Vivado. ``--check`` writes nothing and fails if a committed file differs."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

from arith.tools import arith_common as ac

CLOCK_NS = {"a7": 5.0, "k26": 3.0}


def width_expr(w) -> str:
    return str(w)


def wrapper_text(fn: str, variant: str, spec: dict) -> str:
    v = spec["variants"][variant]
    mod = v["module"]
    params = v["params"]
    ports = [p for p in spec["ports"] if p["name"] != "clk"]
    ins = [p for p in ports if p["dir"] == "in"]
    outs = [p for p in ports if p["dir"] == "out"]

    def rng(p):
        w = str(p["width"])
        return "" if w == "1" else f"[{w}-1:0] "

    L = [f"// {mod}_ooc: registers on every input and output of {mod} for an out-of-context run (arith brief 139a; generated by arith/tools/gen_build.py, do not edit).",
         "// The path under test is register to register; the ports of this wrapper are not timed. The parameters are passed through.",
         f"module {mod}_ooc #("]
    L.append(",\n".join(f"    parameter int {k} = {x}" for k, x in params.items()))
    L.append(") (")
    pl = ["    input  logic clk"]
    pl += [f"    input  logic {rng(p)}{p['name']}" for p in ins]
    pl += [f"    output logic {rng(p)}{p['name']}" for p in outs]
    L.append(",\n".join(pl))
    L.append(");")
    for p in ins:
        L.append(f"    logic {rng(p)}{p['name']}_q;")
    for p in outs:
        L.append(f"    logic {rng(p)}{p['name']}_w;")
    L.append("    always_ff @(posedge clk) begin")
    for p in ins:
        L.append(f"        {p['name']}_q <= {p['name']};")
    for p in outs:
        L.append(f"        {p['name']} <= {p['name']}_w;")
    L.append("    end")
    L.append(f"    {mod} #(" + ", ".join(f".{k}({k})" for k in params) + ") u_dut (")
    L.append(",\n".join(["        .clk(clk)"] + [f"        .{p['name']}({p['name']}_q)" for p in ins] + [f"        .{p['name']}({p['name']}_w)" for p in outs]))
    L.append("    );")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def build_text(fn: str, variant: str, spec: dict) -> str:
    v = spec["variants"][variant]
    y = {
        "variant": variant,
        "function": fn,
        "status": "prepared, not run: no Vivado in brief 139a; a Vivado out-of-context run reads this file (see arith/README.md, 'Running the Vivado characterisation')",
        "top": v["module"] + "_ooc",
        "part": ac.PARTS["a7"],
        "sources": [f"arith/{fn}/{v['file']}"] + [f"arith/{d}" for d in v.get("deps", [])] + [f"arith/{fn}/ooc/{v['module']}_ooc.sv"],
        "generics": dict(v["params"]),
        "ooc": {
            "clock_port": "clk",
            "parts": {k: {"part": ac.PARTS[k], "clock_ns": CLOCK_NS[k]} for k in ("a7", "k26")},
            "flow": "synth_design -mode out_of_context, opt_design, place_design, route_design, one thread (flow/ipchar.tcl); WNS at the target clock gives Fmax = 1000 / (clock_ns - WNS)",
        },
        "points": v["ooc_points"],
        "latency_clocks": v["latency"] + " (+2 for the wrapper's input and output registers)",
        "expected_primitives": v["expected_primitives"],
    }
    head = (f"# Out-of-context build of arith/{fn} variant {variant} (arith brief 139a). Generated by arith/tools/gen_build.py from spec.yaml: edit spec.yaml, not this file.\n"
            "# Format of flow/prepare.py (top, part, sources, generics) plus the out-of-context keys of flow/ipchar.tcl. `part` is the Artix-7 default; `ooc.parts` has both parts.\n")
    return head + yaml.safe_dump(y, sort_keys=False, width=200)


def outputs(fn: str) -> dict[Path, str]:
    spec = ac.load_spec(fn)
    out = {}
    for v, vd in spec["variants"].items():
        out[ac.ARITH / fn / "ooc" / f"{vd['module']}_ooc.sv"] = wrapper_text(fn, v, spec)
        out[ac.ARITH / fn / "build" / v / "build.yaml"] = build_text(fn, v, spec)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("functions", nargs="*", default=list(ac.FUNCTIONS))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    bad = 0
    for fn in a.functions:
        for p, t in outputs(fn).items():
            if a.check:
                if not p.exists() or p.read_text() != t:
                    print("out of date:", p.relative_to(ac.ROOT))
                    bad = 1
            else:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(t)
                print("wrote", p.relative_to(ac.ROOT))
    return bad


if __name__ == "__main__":
    sys.exit(main())
