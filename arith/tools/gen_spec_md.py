#!/usr/bin/env python3
"""Render arith/<function>/spec.md from spec.yaml (arith brief 139a): the prose and the tables come from one source, so the two cannot drift.

    python3 -m arith.tools.gen_spec_md [adder multiplier mac] [--check]"""
from __future__ import annotations

import argparse
import sys

from arith.tools import arith_common as ac
from arith.tools import gen_surface as gs


def render(fn: str) -> str:
    s = ac.load_spec(fn)
    L = [f"# {s['title']} (arith/{fn})", "",
         f"Generated by `python -m arith.tools.gen_spec_md` from [spec.yaml](spec.yaml); edit the YAML, not this file. Part of {"the frequency-domain suite" if fn in ac.FFT_FUNCTIONS else "the arithmetic library"} of brief {ac.brief_of(fn)} ([../README.md](../README.md)).", "",
         s["summary"], "", "## Function", ""]
    L += [f"- {x}" for x in s["semantics"]]
    L += ["", f"Signedness: {s['signedness']}.", "", f"Exactness: {s['exactness']}.", "", f"Latency: {s['latency_definition']}."]
    if s.get("accuracy"):
        L += ["", "## Accuracy", "", s["accuracy"], "", "| Variant | Parameters | Error bound (last places) |", "|---|---|---|"]
        for v, vd in s["variants"].items():
            for pt in vd["accuracy_points"]:
                L.append(f"| `{v}` | " + ", ".join(f"{k} = {x}" for k, x in pt["params"].items()) + " | " + ", ".join(f"{k}: {x}" for k, x in pt["bound_ulp"].items()) + " |")
    L += ["", "## Ports", "",
          "| Port | Direction | Width | Meaning |", "|---|---|---|---|"]
    L += [f"| `{p['name']}` | {p['dir']} | {p['width']} | {p['text']} |" for p in s["ports"]]
    L += ["", "## Parameters", "", "| Parameter | Constraint | Meaning |", "|---|---|---|"]
    for k, v in s["parameters"].items():
        c = (f"{v['min']} to {v['max']}" if "max" in v else f"min {v['min']}") if "min" in v else f"one of {v['values']}"
        L.append(f"| `{k}` | {c} | {v['text']} |")
    L += ["", "## Variants", "",
          "Each variant is one SystemVerilog file under `rtl/`, with the same ports. Parameters of the variant beyond the ones above are in its header. "
          "The primitive use is what the code is written to infer; it was stated BEFORE any Vivado run and is not a measurement.", "",
          "| Variant | Module | Latency (clocks) | Trade-off |", "|---|---|---|---|"]
    for v, vd in s["variants"].items():
        L.append(f"| `{v}` | `{vd['module']}` ([{vd['file']}]({vd['file']})) | `{vd['latency']}` | {vd['tradeoff']} |")
    L += ["", "### Intended primitive use", ""]
    for v, vd in s["variants"].items():
        L.append(f"- `{v}`, Artix-7 (xc7a100t): {vd['expected_primitives']['a7']}")
        L.append(f"  - K26 (xck26): {vd['expected_primitives']['k26']}")
    c = s["contract"]
    L += ["", "## Interface contract", "",
          f"Written without knowing the design the block will sit in (brief {ac.brief_of(fn)}, owner decision 24): this is what a user can rely on and must provide.", "",
          f"- Protocol: {c['protocol']}", f"- Throughput: {c['throughput']}", f"- Latency: {c['latency']}", f"- Reset: {c['reset']}", f"- Clock: {c['clock']}", f"- Stalls: {c['stall']}",
          "", "| Variant | Latency (clocks) | Throughput |", "|---|---|---|"]
    L += [f"| `{v}` | `{vd['latency']}` | {vd['throughput']} |" for v, vd in s["variants"].items()]
    L += ["", "## Integration", "", f"- Port timing: {s['integration']['port_timing']}", f"- Constraints to carry: {s['integration']['constraints']}",
          ("- Verification after integration: this function has no packaged harness (brief 148 left it out; see the report): rerun its bench (tests/) against your instance, which needs the repository's arith/tools and fft_common helpers." if fn in ac.FFT_FUNCTIONS and fn not in ac.HARNESS_FFT_FUNCTIONS
           else "- Verification after integration: rerun the packaged harness against your instance ([harness/README.md](harness/README.md)); it needs no other file of this repository."),
          "", "## What a user could guess wrong", ""]
    L += [f"- {g}" for g in s["guess_wrong"]]
    if s.get("lean_note"):
        L += ["", "## Lean, and what is research", "", s["lean_note"]]
    L += gs.measured_section(fn)
    L += ["", "## Files", "",
          "- [model.py](model.py): the bit-exact model; tests/test_*_model.py check it against independent formulations",
          *([] if fn in ac.FFT_FUNCTIONS and fn not in ac.HARNESS_FFT_FUNCTIONS else ["- [harness/](harness/): the packaged verification harness a user reruns against their own instance (model, bench, SystemVerilog checker, coverage targets, standalone runner)"]),
          "- [tests/](tests/): the cocotb bench, exhaustive and random points, mutation and formal tests; [verif/testplan.yaml](verif/testplan.yaml) names each",
          "- [verif/mutants.yaml](verif/mutants.yaml), [formal/jobs.yaml](formal/jobs.yaml): the seeded faults and the formal jobs; results in [verif/results/](verif/results/)",
          "- [build/](build/): one `build.yaml` per variant for an out-of-context Vivado run on Artix-7 and K26 (" + (f"prepared in brief {ac.brief_of(fn)}, run in brief 160" if fn in gs.FN_ORDER else "prepared, not run") + "); [ooc/](ooc/): the generated register wrappers",
          *([] if fn in ac.FFT_FUNCTIONS else ["- [../../formal/lean/Arith/](../../formal/lean/Arith/): Lean statements (not approved by a human)"]), ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("functions", nargs="*", default=list(ac.ALL_FUNCTIONS))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    bad = 0
    for fn in a.functions:
        p = ac.ARITH / fn / "spec.md"
        t = render(fn)
        if a.check:
            if not p.exists() or p.read_text() != t:
                print("out of date:", p.relative_to(ac.ROOT))
                bad = 1
        else:
            p.write_text(t)
            print("wrote", p.relative_to(ac.ROOT))
    return bad


if __name__ == "__main__":
    sys.exit(main())
