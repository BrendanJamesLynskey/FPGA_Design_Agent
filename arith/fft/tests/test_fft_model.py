"""The FFT models against NumPy's FFT, the identities the contract states and pinned conventions (arith brief 148)."""
from __future__ import annotations

import random

import numpy as np
import pytest

from arith.fft import model
from arith.fft_common import fft_ref as f

PARAMS = dict(TW=18, SCALE=1, RND=1, ORDER=0)


def rand_frame(n, w, rng, frac=0.65):
    a = int(frac * (1 << (w - 1)))
    return [(rng.randrange(-a, a), rng.randrange(-a, a)) for _ in range(n)]


@pytest.mark.parametrize("variant", ["sdf", "burst"])
@pytest.mark.parametrize("logn", [3, 4, 5, 6, 7, 8, 10])
def test_against_numpy_scaled_and_unscaled(variant, logn):
    rng = random.Random(logn)
    n = 1 << logn
    x = rand_frame(n, 16, rng)
    xc = np.array([a + 1j * b for a, b in x])
    for scale in (1, 0):
        for inverse in (0, 1):
            p = dict(PARAMS, SCALE=scale)
            y = np.array([a + 1j * b for a, b in model.frame(variant, p, x, inverse)])
            ref = (np.fft.ifft(xc) * n if inverse else np.fft.fft(xc)) / (n if scale else 1)
            err = np.max(np.abs(y - ref))
            assert err < (5.0 if scale else 2 * 2 ** (logn / 2) + 4), (variant, logn, scale, inverse, err)


@pytest.mark.parametrize("variant", ["sdf", "burst"])
def test_bit_reversed_order_is_the_natural_order_permuted(variant):
    rng = random.Random(3)
    x = rand_frame(64, 16, rng)
    nat = model.frame(variant, dict(PARAMS, ORDER=0), x, 0)
    br = model.frame(variant, dict(PARAMS, ORDER=1), x, 0)
    assert br == [nat[f.bitrev(p, 6)] for p in range(64)]


@pytest.mark.parametrize("variant", ["sdf", "burst"])
def test_inverse_is_the_swap_of_a_forward_transform(variant):
    rng = random.Random(4)
    x = rand_frame(32, 16, rng)
    xs = [(b, a) for a, b in x]
    fwd = model.frame(variant, PARAMS, xs, 0)
    assert model.frame(variant, PARAMS, x, 1) == [(b, a) for a, b in fwd]


@pytest.mark.parametrize("variant", ["sdf", "burst"])
def test_impulse_gives_a_over_n_with_scaling_and_a_without(variant):
    n, a = 64, 4000
    x = [(a, 0)] + [(0, 0)] * (n - 1)
    ys = model.frame(variant, dict(PARAMS, SCALE=1), x, 0)
    yu = model.frame(variant, dict(PARAMS, SCALE=0), x, 0)
    assert all(abs(re - a / n) <= 1.5 and abs(im) <= 1.5 for re, im in ys)       # 4000 / 64 = 62.5
    assert all(abs(re - a) <= 2 and abs(im) <= 2 for re, im in yu)


@pytest.mark.parametrize("variant", ["sdf", "burst"])
def test_round_trip_returns_the_input(variant):
    rng = random.Random(5)
    for logn in (4, 7):
        n = 1 << logn
        x = rand_frame(n, 16, rng)
        # scaled: forward (1/N) then inverse (1/N) gives x / N; unscaled: forward then inverse gives N * x
        p = dict(PARAMS, SCALE=0, W=16)
        y = model.frame(variant, p, x, 0)
        z = model.frame(variant, p, y, 1)       # exact up to rounding: n * x
        assert max(max(abs(a - n * c), abs(b - n * d)) for (a, b), (c, d) in zip(z, x)) < 40 * n ** 0.5, logn


def test_real_input_arrangement_against_numpy_rfft():
    rng = random.Random(6)
    for variant in ("sdf", "burst"):
        for logn in (4, 6, 8):
            n = 1 << logn
            xr = [rng.randrange(-20000, 20000) for _ in range(n)]
            for scale in (1, 0):
                y = np.array([a + 1j * b for a, b in f.real_frame(variant, xr, 18, scale, 1)])
                ref = np.fft.rfft(xr) / (n if scale else 1)
                assert len(y) == n // 2 + 1
                assert np.max(np.abs(y - ref)) < (4 if scale else 8 + n / 16), (variant, logn, scale)


def test_the_twiddle_pattern_of_the_radix_2_squared_pipeline_equals_the_burst_flow_up_to_rounding():
    # the two architectures compute the same transform: they differ only by rounding
    rng = random.Random(8)
    x = rand_frame(256, 16, rng)
    a = np.array([p + 1j * q for p, q in model.frame("sdf", PARAMS, x, 0)])
    b = np.array([p + 1j * q for p, q in model.frame("burst", PARAMS, x, 0)])
    assert np.max(np.abs(a - b)) < 8


def test_the_recorded_accuracy_is_what_the_models_give_today(tmp_path):
    """verif/results/accuracy.json is regenerated by arith/tools/fft_accuracy.py; the test reruns it and compares every number (the date is not compared)."""
    import json
    import subprocess
    import sys

    from arith.tools import arith_common as ac
    out = tmp_path / "accuracy.json"
    r = subprocess.run([sys.executable, "-m", "arith.tools.fft_accuracy", "--out", str(out)], cwd=ac.ROOT, capture_output=True, text=True)
    assert r.returncode == 0, r.stderr[-400:]
    now = json.loads(out.read_text())
    rec = json.loads((ac.ARITH / "fft" / "verif" / "results" / "accuracy.json").read_text())
    now.pop("date"), rec.pop("date")
    assert now == rec, "arith/fft/verif/results/accuracy.json is out of date: run python -m arith.tools.fft_accuracy"
