// fft_window_dsp: window multiplier, one real coefficient for both parts of a complex sample (arith brief 148, variant "dsp").
//
// Function (arith/fft_window/spec.md): yr = round(xr * w / 2**WW) and yi = round(xi * w / 2**WW), where xr and xi are WD-bit signed samples and w is a WW-bit UNSIGNED window
// coefficient of value w / 2**WW (so the largest coefficient is 1 - 2**-WW; exactly 1.0 is not representable, a stated convention). RND = 1 rounds half up, RND = 0 truncates
// (floors). The result has the width of the input and cannot overflow (the coefficient is below 1). STAGES register ranks (0 to 3): rank 1 after the output, rank 2 also
// before the multipliers, rank 3 also after the products. No reset: data only. The coefficient comes from the caller (a ROM generated by arith/fft_common/fft_ref.py's
// window functions, or a counter-addressed table of the caller's); it must be presented with its sample.
//
// Intended primitive use (stated before any Vivado run; not yet measured): two WD x (WW+1) signed multipliers (the unsigned coefficient gets a zero sign bit), so 2 DSP48E1
// (7 series, 25 x 18) for WD <= 25, WW <= 17, or 2 DSP48E2 (27 x 18); the rounding constant is absorbed in the DSP post-adder at STAGES 3; about WD LUTs otherwise.
module fft_window_dsp #(
    parameter int WD     = 16,
    parameter int WW     = 16,
    parameter int RND    = 1,
    parameter int STAGES = 3
) (
    // verilator lint_off UNUSEDSIGNAL
    input  logic            clk,
    // verilator lint_on UNUSEDSIGNAL
    input  logic [WD-1:0]   xr,
    input  logic [WD-1:0]   xi,
    input  logic [WW-1:0]   w,
    output logic [WD-1:0]   yr,
    output logic [WD-1:0]   yi
);
    logic signed [WD-1:0] xr1, xi1, xr2, xi2, ar, ai;
    logic [WW-1:0]        w2, wu;
    logic signed [WW:0]   ws;
    always_ff @(posedge clk) begin
        xr2 <= xr; xi2 <= xi; w2 <= w;
    end
    always_comb begin
        xr1 = xr; xi1 = xi;
        ar = (STAGES >= 2) ? xr2 : xr1;
        ai = (STAGES >= 2) ? xi2 : xi1;
        wu = (STAGES >= 2) ? w2 : w;
        ws = {1'b0, wu};
    end
    (* use_dsp = "yes" *) logic signed [WD+WW:0] pr, pi;
    logic signed [WD+WW:0] qr, qi;
    always_ff @(posedge clk) begin
        qr <= pr; qi <= pi;
    end
    always_comb begin
        pr = ar * ws;
        pi = ai * ws;
    end
    logic signed [WD+WW:0] tr, ti, sr, si;
    logic [WD-1:0] rr, ri;
    always_comb begin
        tr = (STAGES >= 3) ? qr : pr;
        ti = (STAGES >= 3) ? qi : pi;
        sr = (RND != 0) ? tr + (WD + WW + 1)'(1 << (WW - 1)) : tr;
        si = (RND != 0) ? ti + (WD + WW + 1)'(1 << (WW - 1)) : ti;
        rr = WD'(sr >>> WW);
        ri = WD'(si >>> WW);
    end
    logic [WD-1:0] yr_q, yi_q;
    always_ff @(posedge clk) begin
        yr_q <= rr; yi_q <= ri;
    end
    always_comb begin
        yr = (STAGES >= 1) ? yr_q : rr;
        yi = (STAGES >= 1) ? yi_q : ri;
    end
endmodule
