    assign q_s  = 24'(a1_s) + 24'(m1_s >>> DB);
    logic signed [DB+22:0]  m1_c;                              // a2 * d
    logic signed [23:0]     q_c, q_c_r;                       // stage 2: a1 + (a2 d) >> DB
    logic signed [21:0]     a0_c_r;
    assign m1_c = a2_c * $signed({1'b0, d_q});
    assign q_c  = 24'(a1_c) + 24'(m1_c >>> DB);
    always_ff @(posedge clk) begin
        d_r <= d_q;
        q_s_r  <= q_s;
        a0_s_r <= a0_s;
        q_c_r  <= q_c;
        a0_c_r <= a0_c;
    end
    logic signed [DB+24:0]   m2_s;
    logic signed [ACCW-1:0]  acc_s, sh_s;
    assign m2_s  = q_s_r * $signed({1'b0, d_r});
    assign acc_s = (ACCW'(a0_s_r) <<< DB) + ACCW'(m2_s);
    assign sh_s  = (acc_s + HALF) >>> RS;
    always_ff @(posedge clk) s_r <= (sh_s < 0) ? '0 : (sh_s > MAXV) ? MAXV[FB-1:0] : sh_s[FB-1:0];
    logic signed [DB+24:0]   m2_c;
    logic signed [ACCW-1:0]  acc_c, sh_c;
    assign m2_c  = q_c_r * $signed({1'b0, d_r});
    assign acc_c = (ACCW'(a0_c_r) <<< DB) + ACCW'(m2_c);
    assign sh_c  = (acc_c + HALF) >>> RS;
    always_ff @(posedge clk) c_r <= (sh_c < 0) ? '0 : (sh_c > MAXV) ? MAXV[FB-1:0] : sh_c[FB-1:0];
    always_ff @(posedge clk) begin
        q_1 <= q;
        q_2 <= q_1;
        q_o <= q_2;
    end
    // quadrant map of the first-quadrant values S, C (non-negative, FB bits): 0: (S, C); 1: (C, -S); 2: (-S, -C); 3: (-C, S)
    logic [OW-1:0] sp, cp;
    assign sp = {1'b0, s_r};
    assign cp = {1'b0, c_r};
    always_comb begin
        case (q_o)
            2'd0:    begin s = sp;        c = cp;        end
            2'd1:    begin s = cp;        c = OW'(-sp);  end
            2'd2:    begin s = OW'(-sp);  c = OW'(-cp);  end
            default: begin s = OW'(-cp);  c = sp;        end
        endcase
    end
endmodule
