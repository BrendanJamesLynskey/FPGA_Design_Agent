"""The block-floating-point model against NumPy's FFT, brute-force exponents and the identities the contract states (arith brief 161)."""
from __future__ import annotations

import random

import numpy as np
import pytest

from arith.fft_bfp import model
from arith.fft_common import fft_ref as f

P = dict(TW=18, W=16, RND=1, ORDER=0)


def noise(n, w, rng, amp):
    return [(rng.randrange(-amp, amp + 1), rng.randrange(-amp, amp + 1)) for _ in range(n)]


def brute_exponent(words, wo):
    """The smallest s such that every part, shifted right by s (exactly, as a rational) lies in [-2**(wo-1), 2**(wo-1))."""
    s = -wo
    while True:
        lim = 1 << (wo - 1)
        if all(-lim * (1 << max(s, 0)) <= (a << max(-s, 0)) < lim * (1 << max(s, 0)) and -lim * (1 << max(s, 0)) <= (b << max(-s, 0)) < lim * (1 << max(s, 0)) for a, b in words):
            return s
        s += 1


@pytest.mark.parametrize("seed", range(40))
def test_exponent_rule_equals_brute_force(seed):
    rng = random.Random(seed)
    wo = rng.choice((4, 8, 16))
    amp = rng.choice((0, 1, 3, 40, 1000, 1 << 20, 1 << 27))
    words = [(rng.randrange(-amp, amp + 1), rng.randrange(-amp, amp + 1)) for _ in range(rng.choice((1, 4, 16)))]
    if seed % 5 == 0 and words:
        words[0] = (-(1 << rng.randrange(0, 26)), 0)                  # a negative power of two: it needs one bit fewer than the positive one
    if any(a or b for a, b in words):                                 # an all-zero frame has no smallest shift: the rule pins it at 1 - wo (test_extreme_frames)
        assert f.bfp_exponent(words, wo) == brute_exponent(words, wo)


def test_extreme_frames():
    assert f.bfp_exponent([(0, 0)] * 8, 16) == 1 - 16
    assert f.bfp_exponent([(-(1 << 15), 0)], 16) == 0                  # fits 16 bits exactly, no shift
    assert f.bfp_exponent([(1 << 15, 0)], 16) == 1                    # 2**15 needs 17 bits
    out, s = f.bfp_normalise([(1, 0), (0, -1)], 16, 1)
    assert s == -14 and out == [(1 << 14, 0), (0, -(1 << 14))]          # a small frame is shifted LEFT, exactly


def test_rounding_carry_saturates():
    out, s = f.bfp_normalise([((1 << 15) - 1 + 0, 0), (0, 0)], 8, 1)             # 32767 in 8 bits: s = 8 so 32767 / 256 = 127.99 -> rounds to 128 -> saturated to 127
    assert s == 8 and out[0] == (127, 0)
    out, s = f.bfp_normalise([((1 << 15) - 1, 0)], 8, 0)
    assert out[0] == (127, 0)
    out, s = f.bfp_normalise([(-(1 << 15), 0)], 8, 1)
    assert out[0] == (-128, 0) and s == 8


@pytest.mark.parametrize("variant", ["sdf", "burst"])
@pytest.mark.parametrize("logn", [3, 5, 8, 10])
@pytest.mark.parametrize("amp", [3, 300, 20000])
def test_value_times_two_to_the_exponent_is_the_transform_within_the_stated_bound(variant, logn, amp):
    rng = random.Random(logn * 7 + amp)
    n = 1 << logn
    x = noise(n, 16, rng, amp)
    xc = np.array([a + 1j * b for a, b in x])
    for inverse in (0, 1):
        core = f.fft_frame(variant, x, 18, 0, 1, inverse, 1)
        cc = np.array([a + 1j * b for a, b in core])
        ref = (np.fft.ifft(xc) * n) if inverse else np.fft.fft(xc)
        e_core = float(np.max(np.maximum(np.abs((cc - ref).real), np.abs((cc - ref).imag))))
        out = model.frame(variant, dict(P, ORDER=0), x, inverse)
        s = out[0][2]
        assert all(w[2] == s for w in out)
        y = np.array([(a + 1j * b) * 2.0 ** s for a, b, _ in out])
        e = float(np.max(np.maximum(np.abs((y - ref).real), np.abs((y - ref).imag))))
        assert e <= e_core + 2.0 ** s, (variant, logn, amp, inverse, e, e_core, s)
        if s > 1 - 16:                                                  # not an all-zero frame: the largest part uses all but one bit of the word
            assert max(max(abs(a), abs(b)) for a, b, _ in out) >= (1 << 14) - 1


@pytest.mark.parametrize("variant", ["sdf", "burst"])
def test_order_is_the_permutation_and_the_exponent_does_not_depend_on_it(variant):
    rng = random.Random(5)
    x = noise(64, 16, rng, 2000)
    nat = model.frame(variant, dict(P, ORDER=0), x, 0)
    br = model.frame(variant, dict(P, ORDER=1), x, 0)
    assert [br[p] for p in range(64)] == [nat[f.bitrev(p, 6)] for p in range(64)]


@pytest.mark.parametrize("variant", ["sdf", "burst"])
def test_inverse_is_the_swap_of_a_forward_transform(variant):
    rng = random.Random(6)
    x = noise(32, 16, rng, 5000)
    inv = model.frame(variant, dict(P, ORDER=0), x, 1)
    fwd = model.frame(variant, dict(P, ORDER=0), [(b, a) for a, b in x], 0)
    assert inv == [(b, a, s) for a, b, s in fwd]


def test_the_recorded_accuracy_is_what_the_models_give_today(tmp_path):
    """verif/results/accuracy.json is regenerated by arith/tools/fft_bfp_accuracy.py; the test reruns it and compares every number (the date is not compared), and states the bounds the record supports."""
    import json
    import subprocess
    import sys

    from arith.tools import arith_common as ac
    out = tmp_path / "accuracy.json"
    r = subprocess.run([sys.executable, "-m", "arith.tools.fft_bfp_accuracy", "--out", str(out)], cwd=ac.ROOT, capture_output=True, text=True)
    assert r.returncode == 0, r.stderr[-400:]
    now = json.loads(out.read_text())
    rec = json.loads((ac.ARITH / "fft_bfp" / "verif" / "results" / "accuracy.json").read_text())
    now.pop("date"), rec.pop("date")
    assert now == rec, "arith/fft_bfp/verif/results/accuracy.json is out of date: run python -m arith.tools.fft_bfp_accuracy"
    assert rec["all_within_bound"] and rec["points"] == 80
    assert rec["bfp_worst_lsb_max_full_level"] <= 2.0 and rec["bfp_sqnr_db_min_full_level"] >= 80.0 and rec["bfp_sqnr_db_min_minus60"] >= 30.0
