"""The `axi_profile` check (brief 73): does every generated AXI4-Lite register block have the interface profile its design
declares, and does it behave as that profile says?

A design chooses a profile once in spec.yaml (`interfaces: {axi_lite_profile: house|amd_compatible|strict, blocks:
{<map name>: {profile:, <setting>:}}, amd_ip_acknowledged: [...]}`; hwsw/regmap.py, docs/hwsw.md). A block claims one in
its generated RTL (`// PROFILE` and `// SETTINGS` lines). The check does not trust the claim: it finds the block's source
map, resolves the profile the way the generator does (the map's own settings, its own profile, the design's block entry,
the design's profile, house), regenerates the RTL, and compares it with the file text. So a block cannot say `strict` and
behave as `house` (the RTL differs from what its map generates under `strict`: AXI-PROFILE-DRIFT), a map cannot claim a
profile its design did not choose (AXI-PROFILE-MISMATCH), and an edited claim line is caught the same way.

It also reports (advice, not a failure) a design that mixes profiles without declaring the block, a block generated before
profiles existed, a block whose source map it cannot find, and AMD IP (brief 69's measured list) in a design that has a
`strict` block or region, unless the design lists the IP under `amd_ip_acknowledged`.

What it does not do: it does not read hand-written register blocks (their conventions are in their ip.yaml, docs/hwsw.md)
or AMD IP's real configuration, and it cannot see a bus interconnect that sits between a strict master and an AMD slave:
the AMD IP rule is by presence in the design.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import yaml

BANNER = re.compile(r"^// Generated by hwsw/regmap\.py \(regmap/1\) from regmap (\w+) (\S+); model sha256 ([0-9a-f]{64})\.", re.M)
BANNER_ANY = re.compile(r"Generated by hwsw/regmap\.py.*?from regmap (\w+)", re.S)
PROFILE = re.compile(r"^[ \t]*// PROFILE[ \t]+(\w+)[ \t]*$", re.M)
SETTINGS = re.compile(r"^[ \t]*// SETTINGS[ \t]+(.*?)[ \t]*$", re.M)
CODES = ("AXI-PROFILE-SPEC", "AXI-PROFILE-MISMATCH", "AXI-PROFILE-DRIFT", "AXI-PROFILE-MIX", "AXI-PROFILE-STALE",
         "AXI-PROFILE-NOSRC", "AXI-PROFILE-OVERRIDE", "AXI-PROFILE-AMD-STRICT")


def _yaml(p: Path) -> Any:
    try:
        return yaml.safe_load(p.read_text())
    except (OSError, yaml.YAMLError):
        return None


def interfaces(design: Path) -> tuple[dict | None, str]:
    """The design's `interfaces:` section and the file it came from (spec.yaml, else build.yaml)."""
    for n in ("spec.yaml", "build.yaml"):
        d = _yaml(design / n)
        if d is None and (design / n).is_file() and (design / n).read_text().strip():
            return {"__unparseable__": True}, n
        if isinstance(d, dict) and "interfaces" in d and (isinstance(d["interfaces"], dict) or n == "spec.yaml"):
            return d["interfaces"], n
    return None, ""


def generated_blocks(design: Path, root: Path) -> list[Path]:
    """Generated register blocks of the design: its own tree (not build/) and the build's source list."""
    from flow.checks import build_sources
    out = {p.resolve() for p in design.rglob("*") if p.suffix in (".sv", ".v") and "build" not in p.relative_to(design).parts}
    out |= {p.resolve() for p in build_sources(design, root) if p.suffix in (".sv", ".v")}
    keep = []
    for p in sorted(out):
        try:
            text = p.read_text(errors="replace")
        except OSError:
            continue
        # a block is claimed by its banner, or by a PROFILE/SETTINGS line, wherever it sits and whatever the file is called
        if BANNER_ANY.search(text) or PROFILE.search(text):
            keep.append(p)
    return keep


def find_source(name: str, sv: Path, design: Path, root: Path) -> Path | None:
    """The regmap YAML whose `name:` is `name`: beside the block, in the design, in the repo's example maps."""
    where = [sv.parent, sv.parent.parent, design, root / "hwsw" / "examples", root / "hwsw" / "tests" / "data"]
    seen: set[Path] = set()
    for w in where:
        if not w.is_dir():
            continue
        it = w.rglob("*.yaml") if w == design else w.glob("*.yaml")
        for y in sorted(it):
            if y in seen or "build" in y.relative_to(w).parts:
                continue
            seen.add(y)
            d = _yaml(y)
            if isinstance(d, dict) and d.get("regmap") == 1 and d.get("name") == name:
                return y
    return None


def _f(code: str, where: str, message: str, blocking: bool, key: str = "") -> dict[str, Any]:
    return {"tool": "axi_profile", "code": code, "severity": "error" if blocking else "warning", "where": where,
            "key": f"axi_profile:{code} {key or where}", "message": message[:400], "blocking": blocking}


def run_checks(design: Path, root: Path) -> list[dict[str, Any]]:
    from hwsw import regmap
    ifs, src = interfaces(design)
    fs: list[dict[str, Any]] = []
    if isinstance(ifs, dict) and ifs.get("__unparseable__"):
        fs.append(_f("AXI-PROFILE-SPEC", src, f"{src} is not valid YAML, so the design's interfaces: cannot be read", True))
        ifs = None
    errs = regmap.interfaces_errors(ifs)
    for e in errs:
        fs.append(_f("AXI-PROFILE-SPEC", f"{src or 'spec.yaml'} interfaces", f"interfaces: {e}", True, e))
    ifs_ok = ifs if not errs and isinstance(ifs, dict) else None
    design_profile = (ifs_ok or {}).get("axi_lite_profile")
    declared_blocks = (ifs_ok or {}).get("blocks") or {}
    spec = design / src if (ifs_ok is not None and src) else None     # spec.yaml, or build.yaml when that holds interfaces:
    seen: dict[str, str] = {}
    for sv in generated_blocks(design, root):
        rel = _rel(sv, root)
        text = sv.read_text(errors="replace")
        mb = BANNER_ANY.search(text)
        pc, sc = PROFILE.search(text), SETTINGS.search(text)
        if not mb:
            fs.append(_f("AXI-PROFILE-DRIFT", rel, "carries a PROFILE line but not the generator's banner: a generated block "
                         "keeps its banner; regenerate it with python3 -m hwsw.regmap gen", True))
            continue
        name = mb.group(1)
        if not pc:
            fs.append(_f("AXI-PROFILE-STALE", rel, f"{name}: no PROFILE line (generated before interface profiles existed, or the "
                         "line was removed): regenerate it with python3 -m hwsw.regmap gen so that it states its profile and "
                         "settings; it is not compared until then", True))
            continue
        claim = (pc.group(1), (sc.group(1).strip() if sc else ""))
        y = find_source(name, sv, design, root)
        if y is None:
            fs.append(_f("AXI-PROFILE-NOSRC", rel, f"{name}: no source map (regmap YAML with name: {name}) found in the design or "
                         f"hwsw/examples, so its claim ({claim[0]}) cannot be checked against a regeneration: keep the map with "
                         "the design", True))
            seen[name] = claim[0]
            continue
        try:
            m = regmap.load(y, spec=spec)
        except regmap.RegmapError as ex:
            fs.append(_f("AXI-PROFILE-SPEC", _rel(y, root), f"{name}: its map does not load: {str(ex).splitlines()[-1]}", True, name))
            continue
        seen[name] = m.profile
        want = (m.profile, regmap.settings_text(m))
        if claim != want:
            fs.append(_f("AXI-PROFILE-MISMATCH", rel,
                         f"{name}: the RTL says profile {claim[0]} ({claim[1] or 'no settings line'}); its map {_rel(y, root)} "
                         f"under this design's interfaces resolves to {want[0]} ({want[1]}). Regenerate the block, or change "
                         "the map or interfaces: so that they agree", True, name))
        elif text != regmap.emit_sv(m):
            fs.append(_f("AXI-PROFILE-DRIFT", rel,
                         f"{name}: the RTL claims profile {claim[0]} but is not what {_rel(y, root)} generates under it (edited "
                         "by hand, or generated from an older map or generator): regenerate it with python3 -m hwsw.regmap gen", True, name))
        decl_entry = declared_blocks.get(name) or {}
        decl = decl_entry.get("profile")
        if decl and decl != m.profile:
            fs.append(_f("AXI-PROFILE-MISMATCH", _rel(y, root),
                         f"{name}: the design's interfaces.blocks.{name} chooses {decl} but its map names its own profile "
                         f"{m.profile}, which wins: make them agree (drop the map's profile: key to take the design's)", True, name))
        if m.profile != (design_profile or "house") and not decl:
            fs.append(_f("AXI-PROFILE-MIX", rel,
                         f"{name} follows profile {m.profile} but the design's profile is {design_profile or 'house (none chosen)'}"
                         f" and interfaces.blocks does not name {name}: say so under interfaces.blocks.{name}.profile",
                         design_profile is not None, name))
        # a setting the block has that its profile (plus the design's declared block settings) does not give it
        expect = {**regmap.PROFILES[m.profile], **{k: v for k, v in decl_entry.items() if k != "profile"}}
        for k, v in regmap.settings(m).items():
            if v != expect[k]:
                fs.append(_f("AXI-PROFILE-OVERRIDE", rel,
                             f"{name}: {k} = {v} but profile {m.profile} (with the design's interfaces.blocks.{name}) gives "
                             f"{expect[k]}: the map overrides it, or the design's entry was not applied (a map that names its own "
                             f"profile ignores the design's block settings); declare it as interfaces.blocks.{name}.{k}: {v} "
                             "with no profile: key in the map, or remove the override", True, f"{name}.{k}"))
    for n in sorted(set(declared_blocks) - set(seen)):
        fs.append(_f("AXI-PROFILE-SPEC", f"{src} interfaces.blocks.{n}", f"interfaces.blocks.{n}: no generated register block "
                     f"of a map named {n} in this design (a typo, or the block was not generated): the entry applies to nothing",
                     True, n))
    strict = design_profile == "strict" or "strict" in seen.values()
    if strict:
        from flow import amd_ip_notes as N
        ack = set((ifs_ok or {}).get("amd_ip_acknowledged") or [])
        for n, info in sorted(N.scan([design]).get("ips", {}).items()):
            if n not in ack:
                fs.append(_f("AXI-PROFILE-AMD-STRICT", ", ".join(_rel(Path(x), root) for x in info.get("files", [])[:2]) or n,
                             f"{info['ip']} is in a design with a strict AXI4-Lite profile: it answers holes with OKAY and read 0, "
                             "ignores byte strobes and accepts unaligned addresses (measured, brief 69), so a strict driver's "
                             f"expectations do not hold for it. List {n} under interfaces.amd_ip_acknowledged once the driver "
                             "allows for that", False, n))
    return fs


def _rel(p: Path, root: Path) -> str:
    try:
        return p.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return str(p)


def applies(design: Path, root: Path) -> str | None:
    ifs, _ = interfaces(design)
    if ifs is not None or generated_blocks(design, root):
        return None
    return "no generated AXI4-Lite register blocks and no interfaces: section in spec.yaml"
