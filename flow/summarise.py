#!/usr/bin/env python3
"""Collect a design's build results (gates.json + run.json per variant) into results/<milestone>/.

    python3 flow/summarise.py designs/t1_dimmer_counter --out results/f0a

Writes ``<design>_<variant>.json`` for each variant built and ``<design>.md``, a
table of the gates, timing, utilisation, power, run time and memory, with the
ILA's resource cost (ila - base) when both variants exist. Every number in the
markdown comes from those JSON files.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def collect(design: Path, variant: str) -> dict | None:
    d = design / "build" / variant
    if not (d / "gates.json").exists() or not (d / "run.json").exists():
        return None
    g = json.loads((d / "gates.json").read_text())
    r = json.loads((d / "run.json").read_text())
    g["build_dir"] = str(d.relative_to(ROOT))
    return {"design": str(design.relative_to(ROOT)), "variant": variant, "gates": g, "run": r}


def fmt(v: object) -> str:
    return "-" if v is None else str(v)


def markdown(name: str, res: dict[str, dict]) -> str:
    vs = list(res)
    L = [f"# {name}: build results", "",
         "Generated by `flow/summarise.py` from the JSON files next to this one; built locally with "
         f"Vivado {res[vs[0]]['run']['vivado_version']} on the 16 GB build PC (single thread, 6 GB cap).", "",
         "| | " + " | ".join(vs) + " |", "|---|" + "---|" * len(vs)]

    def row(label: str, f) -> None:
        L.append(f"| {label} | " + " | ".join(fmt(f(res[v])) for v in vs) + " |")

    row("all gates", lambda x: "PASS" if x["gates"]["pass"] else "FAIL")
    for gname in res[vs[-1]]["gates"]["gates"]:
        row(f"gate: {gname}", lambda x, g=gname: {True: "pass", False: "FAIL"}.get(x["gates"]["gates"].get(g)))
    row("setup WNS (ns)", lambda x: x["gates"]["timing"]["wns_ns"])
    row("setup TNS (ns)", lambda x: x["gates"]["timing"]["tns_ns"])
    row("hold WHS (ns)", lambda x: x["gates"]["timing"]["whs_ns"])
    row("hold THS (ns)", lambda x: x["gates"]["timing"]["ths_ns"])
    row("pulse width WPWS (ns)", lambda x: x["gates"]["timing"]["wpws_ns"])
    row("timing endpoints (setup)", lambda x: x["gates"]["timing"]["tns_total_endpoints"])
    for k, label in (("lut", "LUTs"), ("lutram", "LUTs as memory"), ("ff", "FFs"), ("bram_tile", "BRAM tiles"),
                     ("dsp", "DSP48E1"), ("iob", "bonded IOBs"), ("bufg", "BUFGs")):
        row(label, lambda x, k=k: x["gates"]["utilization"].get(k))
    row("DRC errors / critical / warnings", lambda x: "{errors} / {critical_warnings} / {warnings}".format(**x["gates"]["drc"]))
    row("methodology critical / warnings", lambda x: "{critical_warnings} / {warnings}".format(**x["gates"]["methodology"]))
    row("methodology rules", lambda x: ", ".join(f"{r['rule']} x{r['count']}" for r in x["gates"]["methodology"]["rules"]) or "none")
    row("CDC", lambda x: "all paths safely timed" if x["gates"]["cdc"]["safely_timed"]
        else ", ".join(f"{r['severity']} {r['rule']} x{r['count']}" for r in x["gates"]["cdc"]["rules"]))
    row("power, total on-chip (W, vectorless)", lambda x: x["gates"]["power"].get("total_w"))
    row("power, dynamic (W)", lambda x: x["gates"]["power"].get("dynamic_w"))
    row("bitstream (bytes)", lambda x: x["gates"]["bitstream"]["bytes"])
    row("build stamp", lambda x: x["run"]["build_stamp"])
    row("Vivado wall time (s)", lambda x: x["run"]["wall_s"])
    row("Vivado peak RSS (MiB)", lambda x: x["run"]["vivado_peak_rss_mib"])
    row("scope peak anonymous memory, all processes (MiB)", lambda x: x["run"].get("scope_anon_peak_mib"))
    row("scope peak charged memory incl. page cache (MiB)", lambda x: x["run"]["scope_memory_peak_mib"])
    row("scope peak swap (MiB)", lambda x: x["run"].get("scope_swap_peak_mib"))
    row("times the 6 GB cap was reached / OOM kills", lambda x: f"{x['run'].get('scope_cap_hits')} / {x['run'].get('scope_oom_kills')}")
    if "base" in res and "ila" in res:
        ub, ui = res["base"]["gates"]["utilization"], res["ila"]["gates"]["utilization"]
        L += ["", "## ILA cost (ila - base)", "", "| Resource | base | ila | cost |", "|---|---|---|---|"]
        for k, label in (("lut", "LUTs"), ("lutram", "LUTs as memory"), ("ff", "FFs"),
                         ("bram_tile", "BRAM tiles"), ("dsp", "DSP48E1"), ("bufg", "BUFGs")):
            b, i = ub.get(k, 0), ui.get(k, 0)
            L.append(f"| {label} | {b} | {i} | {round(i - b, 1)} |")
    L += ["", "Power is Vivado's vectorless estimate (default toggle rates), not a board measurement.", "",
          "Memory: the peak RSS is the largest single Vivado process (`/usr/bin/time -v`). The scope figures come "
          "from the build's cgroup, sampled every 2 s: anonymous memory summed over every process in it (the ILA "
          "build starts helper Vivado processes to synthesise the debug cores), and the charged total, which also "
          "counts page cache. When the charged total reaches the 6 GB cap the kernel reclaims cache first; a build "
          "is at risk only if anonymous memory approaches the cap or an OOM kill is recorded.", ""]
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("design", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    design = (ROOT / a.design).resolve()
    out = (ROOT / a.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    res = {}
    for v in ("base", "ila"):
        c = collect(design, v)
        if c:
            res[v] = c
            (out / f"{design.name}_{v}.json").write_text(json.dumps(c, indent=2) + "\n")
    if not res:
        print(f"summarise: no gates.json/run.json under {design}/build", file=sys.stderr)
        return 1
    (out / f"{design.name}.md").write_text(markdown(design.name, res))
    print(f"summarise: wrote {', '.join(res)} for {design.name} to {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
