#!/usr/bin/env python3
"""Turn a design's build.yaml (and probes.yaml) into Tcl that flow/build.tcl sources.

    python3 flow/prepare.py designs/t1_dimmer_counter --variant base|ila --out <build dir>

Writes ``<out>/inputs.tcl`` (top, part, sources, constraints, generics, out
dir, ILA switch, and the board's thermal environment for report_power) and, for the ``ila`` variant, ``<out>/probes.tcl``. Prints a
JSON line with the build stamp: the first 8 hex digits of the SHA-256 over
every source and constraint file (path and content), so the same sources give
the same stamp in any clone and the shell's BUILD_STAMP register identifies them.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def tcl_list(items: list[str]) -> str:
    return "[list " + " ".join("{" + i + "}" for i in items) + "]"


def expand(patterns: list[str]) -> list[Path]:
    out: list[Path] = []
    for pat in patterns:
        hits = sorted(ROOT.glob(pat))
        if not hits:
            raise SystemExit(f"prepare: no files match {pat}")
        out += hits
    return out


def sources_sha256(files: list[Path]) -> str:
    h = hashlib.sha256()
    for f in files:
        h.update(str(f.relative_to(ROOT)).encode() + b"\0" + f.read_bytes() + b"\0")
    return h.hexdigest()


def probes_tcl(probes_yaml: Path) -> str:
    cfg = yaml.safe_load(probes_yaml.read_text())
    ila = cfg["ila"]
    lines = [f"# generated by flow/prepare.py from {probes_yaml.relative_to(ROOT)}",
             f"set ila_name {{{ila['name']}}}",
             f"set ila_clock_net {{{ila['clock_net']}}}",
             f"set ila_depth {int(ila['depth'])}",
             f"set ila_pipe {int(ila.get('input_pipe_stages', 0))}",
             "set ila_probes {}"]
    # one lappend per probe: a newline inside [list ...] would start a new Tcl command
    for pr in cfg["probes"]:
        lines.append(f"lappend ila_probes [list {{{pr['name']}}} {{{pr['pins']}}} {int(pr['width'])}]")
    return "\n".join(lines) + "\n"


def board_for(cfg: dict) -> str | None:
    """The board a design is built for: build.yaml's ``board``, else the one board whose part matches."""
    if cfg.get("board"):
        return str(cfg["board"])
    hits = [b.parent.name for b in sorted((ROOT / "boards").glob("*/board.yaml"))
            if (yaml.safe_load(b.read_text()) or {}).get("part") == cfg["part"]]
    return hits[0] if len(hits) == 1 else None


def power_env_tcl(board: str | None) -> str:
    """set_operating_conditions arguments from boards/<board>/board.yaml ``thermal`` (empty: Vivado's defaults).

    Vivado's defaults (250 LFM airflow, a medium heat sink, a 10x10 in 12-15 layer board) understate the
    junction temperature of a bare development board, and the power gate (flow/hw.py) refuses a report
    made with them."""
    if not board:
        return ""
    f = ROOT / "boards" / board / "board.yaml"
    th = (yaml.safe_load(f.read_text()) or {}).get("thermal") if f.is_file() else None
    if not th:
        return ""
    return (f"-airflow {int(th['airflow_lfm'])} -heatsink {th['heatsink']} -board {th['board']} "
            f"-board_layers {th['board_layers']} -ambient_temp {float(th['ambient_c'])}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("design", type=Path)
    ap.add_argument("--variant", choices=["base", "ila"], default="base")
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    design = (ROOT / a.design).resolve() if not a.design.is_absolute() else a.design
    cfg = yaml.safe_load((design / "build.yaml").read_text())
    srcs = expand(cfg["sources"])
    xdcs = expand(cfg["constraints"])
    stamp = sources_sha256(srcs + xdcs)
    out = a.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    generics = {**cfg.get("generics", {}), "BUILD_STAMP": f"32'h{stamp[:8]}"}
    ila = a.variant == "ila"
    tcl = [f"# generated by flow/prepare.py for {design.relative_to(ROOT)} ({a.variant})",
           f"set top {{{cfg['top']}}}",
           f"set part {{{cfg['part']}}}",
           f"set sources {tcl_list([str(s) for s in srcs])}",
           f"set constraints {tcl_list([str(x) for x in xdcs])}",
           f"set generics {tcl_list([f'{k}={v}' for k, v in generics.items()])}",
           f"set out {{{out}}}",
           f"set ila {int(ila)}",
           f"set power_env {{{power_env_tcl(board_for(cfg))}}}"]
    if ila:
        (out / "probes.tcl").write_text(probes_tcl(ROOT / cfg["probes"]))
        tcl.append(f"set probes_tcl {{{out / 'probes.tcl'}}}")
    (out / "inputs.tcl").write_text("\n".join(tcl) + "\n")
    json.dump({"design": str(design.relative_to(ROOT)), "variant": a.variant, "top": cfg["top"],
               "part": cfg["part"], "sources_sha256": stamp, "build_stamp": stamp[:8],
               "files": [str(f.relative_to(ROOT)) for f in srcs + xdcs]}, sys.stdout)
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
