"""Generate the synthesisable SystemVerilog of an elaborated block design, its wrappers, and the manifest.

One module per design level: the top, one per hierarchy file, one per generated AXI4-Lite wrapper. Every instance is
``u_<name>``; inside a wrapper the library block is ``u_ip`` and the register bank or window adapter ``u_regs`` /
``u_win``. The viewer's graph uses the same names, and ``hiercheck.py`` compares them with the synthesised hierarchy.

Nets are named ``<inst>__<port>`` (an instance port) and ``<link>__<signal>`` (a bus link), so a generated name never
collides with a port of the design.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from flow.blockdesign import addrmap, components as C, model as M

GEN_VERSION = "65A.1"
HEADER = "// Generated by flow/blockdesign {ver} from {src}; do not edit. Regenerate: python3 -m flow.blockdesign generate {d}\n"
LINT_NOTE = ("/* verilator lint_off UNUSEDSIGNAL */   // generated nets: address bits above a slave's decode and outputs\n"
             "                                       // left open (listed as BD-OPEN-01 by the validator) are not read\n")


def sv_val(v, width: int | None = None, name: str = "") -> str:
    if isinstance(v, str):
        return v if v.startswith(("'", "{")) else f'"{v}"'
    if width:
        return f"{width}'h{v:x}"
    if isinstance(v, int) and not isinstance(v, bool) and name.endswith("ID") and 0 <= v < 1 << 32:
        return f"32'h{v:08x}"           # an ID reads better in hex
    return str(v)


def _ifport_map(E: M.Elab) -> dict:
    """(box, port) -> the net it connects to, for every port that belongs to a bus link or a hierarchy export."""
    out = {}
    for L in E.links:
        for side in (L.master, L.slave):
            b = E.boxes[side[0]]
            if b.kind == "interconnect":
                continue                  # the crossbar's packed ports are sliced explicitly
            i = b.ifaces[side[1]]
            for sig, pn in i.ports.items():
                out[(side[0], pn)] = (L.name, sig, side is L.master)
    for ifn, (inst, ifc) in E.exports.items():
        i = E.boxes[inst].ifaces[ifc]
        for sig, pn in i.ports.items():
            out[(inst, pn)] = ("__export__", f"{ifn}_{sig}", None)
    return out


def _link_sigs(E: M.Elab, L: M.Link) -> dict:
    """signal -> width of a link's nets (master side widths; the xbar side for crossbar links)."""
    if L.kind in ("axi4lite",):
        aw = None
        for side in (L.master, L.slave):
            b = E.boxes[side[0]]
            if b.kind == "interconnect":
                aw = b.params["ADDR_W"]
        if aw is None:
            aw = E.boxes[L.master[0]].ifaces[L.master[1]].addr_w
        return {s: (aw if s in ("awaddr", "araddr") else M.AXIL_W.get(s, 1)) for s, _ in M.AXIL_PORTS}
    sigs = {}
    for side in (L.master, L.slave):
        b = E.boxes[side[0]]
        for sig, pn in b.ifaces[side[1]].ports.items():
            sigs[sig] = max(sigs.get(sig, 0), b.ports[pn].width)
    return sigs


def _seg_expr(E: M.Elab, s: M.Seg, nets: dict) -> str:
    if s.src is None:
        e = f"{s.width}'d{s.const}"
    else:
        base = s.src[1] if s.src[0] == "ext" else nets[(s.src[1], s.src[2])]
        full = M.port_of(E, s.src).width
        e = base if (s.src_lsb == 0 and s.width == full) else (f"{base}[{s.src_lsb}]" if s.width == 1 and full > 1
                                                             else f"{base}[{s.src_lsb + s.width - 1}:{s.src_lsb}]" if full > 1 else base)
    return f"~{e}" if s.invert else e


def _sink_expr(E: M.Elab, dst: tuple, width: int, nets: dict) -> str:
    segs = sorted([s for s in E.segs if s.dst == dst], key=lambda s: s.dst_lsb, reverse=True)
    parts, nxt = [], width
    for s in segs:
        hi = s.dst_lsb + s.width
        if hi < nxt:
            parts.append(f"{nxt - hi}'d0")
        parts.append(_seg_expr(E, s, nets))
        nxt = s.dst_lsb
    if nxt > 0:
        parts.append(f"{nxt}'d0")
    return parts[0] if len(parts) == 1 else "{" + ", ".join(parts) + "}"


def _decl(name: str, w: int) -> str:
    return f"    logic {'' if w == 1 else f'[{w - 1}:0] '}{name};"


def _raised(E: M.Elab, raised: list) -> dict:
    """inst -> [(the parameter's name on that instance, its name in this module)] for the raised parameters."""
    out: dict = {}
    for (path, p, name) in raised:
        b = E.boxes[path[0]]
        child = p if (b.kind in ("component", "wrapped") or len(path) == 1) else "_".join(path[1:]).upper() + "_" + p
        out.setdefault(path[0], []).append((child, name))
    return out


def module_text(E: M.Elab, raised: list, src_name: str, ddir: str) -> str:
    """The SystemVerilog module of one design level (the top or a hierarchy)."""
    is_top = E.kind == "top"
    name = E.top if is_top else E.mprefix
    ifmap = _ifport_map(E)
    nets = {}
    L = [HEADER.format(ver=GEN_VERSION, src=src_name, d=ddir)]
    L.append(f"// {E.data.get('summary', '').strip()}" if E.data.get("summary") else f"// hierarchy {E.name}")
    params = []
    if is_top and any(b.comp and b.comp.name == "test_shell" for b in E.boxes.values()):
        params.append("    parameter logic [31:0] BUILD_STAMP = 32'h0")      # the flow sets the sources' hash here
    rmap = _raised(E, raised)
    for (path, p, pname) in raised:
        v = _param_value(E, path, p)
        params.append(f"    parameter {'int' if isinstance(v, int) else ''} {pname} = {sv_val(v)}".replace("parameter  ", "parameter "))
    head = f"module {name}" + (" #(\n" + ",\n".join(params) + "\n)" if params else "") + " (\n"
    ports = []
    for p in E.ports.values():
        ports.append(f"    {'input ' if p.dir == 'in' else 'output'} logic {'' if p.width == 1 else f'[{p.width - 1}:0] '}{p.name}")
    if not is_top:
        for ifn, (inst, ifc) in E.exports.items():
            i = E.boxes[inst].ifaces[ifc]
            for sig, pn in i.ports.items():
                bp = E.boxes[inst].ports[pn]
                ports.append(f"    {'input ' if bp.dir == 'in' else 'output'} logic {'' if bp.width == 1 else f'[{bp.width - 1}:0] '}{ifn}_{sig}")
    L.append(head + ",\n".join(ports) + "\n);")
    # ---- nets
    L.append(LINT_NOTE)
    for bn, b in E.boxes.items():
        for p in b.ports.values():
            if (bn, p.name) in ifmap:
                continue
            nets[(bn, p.name)] = f"{bn}__{p.name}"
            L.append(_decl(f"{bn}__{p.name}", p.width))
    link_nets = {}
    for Lk in E.links:
        sigs = _link_sigs(E, Lk)
        link_nets[Lk.name] = sigs
        L.append(f"    // link {Lk.name}: {Lk.master[0]}.{Lk.master[1]} -> {Lk.slave[0]}.{Lk.slave[1]} ({Lk.kind})")
        for sig, w in sigs.items():
            L.append(_decl(f"{Lk.name}__{sig}", w))
    for bn, b in E.boxes.items():
        if b.kind == "interconnect":
            n_m, n_s, aw = b.params["N_M"], b.params["N_S"], b.params["ADDR_W"]
            for side, n in (("s", n_m), ("m", n_s)):
                for sig, _ in M.AXIL_PORTS:
                    w = aw if sig in ("awaddr", "araddr") else M.AXIL_W.get(sig, 1)
                    L.append(f"    logic [{n * w - 1}:0] {bn}__{side}_axil_{sig};")   # always a vector: sliced per port
    L.append("    /* verilator lint_on UNUSEDSIGNAL */\n")
    # ---- instances
    for bn, b in E.boxes.items():
        L.append(_instance_text(E, b, nets, ifmap, rmap, is_top))
    # ---- crossbar slices
    for bn, b in E.boxes.items():
        if b.kind != "interconnect":
            continue
        aw = b.params["ADDR_W"]
        for Lk in [x for x in E.links if x.xbar == bn]:
            xside = "s" if Lk.slave[0] == bn else "m"
            for sig, _ in M.AXIL_PORTS:
                w = aw if sig in ("awaddr", "araddr") else M.AXIL_W.get(sig, 1)
                sl = f"{bn}__{xside}_axil_{sig}" + (f"[{Lk.index}]" if w == 1 else f"[{Lk.index * w + w - 1}:{Lk.index * w}]")
                into_xbar = (C.driven_by_master(sig) and xside == "s") or (not C.driven_by_master(sig) and xside == "m")
                L.append(f"    assign {sl} = {Lk.name}__{sig};" if into_xbar else f"    assign {Lk.name}__{sig} = {sl};")
    # ---- ties for bus signals one side lacks
    for Lk in E.links:
        if Lk.xbar:
            continue
        sigs = link_nets[Lk.name]
        mi = E.boxes[Lk.master[0]].ifaces[Lk.master[1]].ports
        si = E.boxes[Lk.slave[0]].ifaces[Lk.slave[1]].ports
        for sig, w in sigs.items():
            drv = mi if C.driven_by_master(sig) else si
            if sig not in drv:
                t = C.TIE.get(sig, "0")
                L.append(f"    assign {Lk.name}__{sig} = {w}'d{(1 << w) - 1 if t == 'ones' else int(t) if t.isdigit() else 0};")
    for Lk in [x for x in E.links if x.xbar]:
        side = Lk.master if Lk.slave[0] == Lk.xbar else Lk.slave
        ports = E.boxes[side[0]].ifaces[side[1]].ports
        for sig, w in link_nets[Lk.name].items():
            mine = C.driven_by_master(sig) == (side is Lk.master)
            if mine and sig not in ports:
                t = C.TIE.get(sig, "0")
                L.append(f"    assign {Lk.name}__{sig} = {w}'d{(1 << w) - 1 if t == 'ones' else int(t) if t.isdigit() else 0};")
    # ---- input nets and design outputs from the connections
    for bn, b in E.boxes.items():
        for p in b.ports.values():
            if p.dir == "in" and (bn, p.name) in nets:
                if any(s.dst == ("box", bn, p.name) for s in E.segs):
                    L.append(f"    assign {nets[(bn, p.name)]} = {_sink_expr(E, ('box', bn, p.name), p.width, nets)};")
    for p in E.ports.values():
        if p.dir == "out":
            if any(s.dst == ("ext", p.name) for s in E.segs):
                L.append(f"    assign {p.name} = {_sink_expr(E, ('ext', p.name), p.width, nets)};")
    L.append("endmodule\n")
    return "\n".join(L)


def _param_value(E: M.Elab, path: list, p: str):
    cur = E
    for seg in path[:-1]:
        cur = cur.boxes[seg].sub
    return cur.boxes[path[-1]].params[p]


def _port_conn(E, b, p, nets, ifmap):
    key = (b.name, p.name)
    if key in ifmap:
        lname, sig, _ = ifmap[key]
        if lname == "__export__":
            return sig
        lw = _link_sigs(E, next(x for x in E.links if x.name == lname))[sig]
        net = f"{lname}__{sig}"
        if p.width == lw:
            return net
        if p.width < lw:
            return f"{net}[{p.width - 1}:0]"
        return f"{{{p.width - lw}'d0, {net}}}" if p.dir == "in" else net
    return nets[key]


def _instance_text(E, b, nets, ifmap, rmap, is_top) -> str:
    if b.kind == "interconnect":
        pv = [f".N_M({b.params['N_M']})", f".N_S({b.params['N_S']})", f".ADDR_W({b.params['ADDR_W']})",
              f".S_BASE({b.params['N_S'] * b.params['ADDR_W']}'h{b.params.get('S_BASE', 0):x})",
              f".S_BITS({b.params['N_S'] * 8}'h{b.params.get('S_BITS', 0):x})"]
        conns = [f".clk({nets[(b.name, 'clk')]})", f".rst({nets[(b.name, 'rst')]})"]
        for side in ("s", "m"):
            for sig, _ in M.AXIL_PORTS:
                conns.append(f".{side}_axil_{sig}({b.name}__{side}_axil_{sig})")
        return f"    // {b.note}\n    axil_xbar #({', '.join(pv)}) u_{b.name} (\n        " + ",\n        ".join(conns) + ");\n"
    pv = []
    mine = dict(rmap.get(b.name, []))
    if b.kind in ("component", "reset_sync"):
        for k, v in b.params.items():
            if k in mine:
                pv.append(f".{k}({mine.pop(k)})")
            elif b.comp.name == "test_shell" and k == "BUILD_STAMP" and is_top:
                pv.append(".BUILD_STAMP(BUILD_STAMP)")
            elif b.origin.get(k) != "default":
                pv.append(f".{k}({sv_val(v, name=k)})")
    pv += [f".{child}({name})" for child, name in mine.items()]
    conns = [f".{p.name}({_port_conn(E, b, p, nets, ifmap)})" for p in b.ports.values()]
    if b.kind == "reset_sync":
        what = f"// {b.note}"
    elif b.kind == "wrapped":
        what = (f"// {b.name}: {b.comp.name}" + (f" ({b.variant})" if b.variant else "") + " with a generated AXI4-Lite "
                + ("window adapter" if b.wrap["kind"] == "window" else "register bank"))
    elif b.kind == "hierarchy":
        what = f"// {b.name}: hierarchy {b.sub.name}"
    else:
        what = f"// {b.name}: {b.comp.name}" + (f" ({b.variant})" if b.variant else "")
    ptxt = f" #({', '.join(pv)})" if pv else ""
    return f"    {what}\n    {b.module}{ptxt} u_{b.name} (\n        " + ",\n        ".join(conns) + ");\n"


# -------------------------------------------------------------------------------------------------------- wrappers
def wrapper_text(E: M.Elab, b: M.Box, raised_here: dict, src_name: str, ddir: str) -> str:
    c, wr = b.comp, b.wrap
    clk = c.clocks[0] if c.clocks else "clk"
    rst_port, rst_pol = next(iter(c.resets.items())) if c.resets else ("rst", "high")
    rst_hi = rst_port if rst_pol == "high" else f"~{rst_port}"
    L = [HEADER.format(ver=GEN_VERSION, src=src_name, d=ddir)]
    L.append(f"// {b.name}: {c.name}{f' ({b.variant})' if b.variant else ''} behind a generated AXI4-Lite "
             + ("window adapter (bd_axil_win)." if wr["kind"] == "window" else "register bank (bd_axil_regs)."))
    params = [f"    parameter {'int ' if isinstance(b.params[p], int) else ''}{p} = {sv_val(b.params[p])}" for p in raised_here]
    ports = []
    for p in b.ports.values():
        ports.append(f"    {'input ' if p.dir == 'in' else 'output'} logic {'' if p.width == 1 else f'[{p.width - 1}:0] '}{p.name}")
    L.append(f"module {b.module}" + (" #(\n" + ",\n".join(params) + "\n)" if params else "") + " (\n" + ",\n".join(ports) + "\n);")
    ipconn = {}
    for p in c.module.ports:
        if p.name in b.ports and p.name != (wr.get("tick") or {}).get("to"):
            ipconn[p.name] = p.name
    if wr["kind"] == "window":
        win = c.iface(wr["window"]).ports
        L += [f"    logic [6:0]  w_addr;", "    logic        w_wr, w_rd;", "    logic [31:0] w_wdata, w_rdata;",
              f"    bd_axil_win #(.ADDR_W({M.WRAP_ADDR_W})) u_win (",
              f"        .clk({clk}), .rst({rst_hi}),",
              "        " + ", ".join(f".s_axil_{s}(s_axil_{s})" for s, _ in M.AXIL_PORTS) + ",",
              "        .win_addr(w_addr), .win_wr(w_wr), .win_rd(w_rd), .win_wdata(w_wdata), .win_rdata(w_rdata));"]
        ipconn.update({win["win_addr"]: "w_addr", win["win_wr"]: "w_wr", win["win_rd"]: "w_rd", win["win_wdata"]: "w_wdata",
                       win["win_rdata"]: "w_rdata"})
    else:
        n_rw, n_ro = len(wr["control"]), len(wr["status"])
        reset = sum((r["reset"] & 0xFFFFFFFF) << (32 * i) for i, r in enumerate(wr["control"]))
        L += [f"    localparam int N_RW = {n_rw}, N_RO = {n_ro};",
              "    /* verilator lint_off UNUSEDSIGNAL */   // register bits that drive no input of the block",
              "    logic [N_RW*32-1:0] rw_q;", "    logic [N_RW-1:0]    rw_wr;",
              "    /* verilator lint_on UNUSEDSIGNAL */", "    logic [N_RO*32-1:0] ro_d;",
              f"    bd_axil_regs #(.ADDR_W({M.WRAP_ADDR_W}), .N_RW(N_RW), .N_RO(N_RO), .RW_RESET({32 * n_rw}'h{reset:x})) u_regs (",
              f"        .clk({clk}), .rst({rst_hi}),",
              "        " + ", ".join(f".s_axil_{s}(s_axil_{s})" for s, _ in M.AXIL_PORTS) + ",",
              "        .rw_q(rw_q), .rw_wr(rw_wr), .ro_d(ro_d));"]
        for i, r in enumerate(wr["control"]):
            L.append(f"    // control {r['name']} (offset 0x{4 * i:03x}): {r['doc']}")
            for f in r["fields"]:
                ipconn[f["port"]] = f"rw_q[{32 * i + f['lsb'] + f['width'] - 1}:{32 * i + f['lsb']}]" if f["width"] > 1 else f"rw_q[{32 * i + f['lsb']}]"
        for j, r in enumerate(wr["status"]):
            L.append(f"    // status {r['name']} (offset 0x{4 * (n_rw + j):03x}): {r['doc']}")
            L.append(f"    assign ro_d[{32 * j + 31}:{32 * j}] = {_status_expr(r)};")
        if wr.get("tick"):
            t = wr["tick"]
            k = [r["name"] for r in wr["control"]].index(t["div_reg"])
            L += [f"    // the {t['to']} input: one clock in every {t['div_reg']} + 1 (a generated sample-rate divider)",
                  "    logic [31:0] tick_cnt;", "    logic        tick_q;",
                  f"    always_ff @(posedge {clk}) begin",
                  f"        if ({rst_hi}) begin tick_cnt <= '0; tick_q <= 1'b0; end",
                  f"        else if (tick_cnt >= rw_q[{32 * k + 31}:{32 * k}]) begin tick_cnt <= '0; tick_q <= 1'b1; end",
                  "        else begin tick_cnt <= tick_cnt + 1'b1; tick_q <= 1'b0; end", "    end",
                  f"    assign {t['to']} = tick_q;"]
            ipconn[t["to"]] = "tick_q"
    # the block itself, every parameter fixed (or raised)
    pv = []
    for k, v in b.params.items():
        if k in raised_here:
            pv.append(f".{k}({k})")
        elif b.origin.get(k) != "default":
            pv.append(f".{k}({sv_val(v)})")
    for p in c.module.ports:
        if p.name not in ipconn:
            raise ValueError(f"{b.name}: no connection for {c.name}.{p.name}")
    L.append(f"    {c.top}{' #(' + ', '.join(pv) + ')' if pv else ''} u_ip (\n        "
             + ",\n        ".join(f".{p.name}({ipconn[p.name]})" for p in c.module.ports) + ");")
    L.append("endmodule\n")
    return "\n".join(L)


def _status_expr(r: dict) -> str:
    fs = sorted(r["fields"], key=lambda f: f["lsb"], reverse=True)
    if not fs:
        return "32'd0"
    if len(fs) == 1 and fs[0]["lsb"] == 0 and fs[0]["signed"] and fs[0]["width"] < 32:
        f = fs[0]
        return f"{{{{{32 - f['width']}{{{f['port']}[{f['width'] - 1}]}}}}, {f['port']}}}"
    parts, nxt = [], 32
    for f in fs:
        hi = f["lsb"] + f["width"]
        if hi < nxt:
            parts.append(f"{nxt - hi}'d0")
        parts.append(f["port"])
        nxt = f["lsb"]
    if nxt > 0:
        parts.append(f"{nxt}'d0")
    return parts[0] if len(parts) == 1 else "{" + ", ".join(parts) + "}"


# ------------------------------------------------------------------------------------------------------- the files
def raised_params(E: M.Elab) -> dict:
    """Per generated module, the parameters raised through it: module name -> [(path from it, PARAM, its name there)]."""
    out: dict = {}
    for (path, p, v) in E.top_params:
        cur, mod = E, E.top
        for depth in range(len(path)):
            pname = "_".join(path[depth:]).upper() + "_" + p if depth < len(path) else p
            out.setdefault(mod, []).append((path[depth:], p, pname))
            b = cur.boxes[path[depth]]
            if b.sub is not None:
                cur, mod = b.sub, b.sub.mprefix
            elif b.kind == "wrapped":
                out.setdefault(b.module, []).append(([], p, p))
                break
            else:
                break
    return out


def generate(design_dir: Path, E: M.Elab | None = None) -> dict:
    """{repo-relative path: text} of every generated file (not written)."""
    design_dir = Path(design_dir)
    src = design_dir / "blockdesign.yaml"
    E = E or M.elaborate(src)
    if E.errors():
        raise ValueError("the block design has errors:\n" + "\n".join(d.text() for d in E.errors()))
    rel = design_dir.resolve().relative_to(M.ROOT)
    out: dict = {}
    raised = raised_params(E)

    def emit(el: M.Elab):
        modname = el.top if el.kind == "top" else el.mprefix
        mine = raised.get(modname, [])
        r_here = [(path, p, name) for (path, p, name) in mine if path]
        out[f"{rel}/gen/rtl/{modname}.sv"] = module_text(el, r_here, el.path.name, str(rel))
        for b in el.boxes.values():
            if b.kind == "wrapped":
                wr_raised = [p for (path, p, name) in raised.get(b.module, []) if not path]
                out[f"{rel}/gen/rtl/{b.module}.sv"] = wrapper_text(el, b, wr_raised, el.path.name, str(rel))
            if b.sub is not None and f"{rel}/gen/rtl/{b.sub.mprefix}.sv" not in out:
                emit(b.sub)
    emit(E)
    out[f"{rel}/gen/addrmap.h"] = addrmap.c_header(E)
    out[f"{rel}/gen/address_map.md"] = addrmap.markdown(E)
    out[f"{rel}/gen/address_map.json"] = addrmap.write_json(E)
    srcs = sources(E, rel)
    out[f"{rel}/build.yaml"] = build_yaml(E, rel, srcs)
    from flow.blockdesign import graph
    g = graph.build(E)
    out[f"{rel}/gen/graph.json"] = json.dumps(g, indent=1) + "\n"
    out[f"{rel}/gen/manifest.json"] = json.dumps(manifest(E, rel, out, srcs), indent=1) + "\n"
    return out


def sources(E: M.Elab, rel) -> list[str]:
    files: list[str] = []

    def walk(el):
        for b in el.boxes.values():
            if b.comp is not None:
                for f in b.comp.rtl:
                    if f not in files:
                        files.append(f)
                if b.kind == "wrapped":
                    sup = C.load("bd_axil_win" if b.wrap["kind"] == "window" else "bd_axil_regs").rtl
                    files.extend(x for x in sup if x not in files)
            if b.sub is not None:
                walk(b.sub)
    walk(E)
    return sorted(files) + [f"{rel}/gen/rtl/*.sv"]


def build_yaml(E: M.Elab, rel, srcs: list[str]) -> str:
    L = [f"# How flow/run_vivado.sh builds this design. Generated by flow/blockdesign from blockdesign.yaml; do not edit.",
         f"top: {E.top}", f"part: {E.data.get('part', 'xc7a100tcsg324-1')}", "sources:"]
    L += [f"  - {s}" for s in srcs]
    L += ["constraints:"] + [f"  - {c}" for c in E.data.get("constraints") or []]
    L += ["generics: {}            # board values are the generated defaults; BUILD_STAMP is added by the flow", ""]
    return "\n".join(L)


def _sha(text: str | bytes) -> str:
    return hashlib.sha256(text.encode() if isinstance(text, str) else text).hexdigest()


def manifest(E: M.Elab, rel, out: dict, srcs: list[str]) -> dict:
    inputs = {}

    def walk(el):
        inputs[str(el.path.relative_to(M.ROOT))] = _sha(el.path.read_bytes())
        for b in el.boxes.values():
            if b.sub is not None:
                walk(b.sub)
    walk(E)
    blocks = []

    def wb(el, prefix):
        for b in el.boxes.values():
            if b.sub is not None:
                wb(b.sub, f"{prefix}{b.name}/")
            if b.comp is not None:
                blocks.append({"path": f"{prefix}{b.name}", "component": b.comp.name, "source": b.comp.source,
                               "version": b.comp.version, "variant": b.variant, "module": b.module,
                               "params": {k: v for k, v in b.params.items()}, "generated": b.generated})
    wb(E, "")
    return {"schema": "fpga-design-agent/blockdesign-manifest/v1", "design": E.name, "top": E.top, "generator": GEN_VERSION,
            "inputs": inputs, "components": blocks,
            "outputs": {k: _sha(v) for k, v in sorted(out.items()) if not k.endswith("manifest.json")},
            "sources": srcs, "diagnostics": [d.text() for d in E.all_diags()], "summary": M.summary(E)}


def write(design_dir: Path) -> list[str]:
    files = generate(design_dir)
    for k, v in files.items():
        p = M.ROOT / k
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(v)
    return sorted(files)


def check(design_dir: Path) -> list[str]:
    """Paths whose committed text differs from what the generator writes now (the drift check)."""
    files = generate(design_dir)
    bad = [k for k, v in files.items() if not (M.ROOT / k).is_file() or (M.ROOT / k).read_text() != v]
    gen = Path(design_dir).resolve() / "gen"
    extra = [str(p.relative_to(M.ROOT)) for p in gen.rglob("*") if p.is_file() and str(p.relative_to(M.ROOT)) not in files
             and p.name != "viewer.html"] if gen.is_dir() else []
    return bad + extra
