"""Brief 100B step 1: where the wall-clock goes, from existing records only (no new run). Writes results/b100b/where_time.json and .md.

Vivado stage shares come from each build's stages.txt (cumulative seconds at the end of each flow stage, flow/build.tcl); agent-run
shares from the b100 stage-2 run records (audit.jsonl, meta.json, stream.jsonl's result line: duration_api_ms is the model API time).
    python3 flow/rw/speed/where_time.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
R = ROOT / "results"
GROUPS = {   # flow stage name -> group (a stage's time is its end stamp minus the previous stamp)
    "read": "front end (read, elaborate, RTL reports)", "elaborate": "front end (read, elaborate, RTL reports)",
    "rtl_reports": "front end (read, elaborate, RTL reports)",
    "synth": "synthesis", "constraints": "synthesis",
    "synth_reports": "post-synthesis reports", "opt": "opt_design", "place": "place_design (incl. phys_opt)",
    "phys_opt": "place_design (incl. phys_opt)", "place_reports": "place_design (incl. phys_opt)",
    "route": "route_design", "result_dump": "post-route reports", "reports": "post-route reports",
    "bitstream": "write_bitstream", "delay_table": "other",
}
BUILDS = {
    "c10 DDS sine, Nexys A7 (small), 1 thread, run a": "33_vivado_speed_2026_1/raw/c10_t1_a",
    "c10 DDS sine, Nexys A7 (small), 1 thread, run b": "33_vivado_speed_2026_1/raw/c10_t1_b",
    "c13 Harris VGA, Nexys A7 (mid), 1 thread, run a": "33_vivado_speed_2026_1/raw/c13_t1_a",
    "c13 Harris VGA, Nexys A7 (mid), 1 thread, run b": "33_vivado_speed_2026_1/raw/c13_t1_b",
    "b96 10G transmit design, K26, build a": "b96/build_a",
    "b96 10G transmit design, K26, build b": "b96/build_b",
    "CDC rig, 36k LUT, 1 thread": "33_vivado_speed_2026_1/raw/rig_t1",
}


def stages(path: Path) -> dict[str, float]:
    out: dict[str, float] = {}
    prev = 0.0
    for line in path.read_text().splitlines():
        name, t = line.split()
        t = float(t)
        g = GROUPS.get(name, "other")
        out[g] = out.get(g, 0.0) + (t - prev)
        prev = t
    out["TOTAL"] = prev
    return out


def agent_run(arm: str) -> dict:
    d = R / "b100" / "agent" / arm
    meta = json.loads((d / "meta.json").read_text())
    api = None
    for line in (d / "stream.jsonl").read_text().splitlines():
        j = json.loads(line)
        if j.get("type") == "result":
            api = j["duration_api_ms"] / 1000.0
    rows = [json.loads(x) for x in (d / "audit.jsonl").read_text().splitlines()]
    build_s = sum(float(m.group(1)) for r in rows if r.get("tool") == "build"
                  for m in [re.search(r"exit 0, ([\d.]+) s", r.get("result_summary") or "")] if m)
    ref_route = 0.0     # Vivado route inside rw_referee
    rw_s = 0.0          # RapidWright's own seconds reported by rw_place_chain
    for r in rows:
        s = r.get("result_summary") or ""
        if r.get("tool") == "rw_referee":
            m = re.search(r'"route": ([\d.]+)', s)
            ref_route += float(m.group(1)) if m else 0
        if r.get("tool") == "rw_place_chain":
            m = re.search(r'"seconds": ([\d.]+)', s)
            rw_s += float(m.group(1)) if m else 0
    wall = meta["wall_s"]
    return {"wall_s": wall, "vivado_flow_build_s": build_s, "vivado_route_in_referee_s": ref_route,
            "rapidwright_placer_s": rw_s, "model_api_s": api,
            "other_s": round(wall - build_s - ref_route - rw_s - (api or 0), 1)}


def main() -> None:
    out: dict = {"builds": {}, "agent_runs": {}, "latency_loop_b97": {}}
    for label, rel in BUILDS.items():
        out["builds"][label] = {k: round(v, 1) for k, v in stages(R / rel / "stages.txt").items()}
    for arm in "ab":
        out["agent_runs"][f"b100 stage 2 arm {arm.upper()} (K26 chain, timing closure)"] = agent_run(arm)
    for n in ("A0_1", "A0_2", "A1_1", "A1_2"):
        rows = [json.loads(x) for x in (R / "b97" / "paired" / n / "history.jsonl").read_text().splitlines()]
        base = next(r for r in rows if r["event"] == "baseline")["seconds"]
        vis = sum(r["wall_s"] for r in rows if r["event"] == "visit")
        out["latency_loop_b97"][n] = {"baseline_sim_s": base, "visits_wall_s": round(vis, 1)}
    (R / "b100b" / "where_time.json").write_text(json.dumps(out, indent=1) + "\n")
    md = ["# Where the wall-clock goes (generated by flow/rw/speed/where_time.py from existing records)\n",
          "## Vivado builds (flow stages, seconds and share of the build)\n"]
    groups = list(dict.fromkeys(GROUPS.values()))
    md.append("| build | " + " | ".join(groups) + " | total s |")
    md.append("|---|" + "---|" * (len(groups) + 1))
    for label, st in out["builds"].items():
        tot = st["TOTAL"]
        md.append(f"| {label} | " + " | ".join(f"{st.get(g, 0):.0f} ({100*st.get(g,0)/tot:.0f} %)" for g in groups) + f" | {tot:.0f} |")
    md += ["", "## Agent runs (b100 stage 2; one run per arm)\n", "| run | wall s | Vivado flow build s | Vivado route inside rw_referee s | RapidWright placer s | model API s | other (tools, files, waiting) s |", "|---|---|---|---|---|---|---|"]
    for k, v in out["agent_runs"].items():
        md.append(f"| {k} | {v['wall_s']:.0f} | {v['vivado_flow_build_s']:.0f} ({100*v['vivado_flow_build_s']/v['wall_s']:.0f} %) | {v['vivado_route_in_referee_s']:.0f} | {v['rapidwright_placer_s']:.0f} | {v['model_api_s']:.0f} ({100*v['model_api_s']/v['wall_s']:.1f} %) | {v['other_s']:.0f} |")
    md += ["", "Arm B's 'other' includes a second Vivado build (pblock, 1,880 s by the b100 report) that ran after the agent abandoned the call at 1,800 s; "
           "arm A's 'other' is file reads, reports and tool overhead. Model API time is the CLI's own duration_api_ms.", "", "## Latency loop of brief 97 (simulation bench, no Vivado)\n", "| run | baseline bench s | all visits (model turns + bench) wall s |", "|---|---|---|"]
    for k, v in out["latency_loop_b97"].items():
        md.append(f"| {k} | {v['baseline_sim_s']} | {v['visits_wall_s']} |")
    (R / "b100b" / "where_time.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
