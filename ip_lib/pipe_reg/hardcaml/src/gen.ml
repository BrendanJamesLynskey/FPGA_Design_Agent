(* gen: write the Verilog of pipe_reg for a list of configurations: one parameter-less Hardcaml module per point plus a
   wrapper `pipe_reg` with the SystemVerilog block's own parameters and ports, so the existing cocotb benches, SVA monitors
   and formal wrappers instantiate it unchanged. A parameter point that was not generated, or is out of range, stops
   elaboration with $error (the SV's guards do the same).  usage: gen.exe OUT.sv  W,N,MODE,TLAST,TKEEP,TUSER ... *)
open Hardcaml
open Pipe_reg_hc

let parse s =
  match List.map int_of_string (String.split_on_char ',' s) with
  | [ w; n; mode; tl; tk; tu ] ->
    { w; n; mode; tlast = tl <> 0; tkeep = tk <> 0; tuser_w = tu }
  | _ -> failwith ("bad config " ^ s)
;;

let wrapper_header_tmpl =
  {|// pipe_reg: wrapper generated by gen.exe (brief 171). Same parameters and ports as ip_lib/pipe_reg/rtl/pipe_reg.sv;
// the datapath is the Hardcaml module of the matching parameter point.
module pipe_reg #(
    parameter int W        = 32,
    parameter int N        = 1,
    parameter int MODE     = 1,
    parameter int TLAST_EN = 0,
    parameter int TKEEP_EN = 0,
    parameter int TUSER_W  = 0
) (
    input  logic                         aclk,
    input  logic                         aresetn,
    input  logic                         s_axis_tvalid,
    output logic                         s_axis_tready,
    input  logic [W-1:0]                 s_axis_tdata,
    input  logic                         s_axis_tlast,
    input  logic [(W/8 > 0 ? W/8 : 1)-1:0] s_axis_tkeep,
    input  logic [(TUSER_W > 0 ? TUSER_W : 1)-1:0] s_axis_tuser,
    output logic                         m_axis_tvalid,
    input  logic                         m_axis_tready,
    output logic [W-1:0]                 m_axis_tdata,
    output logic                         m_axis_tlast,
    output logic [(W/8 > 0 ? W/8 : 1)-1:0] m_axis_tkeep,
    output logic [(TUSER_W > 0 ? TUSER_W : 1)-1:0] m_axis_tuser@FORMAL_PORTS@
);
    generate
|}
;;

let wrapper_header formal =
  let r = if formal then ",\n    output logic [W-1:0] f_in_o, f_out_o" else "" in
  Str_replace.replace wrapper_header_tmpl "@FORMAL_PORTS@" r
;;

let wrapper_case formal first c =
  let b = Buffer.create 512 in
  let p = Printf.bprintf in
  p b "        %sif (W == %d && N == %d && MODE == %d && TLAST_EN == %d && TKEEP_EN == %d && TUSER_W == %d) begin : g_hc\n"
    (if first then "" else "end else ")
    c.w c.n c.mode (Bool.to_int c.tlast) (Bool.to_int c.tkeep) c.tuser_w;
  p b "            %s u (%s.s_axis_tvalid, .s_axis_tready, .s_axis_tdata, .m_axis_tvalid, .m_axis_tready, .m_axis_tdata"
    (name c) (if c.n = 0 && not formal then "" else ".aclk, .aresetn, ");
  if c.tlast then p b ",\n                .s_axis_tlast, .m_axis_tlast";
  if c.tkeep then p b ",\n                .s_axis_tkeep, .m_axis_tkeep";
  if c.tuser_w > 0 then p b ",\n                .s_axis_tuser, .m_axis_tuser";
  if formal then p b ",\n                .f_in_o, .f_out_o";
  p b ");\n";
  if not c.tlast then p b "            assign m_axis_tlast = 1'b0;\n";
  if not c.tkeep then p b "            assign m_axis_tkeep = '0;\n";
  if c.tuser_w = 0 then p b "            assign m_axis_tuser = '0;\n";
  Buffer.contents b
;;

let () =
  match Array.to_list Sys.argv with
  | _ :: out :: cfgs when cfgs <> [] ->
    let formal = List.mem "-formal" cfgs in
    let cfgs = List.map parse (List.filter (fun s -> s <> "-formal") cfgs) in
    let oc = open_out out in
    List.iter
      (fun c ->
         let circuit = create ~formal c in
         Rtl.output ~output_mode:(To_channel oc) Verilog circuit;
         output_string oc "\n")
      cfgs;
    output_string oc (wrapper_header formal);
    List.iteri (fun i c -> output_string oc (wrapper_case formal (i = 0) c)) cfgs;
    if formal
    then output_string oc "        end\n    endgenerate\nendmodule\n" (* yosys' read_verilog cannot parse elaboration $error *)
    else
      output_string oc
        "        end else begin : g_unsupported\n            initial $error(\"pipe_reg (Hardcaml): parameter point not generated or out of range (W %0d N %0d MODE %0d TLAST_EN %0d TKEEP_EN %0d TUSER_W %0d)\", W, N, MODE, TLAST_EN, TKEEP_EN, TUSER_W);\n        end\n    endgenerate\nendmodule\n";
    close_out oc
  | _ -> prerr_endline "usage: gen OUT.sv W,N,MODE,TLAST,TKEEP,TUSER ..."; exit 2
;;
