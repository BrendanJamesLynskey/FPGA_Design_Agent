(* gen: write the Verilog of credit_chan for a list of parameter points: one parameter-less Hardcaml module per point plus a
   wrapper `credit_chan` with the SystemVerilog block's parameters and ports, so the existing cocotb benches, SVA monitors
   and formal wrappers instantiate it unchanged. A point that was not generated stops elaboration with $error.
   usage: gen.exe OUT.sv [-formal] W,CREDITS,LF,LB,TLAST,TKEEP,TUSER ...   (-formal adds the ghost counters f_in_o, f_out_o) *)
open Hardcaml
open Credit_chan_hc

let parse s =
  match List.map int_of_string (String.split_on_char ',' s) with
  | [ w; credits; lf; lb; tl; tk; tu ] ->
    { w; credits; lf; lb; tlast = tl <> 0; tkeep = tk <> 0; tuser_w = tu }
  | _ -> failwith ("bad config " ^ s)
;;

let header formal =
  Printf.sprintf
    {|// credit_chan: wrapper generated by gen.exe (brief 171). Same parameters and ports as ip_lib/credit_chan/rtl/credit_chan.sv;
// the datapath is the Hardcaml module of the matching parameter point.
module credit_chan #(
    parameter int W        = 32,
    parameter int CREDITS  = 8,
    parameter int LF       = 1,
    parameter int LB       = 1,
    parameter int TLAST_EN = 0,
    parameter int TKEEP_EN = 0,
    parameter int TUSER_W  = 0
) (
    input  logic                         aclk,
    input  logic                         aresetn,
    input  logic                         s_axis_tvalid,
    output logic                         s_axis_tready,
    input  logic [W-1:0]                 s_axis_tdata,
    input  logic                         s_axis_tlast,
    input  logic [(W/8 > 0 ? W/8 : 1)-1:0] s_axis_tkeep,
    input  logic [(TUSER_W > 0 ? TUSER_W : 1)-1:0] s_axis_tuser,
    output logic                         m_axis_tvalid,
    input  logic                         m_axis_tready,
    output logic [W-1:0]                 m_axis_tdata,
    output logic                         m_axis_tlast,
    output logic [(W/8 > 0 ? W/8 : 1)-1:0] m_axis_tkeep,
    output logic [(TUSER_W > 0 ? TUSER_W : 1)-1:0] m_axis_tuser%s
);
    generate
|}
    (if formal then ",\n    output logic [W-1:0] f_in_o, f_out_o" else "")
;;

let case formal first c =
  let b = Buffer.create 512 in
  let p = Printf.bprintf in
  p b "        %sif (W == %d && CREDITS == %d && LF == %d && LB == %d && TLAST_EN == %d && TKEEP_EN == %d && TUSER_W == %d) begin : g_hc\n"
    (if first then "" else "end else ")
    c.w c.credits c.lf c.lb (Bool.to_int c.tlast) (Bool.to_int c.tkeep) c.tuser_w;
  p b "            %s u (.aclk, .aresetn, .s_axis_tvalid, .s_axis_tready, .s_axis_tdata, .m_axis_tvalid, .m_axis_tready, .m_axis_tdata" (name c);
  if c.tlast then p b ",\n                .s_axis_tlast, .m_axis_tlast";
  if c.tkeep then p b ",\n                .s_axis_tkeep, .m_axis_tkeep";
  if c.tuser_w > 0 then p b ",\n                .s_axis_tuser, .m_axis_tuser";
  if formal then p b ",\n                .f_in_o, .f_out_o";
  p b ");\n";
  if not c.tlast then p b "            assign m_axis_tlast = 1'b0;\n";
  if not c.tkeep then p b "            assign m_axis_tkeep = '0;\n";
  if c.tuser_w = 0 then p b "            assign m_axis_tuser = '0;\n";
  Buffer.contents b
;;

let () =
  match Array.to_list Sys.argv with
  | _ :: out :: cfgs when cfgs <> [] ->
    let formal = List.mem "-formal" cfgs in
    let cfgs = List.map parse (List.filter (fun s -> s <> "-formal") cfgs) in
    let oc = open_out out in
    List.iter
      (fun c ->
         Rtl.output ~output_mode:(To_channel oc) Verilog (create ~formal c);
         output_string oc "\n")
      cfgs;
    output_string oc (header formal);
    List.iteri (fun i c -> output_string oc (case formal (i = 0) c)) cfgs;
    if formal
    then output_string oc "        end\n    endgenerate\nendmodule\n" (* yosys read_verilog cannot parse elaboration $error *)
    else
      output_string oc
        "        end else begin : g_unsupported\n            initial $error(\"credit_chan (Hardcaml): parameter point not generated or out of range (W %0d CREDITS %0d LF %0d LB %0d TLAST_EN %0d TKEEP_EN %0d TUSER_W %0d)\", W, CREDITS, LF, LB, TLAST_EN, TKEEP_EN, TUSER_W);\n        end\n    endgenerate\nendmodule\n";
    close_out oc
  | _ -> prerr_endline "usage: gen OUT.sv [-formal] W,CREDITS,LF,LB,TLAST,TKEEP,TUSER ..."; exit 2
;;
