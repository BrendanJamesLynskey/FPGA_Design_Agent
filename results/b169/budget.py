#!/usr/bin/env python3
"""Brief 169: the clock-by-clock budget of lat_all3_bypass (and the prototype cuts), generated from records: results/b169/core_sim/*.json (xsim, four phases) and board_inputs.json.
Writes budget.json (every figure) and budget.svg (one figure). usage: budget.py"""
import json, pathlib
H = pathlib.Path(__file__).parent
T = 6.2058
sim = {c: json.load(open(H / "core_sim" / f"{c}.json"))["mean_over_phases_clocks"] for c in ("base", "early", "fast", "both")}
brd = json.load(open(H / "board_inputs.json"))["lat_all3_bypass"]
fire_go = sim["base"]["fire_to_go"]
stages = [  # name, start event, end event, clocks (sim mean over four phases), board note
    ("pcs_rx stage A (gearbox, block extract)", "GT RXDATA word holding the block's last bit captured", "same edge: `blk` register loaded", 0.0),
    ("pcs_rx stage B (descramble, decode)", "`blk` loaded", "`x_d`/`x_c` loaded (word 7 of the frame: the price)", 1.0),
    ("mac64_rx aligned-word register", "`x_d` loaded", "`m_d` holds word 7 (lane-4 starts realigned)", sim["base"]["x_price_to_fire"]),
    ("trade64 decision `fire`", "`m_d` holds word 7", "`fire` high (combinational compare, price <= thr)", 0.0),
    ("go-pulse crossing RXUSRCLK2 -> TXUSRCLK2", "`fire` high (toggle flop loads)", "`go_p` high in TXUSRCLK2 (2 synchroniser flops, XOR edge detect, no output register)", fire_go),
    ("order start: frame_src start -> mac64_tx preamble register", "`go_p` high", "preamble word in the MAC output register (`sop`)", sim["base"]["go_to_sop"]),
    ("pcs_tx gearbox, first bit of the start block", "preamble in the MAC register", "first bit of the start block on GT TXDATA", 1.0),
    ("pcs_tx gearbox spill, last bit of the start block", "first bit on TXDATA", "last bit of the start block on TXDATA (a 66-bit block never fits one 64-bit word)", 1.0),
]
tot = sum(s[3] for s in stages)
out = {"period_ns": T, "sim_means_clocks": sim, "stages": [dict(zip(("stage", "start", "end", "clocks"), s)) for s in stages], "sim_total_clocks": round(tot, 2), "board": brd}
frame = 8.51   # 52.8 ns / 6.2058 (docs/latency_definitions.md, from bench_feed_v1 offsets): first bit of the frame to the end of the price word
dig_first = tot - 1.0      # first bit of the start block, not the last
resid = brd["E_mean"] + brd["D_register_mean"] - frame - dig_first
out["board_decomposition_clocks"] = {"L_minus_E_mean": round(brd["E_mean"] + brd["D_register_mean"], 2), "frame_time_to_price_word_derived": frame, "digital_sim_price_word_to_first_bit": round(dig_first, 2),
                                     "residual_GT_module_fibre_derived": round(resid, 2), "residual_ns": round(resid * T, 1)}
json.dump(out, open(H / "budget.json", "w"), indent=1)
# ---- svg: two bars, sim chain and board decomposition, plus the prototype savings
W, X0, S = 900, 40, 34.0       # px per clock
cols = ["#555", "#777", "#999", "#bbb", "#333", "#888", "#666", "#aaa"]
svg = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} 330" font-family="sans-serif" font-size="12">',
       '<style>text{fill:#222}.bg{fill:#fff}@media (prefers-color-scheme: dark){text{fill:#eee}.bg{fill:#111}}</style><rect class="bg" width="100%" height="100%"/>',
       '<text x="40" y="22" font-size="14" font-weight="bold">lat_all3_bypass: where the clocks go (generated by results/b169/budget.py)</text>',
       '<text x="40" y="46">Simulated, price word at the receive GT port to the order start block on the transmit GT port (xsim, mean of four phases)</text>']
x = X0
for i, (n, a, b, c) in enumerate(stages):
    w = max(c * S, 1.5)
    svg.append(f'<rect x="{x:.1f}" y="54" width="{w:.1f}" height="30" fill="{cols[i]}" stroke="#fff"/>')
    if c >= 0.5:
        svg.append(f'<text x="{x + 3:.1f}" y="73" fill="#fff" style="fill:#fff">{c:.2f}</text>')
    svg.append(f'<text x="{x:.1f}" y="{98 + 12 * (i % 4)}" font-size="10">{i + 1}</text>')
    x += c * S
svg.append(f'<text x="{x + 6:.1f}" y="73">{tot:.2f} clocks = {tot * T:.0f} ns</text>')
y = 150
svg.append(f'<text x="40" y="{y}">Board: L - E (first bit in to first bit out, optics included, FPGA stamps), mean of 100 links = {brd["E_mean"] + brd["D_register_mean"]:.2f} clocks</text>')
x = X0
parts = [("frame time to the end of the price word (derived)", frame, "#999"), ("digital, simulated (price word to first bit out)", dig_first, "#555"), ("GT in/out (bypassed), module, fibre: residual", resid, "#ccc")]
for n, c, col in parts:
    svg.append(f'<rect x="{x:.1f}" y="{y + 8}" width="{c * S:.1f}" height="30" fill="{col}" stroke="#fff"/><text x="{x + 3:.1f}" y="{y + 28}" style="fill:{"#fff" if col != "#ccc" else "#222"}">{c:.1f}</text>')
    svg.append(f'<text x="{x:.1f}" y="{y + 52}" font-size="10">{n}</text>')
    x += c * S
y = 240
svg.append(f'<text x="40" y="{y}">Prototype cuts (xsim, mean of four phases, price word to start block): base {sim["base"]["tick_to_trade"]:.2f}, EARLY_MAC {sim["early"]["tick_to_trade"]:.2f}, FAST_PRE {sim["fast"]["tick_to_trade"]:.2f}, both {sim["both"]["tick_to_trade"]:.2f} clocks</text>')
for i, c in enumerate(("base", "early", "fast", "both")):
    w = sim[c]["tick_to_trade"] * S
    svg.append(f'<rect x="{X0}" y="{y + 10 + 17 * i}" width="{w:.1f}" height="13" fill="#666"/><text x="{X0 + w + 5:.1f}" y="{y + 21 + 17 * i}">{c} {sim[c]["tick_to_trade"]:.2f}</text>')
svg.append('</svg>')
(H / "budget.svg").write_text("\n".join(svg))
print(json.dumps(out["board_decomposition_clocks"]), round(tot, 2))
for s in stages:
    print(f"{s[3]:5.2f}  {s[0]}")
