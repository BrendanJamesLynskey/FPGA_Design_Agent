"""Write RESULTS.md (every table of the brief 114 evaluation) from results.json and results_v2.json. No number is typed by hand.

    python3 results/114_doc_crossread/make_tables.py
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAMES = {"A": "Sonnet 5.5", "B": "Haiku 5.5"}
TARGET = {"h1_96d_five_word": ("word_count_flagged", "addresses_flagged"), "h3_clock_phase": ("reader_mentions_clock_phase_attribute",),
          "p1_uartlite_stat_ctrl_swapped": ("detected",), "p2_timer_load_bit": ("detected",), "p3_zb_accel_id_reset": ("detected",), "p4_zb_accel_version_width": ("detected",)}


def inp(x: dict) -> int:
    return sum(x.get(k) or 0 for k in ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens"))


def main() -> None:
    fr = json.loads((HERE / "results.json").read_text())["arms"]
    v2 = json.loads((HERE / "results_v2.json").read_text())["arms"]
    out = ["# Brief 114: results tables (generated by make_tables.py from results.json and results_v2.json)", "",
           "Frozen comparator = the code of the pre-registration commit (with the one exception-fix re-run listed in PREREGISTRATION.md). v2 = the same stored reader replies re-compared with the post-hoc rules. Each cell is runs out of 3.", ""]
    out += ["## Detection of the planted and historical targets", "", "| case | what | " + " | ".join(f"{NAMES[a]} frozen | {NAMES[a]} v2" for a in "AB") + " |", "|---|---|" + "---|---|" * 2]
    for cid, keys in TARGET.items():
        cells = []
        for a in "AB":
            for res in (fr, v2):
                r = res[a][cid]
                cells.append(" / ".join(f"{k.replace('_flagged', '').replace('reader_mentions_clock_phase_attribute', 'reader names the attribute')} {r['detected_runs'].get(k, 0)}" for k in keys) if len(keys) > 1 else f"{r['detected_runs'].get(keys[0], 0)}")
        out.append(f"| {cid} | {', '.join(keys)} | " + " | ".join(cells) + " |")
    both = {a: sum(1 for x in fr[a]["h1_96d_five_word"]["runs"] if x["targets"]["word_count_flagged"] and x["targets"]["addresses_flagged"]) for a in "AB"}
    out += ["", "h1 with both the word count and the addresses flagged in the same run: " + ", ".join(f"{NAMES[a]} {both[a]}" for a in "AB") + " (of 3).", ""]
    out += ["## Correct files and the ten-word driver: runs with at least one `disagree` row (rows in brackets)", "", "| case | " + " | ".join(f"{NAMES[a]} frozen | {NAMES[a]} v2" for a in "AB") + " |", "|---|" + "---|---|" * 2]
    for cid in ("h2_96d2_ten_word", "f1_uartlite", "f2_timer", "f3_gpio", "f4_zb_accel"):
        cells = []
        for a in "AB":
            for res in (fr, v2):
                r = res[a][cid]
                rows = sum(len(x["disagree_rows"]) for x in r["runs"] if not x["failed"])
                cells.append(f"{r['runs_with_a_disagree']} ({rows})")
        out.append(f"| {cid} | " + " | ".join(cells) + " |")
    out += ["", "h2 pre-registered pass (no `disagree` row on the three mask attributes), runs out of 3: " + ", ".join(f"{NAMES[a]} {3 - fr[a]['h2_96d2_ten_word']['runs_with_a_mask_disagree']}" for a in "AB"), ""]
    out += ["## Cost and size per reader call (medians of 3; the plan's own estimate, not a charge)", "",
            "| case | " + " | ".join(f"{NAMES[a]} s | out tok | in tok | est USD | facts | quotes found" for a in "AB") + " |", "|---|" + "---|---|---|---|---|---|" * 2]
    for cid in fr["A"]:
        cells = []
        for a in "AB":
            runs = [x for x in fr[a][cid]["runs"] if not x["failed"]]
            m = fr[a][cid]["median"]
            cells += [f"{m['seconds']}", f"{m['output_tokens']:.0f}", f"{statistics.median([inp(x) for x in runs]):.0f}", f"{m['plan_cost_estimate_usd']}", f"{m['facts']:.0f}", f"{m['quote_ok_share']}"]
        out.append(f"| {cid} | " + " | ".join(cells) + " |")
    out += ["", "Totals over the 33 calls of an arm: " + "; ".join(
        f"{NAMES[a]} {sum(x['seconds'] or 0 for c in fr[a].values() for x in c['runs']):.0f} s, {sum(x['output_tokens'] or 0 for c in fr[a].values() for x in c['runs'])} output tokens, "
        f"plan estimate {sum(x['plan_cost_estimate_usd'] or 0 for c in fr[a].values() for x in c['runs']):.2f} USD" for a in "AB") + ".", ""]
    out += ["## Reader validity", "", "| arm | facts | quotes not found | repairs used | reader problems listed |", "|---|---|---|---|---|"]
    for a in "AB":
        runs = [x for c in fr[a].values() for x in c["runs"] if not x["failed"]]
        facts = sum(x["facts"] for x in runs)
        out.append(f"| {NAMES[a]} | {facts} | {sum(round(x['facts'] * (1 - x['quote_ok_share'])) for x in runs if x['quote_ok_share'] is not None)} | {sum(x['repairs'] or 0 for x in runs)} | {sum(x['reader_problems'] for x in runs)} |")
    out += [""]
    out += ["## Per-run status counts (frozen comparator)", "", "| run | agree | disagree | not_in_code | mentioned | other_variant |", "|---|---|---|---|---|---|"]
    for a in "AB":
        for cid, r in fr[a].items():
            for x in r["runs"]:
                s = x["status_counts"]
                out.append(f"| {x['run']} | {s.get('agree', 0)} | {s.get('disagree', 0)} | {s.get('not_in_code', 0)} | {s.get('mentioned', 0)} | {s.get('other_variant', 0)} |")
    (HERE / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("wrote RESULTS.md")


if __name__ == "__main__":
    main()
