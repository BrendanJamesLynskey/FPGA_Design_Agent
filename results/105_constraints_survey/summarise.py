#!/usr/bin/env python3
"""Brief 105: turn raw/<variant>/metrics.txt (written by flow/tests/fixtures/constraints_survey/measure.tcl) into results.md.

    python3 results/105_constraints_survey/summarise.py
"""
from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
RAW = HERE / "raw"


def metrics(v: str) -> dict[str, str]:
    f = RAW / v / "metrics.txt"
    if not f.exists():
        return {}
    return dict(l.split(" ", 1) for l in f.read_text().splitlines() if " " in l)


def mtbf_min(v: str) -> str:
    f = RAW / v / "mtbf.rpt"
    if not f.exists() or f.stat().st_size == 0:
        return "no report written (Power 33-219: no identified synchronizers)"
    t = f.read_text()
    vals = [float(x) for x in re.findall(r"\|\s*\d+\s*\|\s*([0-9.e+]+) years", t)]
    s = re.search(r"\| Synchronizers\s*\|\s*(\d+)\s*\|\s*([0-9.e+]+) years", t)
    return f"{s.group(1)} chains, overall {s.group(2)} years, worst chain {min(vals):.3g} years" if s and vals else "unparsed"


def bus_skew(v: str) -> str:
    f = RAW / v / "bus_skew.rpt"
    if not f.exists():
        return "n/a"
    t = f.read_text()
    if "No bus skew constraints" in t:
        return "No bus skew constraints"
    m = re.search(r"\]\s+(Slow|Fast)\s+([0-9.]+)\s+([0-9.]+)\s+(-?[0-9.]+)\s*$", t, re.M)
    return f"requirement {m.group(2)}, actual {m.group(3)}, slack {m.group(4)} ns" if m else "unparsed"


def rule_rows(v: str, rpt: str, ids: tuple[str, ...]) -> str:
    f = RAW / v / rpt
    if not f.exists():
        return "n/a"
    t = f.read_text()
    hit = [i for i in ids if re.search(rf"\b{re.escape(i)}\b", t)]
    return ", ".join(hit) if hit else "none"


def main() -> None:
    out = ["# results/105_constraints_survey: measurements (generated by summarise.py; do not edit)", ""]
    out += ["## M1: ASYNC_REG present against absent (24 independent 2-flop synchronisers, clk_a 10 ns to clk_b 3 ns, out-of-context, Vivado 2026.1)", "",
            "| Variant | Part | Chains in the same slice | Mean / max slice distance s1 to s2 | Mean / max s1 to s2 delay (ns) | SRL cells | ASYNC_REG cells | MTBF report | TIMING-10 | CDC rows |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for v in ("m1_a7_attr", "m1_a7_plain", "m1_k26_attr", "m1_k26_plain"):
        m = metrics(v)
        if not m:
            continue
        mt = mtbf_min(v) if "k26" in v else "not available on 7-series"
        out.append(f"| {v} | {m['part']} | {m['chains_in_same_slice']} of {m['chains']} | {m['mean_slice_distance']} / {m['max_slice_distance']} | "
                   f"{m['mean_s1_to_s2_delay_ns']} / {m['max_s1_to_s2_delay_ns']} | {m['srl_cells']} | {m['async_reg_cells']} | {mt} | "
                   f"{rule_rows(v, 'methodology.rpt', ('TIMING-10',))} | {rule_rows(v, 'cdc.rpt', ('CDC-2', 'CDC-3', 'CDC-5', 'CDC-6'))} |")
    out += ["", "## M2: MAX_FANOUT and DONT_TOUCH on one enable register driving 3000 flops (xc7a100t, clk 2.7 ns, out-of-context)", "",
            "| Variant | Attribute on `go` | Worst path from `go`: slack / delay (ns) | Design WNS (ns) | Copies of `go` | Largest fanout | Total flops |", "|---|---|---|---|---|---|---|"]
    names = {"m2_0": "none", "m2_1": "MAX_FANOUT=100", "m2_2": "MAX_FANOUT=100 + DONT_TOUCH", "m2_3": "DONT_TOUCH"}
    for v, a in names.items():
        m = metrics(v)
        if m:
            out.append(f"| {v} | {a} | {m['go_path_wns']} / {m['go_path_delay_ns']} | {m['wns']} | {m['go_register_cells']} | {m['max_go_fanout']} | {m['ff_count']} |")
    out += ["", "## M3: bus skew on a 16-bit Gray pointer (xc7a100t, clk_a 10 ns to clk_b 6 ns, out-of-context)", "",
            "| Variant | Exceptions | WNS (ns) | Datapath delay min / max / spread (ns) | Bus-skew report |", "|---|---|---|---|---|"]
    names = {"m3_a": "none", "m3_b": "set_max_delay -datapath_only 10", "m3_c": "datapath-only plus set_bus_skew 6", "m3_d": "datapath-only plus set_bus_skew 0.25"}
    for v, a in names.items():
        m = metrics(v)
        if m:
            out.append(f"| {v} | {a} | {m['wns']} | {m['delay_min_ns']} / {m['delay_max_ns']} / {m['delay_spread_ns']} | {bus_skew(v)} |")
    (HERE / "results.md").write_text("\n".join(out) + "\n")
    print("wrote", HERE / "results.md")


if __name__ == "__main__":
    main()
