#!/usr/bin/env python3
"""Brief 106: the three measurements, from committed records only (no model call, no Vivado).

1. the derived-constants gate, back-tested on the six 82P3 run records (public RTL and the task spec);
2. the stale-data check's comparison, run on every committed build manifest;
3. plan repeatability over the 82P2 and 82P3 run records.

    python3 results/106_orchestrator/analyse.py        # writes results.json and results.md next to this file
"""
from __future__ import annotations

import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from flow import derived_constants as DC      # noqa: E402
from flow import plan_repeat as PR            # noqa: E402
from flow import stale_check as SC            # noqa: E402

HERE = Path(__file__).parent
RUNS = ROOT / "benchmark" / "v2" / "runs"
SPEC = ROOT / "benchmark" / "v2" / "tasks" / "v2_e_udp_endpoint" / "spec.md"


def design_id_of(rtl: Path, spec: Path) -> tuple[int | None, list[dict]]:
    with tempfile.TemporaryDirectory() as td:
        d = Path(td) / "d"
        shutil.copytree(rtl, d / "rtl")
        shutil.copy(spec, d / "spec.md")
        t = DC.derive(d, Path(td))
    b = t["design_id_bindings"]
    return (b[0]["value"] if b else None), [f for f in t["findings"] if f["blocking"]]


def backtest_82p3() -> list[dict]:
    rows = []
    for rec in sorted((RUNS / "b82p3" / "records").glob("*.json")):
        r = json.loads(rec.read_text())
        art = RUNS / "b82p3" / "artifacts" / r["run_id"]
        score = json.loads((art / "hidden_score.json").read_text())
        val, blocking = design_id_of(art / "rtl", SPEC)
        rows.append({"arm": r["arm"], "repeat": r["repeat"], "run_id": r["run_id"], "bound_design_id": f"0x{val:08X}" if val is not None else None,
                     "gate": "FAIL (CONST-ID-01)" if blocking else "pass", "hidden_pass": bool(score.get("pass")),
                     "tests": f"{sum(score['tests'].values())}/{len(score['tests'])}" if isinstance(score.get("tests"), dict) else None})
    return rows


def manifests() -> dict:
    out = []
    for p in sorted((ROOT / "results").rglob("manifest.json")):
        m = json.loads(p.read_text())
        if "inputs" not in m:
            continue
        c = SC.check_manifest(m, ROOT)
        out.append({"manifest": str(p.relative_to(ROOT)), "build_id": c["build_id"], "inputs": c["inputs"], "status": c["status"],
                    "changed": len(c["changed"]), "removed": len(c["removed"]),
                    "flow_changed": sum(1 for f in c["changed"] + c["removed"] if f.startswith("flow/")),
                    "design_changed": sum(1 for f in c["changed"] + c["removed"] if not f.startswith("flow/"))})
    return {"rows": out, "stale": sum(1 for r in out if r["status"] == "stale"), "total": len(out)}


def repeatability() -> dict:
    groups: dict = {}
    expected: dict = {}
    for d in ("b82p2", "b82p3"):
        groups.update(PR.load_records(RUNS / d))
    # derived parameter: the shell design ID each run's RTL binds, where the design has a shell instance
    for key, runs in groups.items():
        task = key.split(":")[1]
        spec = ROOT / "benchmark" / "v2" / "tasks" / task / "spec.md"
        did = DC.spec_table(spec.read_text())["design_id"] if spec.is_file() else None
        expected[key] = did["value"] if did else None
        for r in runs:
            art = RUNS / key.split(":")[0] / "artifacts" / str(r["run_id"]) / "rtl"
            r["params"] = None
            if art.is_dir() and spec.is_file():
                v, _ = design_id_of(art, spec)
                r["params"] = v
    return PR.score(groups, expected)


def main() -> int:
    res = {"backtest_82p3": backtest_82p3(), "stale_manifests": manifests(), "repeatability": repeatability()}
    (HERE / "results.json").write_text(json.dumps(res, indent=1) + "\n")
    L = ["# results/106_orchestrator (generated by analyse.py from committed records; no number typed by hand)", ""]
    L += ["## 1. Derived-constants gate on the 82P3 runs", "",
          "| Arm | Repeat | Run id | Shell DESIGN_ID bound in the RTL | Gate | Hidden bench |", "|---|---|---|---|---|---|"]
    for r in res["backtest_82p3"]:
        L.append(f"| {r['arm']} | {r['repeat']} | {r['run_id']} | {r['bound_design_id']} | {r['gate']} | {'pass' if r['hidden_pass'] else 'fail'}" + (f" ({r['tests']})" if r["tests"] else "") + " |")
    rows = res["backtest_82p3"]
    fl = [r for r in rows if r["gate"] != "pass"]
    L += ["", f"Gate flags {len(fl)} of {len(rows)} runs; {sum(1 for r in fl if not r['hidden_pass'])} of the {sum(1 for r in rows if not r['hidden_pass'])} failures; "
              f"{sum(1 for r in fl if r['hidden_pass'])} of the {sum(1 for r in rows if r['hidden_pass'])} passes. The spec's derived value is 0x55455031 (\"UEP1\").", ""]
    sm = res["stale_manifests"]
    L += ["## 2. Stale check on every committed build manifest", "",
          f"{sm['stale']} of {sm['total']} manifests under `results/` are stale against the files in this checkout.", "",
          "| Manifest | Build ID | Inputs | Changed | Gone | of which flow/ | of which design |", "|---|---|---|---|---|---|---|"]
    for r in sm["rows"]:
        L.append(f"| {r['manifest']} | {r['build_id']} | {r['inputs']} | {r['changed']} | {r['removed']} | {r['flow_changed']} | {r['design_changed']} |")
    rp = res["repeatability"]
    L += ["", "## 3. Plan repeatability (82P2 and 82P3 run records)", "",
          "| Group | Runs | Without a stage record | Collapsed plans | Visit counts | Equal-plan pairs | Equal-visit pairs | Equal design-ID pairs | Runs binding the spec's design ID |", "|---|---|---|---|---|---|---|---|---|"]
    for k, g in rp["groups"].items():
        plans = "; ".join(">".join(map(str, p)) if p else "-" for p in g["plans"])
        L.append(f"| {k} | {g['runs']} | {g['no_plan']} | {plans} | {g['visit_counts']} | {g['plan']['equal_pairs']}/{g['plan']['pairs']} | {g['visits']['equal_pairs']}/{g['visits']['pairs']} | {g['params']['equal_pairs']}/{g['params']['pairs']} | {str(g['correct']['equal_pairs']) + '/' + str(g['correct']['pairs']) if 'correct' in g else 'no quoted ID'} |")
    t = rp["total"]
    fmt = lambda x: f"{x['equal_pairs']}/{x['pairs']}" + (f" = {x['rate']:.2f}" if x["rate"] is not None else "")
    L += ["", f"Total: plan (stage order) {fmt(t['plan'])}; visits (order and repeats) {fmt(t['visits'])}; equal design-ID pairs {fmt(t['params'])}; runs binding the spec's design ID {t['correct']['equal_pairs']}/{t['correct']['pairs']}.", ""]
    (HERE / "results.md").write_text("\n".join(L))
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
