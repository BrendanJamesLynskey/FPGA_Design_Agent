#!/usr/bin/env python3
"""Brief 33: turn raw/<label>/call.json (+ run.json, result_hash.json, stages.txt) into results.md and summary.json.

    python3 results/33_vivado_speed/summarise.py

Every number in the brief 33 report comes from this file's output. Sections:
1. thread counts: wall time, per-stage time, peak memory and the result hashes per design and thread count;
2. the build cache: an agent run's build sequence (synth, synth, route x4, bitstream) with the cache, against the same
   sequence without it, modelled from the fresh builds' own stage timestamps (stated as such);
3. incremental implementation;
4. reports: the share of each build spent in the report steps.
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RAW = HERE / "raw"


def load(label: str) -> dict | None:
    d = RAW / label
    if not (d / "call.json").is_file():
        return None
    c = json.loads((d / "call.json").read_text())
    for f in ("run.json", "result_hash.json"):
        if (d / f).is_file():
            c[f[:-5]] = json.loads((d / f).read_text())
    if (d / "stages.txt").is_file():
        c["stages"] = {l.split()[0]: float(l.split()[1]) for l in (d / "stages.txt").read_text().splitlines() if l.strip()}
    return c


def peak(c: dict) -> int | None:
    r = c.get("run") or {}
    return r.get("scope_anon_peak_mib") or c.get("scope_anon_peak_mib")


def hashes(c: dict) -> tuple[str, str]:
    h = c.get("result_hash") or {}
    return (h.get("placement_sha256", "")[:12], h.get("routing_sha256", "")[:12])


def stage_split(st: dict) -> dict:
    """Seconds per part of the flow, from the cumulative stage log of a full fresh build."""
    g = lambda k: st.get(k)          # noqa: E731
    out = {}
    if "constraints" in st and "synth_reports" not in st:          # the CDC rig's own build script (hil/cdc_soak)
        out["synth"] = g("synth")
        out["opt_place_physopt"] = round(g("phys_opt") - g("constraints"), 1)
        out["route"] = round(g("route") - g("phys_opt"), 1)
        out["route_reports"] = round(g("reports") - (g("result_dump") or g("route")), 1)
        out["bitstream"] = round(g("bitstream") - g("reports"), 1)
        return out
    if g("synth_reports") is not None:
        out["synth"] = g("synth")
        out["synth_reports"] = round(g("synth_reports") - g("synth"), 1)
        out["rtl_elab"] = g("rtl_reports")
    if g("place_reports") is not None:
        out["opt_place_physopt"] = round(g("phys_opt") - g("synth_reports"), 1)
    if g("route") is not None:
        out["route"] = round(g("route") - g("place_reports"), 1)
    if g("reports") is not None:
        out["route_reports"] = round(g("reports") - (g("result_dump") or g("route")), 1)
    if g("bitstream") is not None:
        out["bitstream"] = round(g("bitstream") - g("reports"), 1)
    return out


def main() -> int:
    lines = ["# Brief 33 measurements (generated by summarise.py from raw/)", ""]
    summary: dict = {"threads": {}, "cache": {}, "incremental": {}, "reports": {}}
    designs = {"c10": "build/bench/c10_dds_sine (small: 1.2k LUT)",
               "c13": "build/bench/c13_nexys_harris_vga (mid: 11k LUT)",
               "rig": "hil/cdc_soak full (large: 36k LUT, 56%)"}
    lines += ["## 1. Thread counts (fresh full builds, no cache)", "",
              "| design | run | threads | wall s | wall s without the hash dump | hash dump s | synth s | opt+place+phys_opt s | route s | route reports s | bitstream s "
              "| peak anon MiB | placement hash | routing hash | WNS ns | gates |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for key in ("c10", "c13", "rig"):
        for lab in sorted(p.name for p in RAW.glob(f"{key}_t*")):
            c = load(lab)
            if not c:
                continue
            sp = stage_split(c.get("stages", {}))
            ph, rh = hashes(c)
            st = c.get("stages", {})
            dump = round(st["result_dump"] - st["route"], 1) if "result_dump" in st else 0.0
            sp["wall_no_dump"] = round(c["wall_s"] - dump, 1)
            lines.append(f"| {key} | {lab} | {c['threads']} | {c['wall_s']} | {sp['wall_no_dump']} | {dump} | {sp.get('synth', '')} | "
                         f"{sp.get('opt_place_physopt', '')} | {sp.get('route', '')} | {sp.get('route_reports', '')} | "
                         f"{sp.get('bitstream', '')} | {peak(c)} | {ph} | {rh} | {c.get('wns_ns')} | "
                         f"{'pass' if c.get('gates_pass') else ('-' if key == 'rig' else 'FAIL')} |")
            summary["threads"][lab] = {"design": key, "threads": c["threads"], "wall_s": c["wall_s"], "split": sp,
                                       "peak_anon_mib": peak(c), "placement": ph, "routing": rh, "wns_ns": c.get("wns_ns"),
                                       "gates_pass": c.get("gates_pass"), "exit_code": c.get("exit_code")}
    lines += ["", "Hashes: flow/result_hash.py over every placed cell's site and BEL and every net's route (first 12 hex "
              "digits shown). Peak anon: the systemd scope's largest anonymous memory (all processes), polled every 2 s.", ""]

    lines += ["## 2. Build cache: one agent run's build sequence", ""]
    for key in ("c10", "c13"):
        seq = [load(p.name) for p in sorted(RAW.glob(f"{key}_seq*"))]
        seq = [s for s in seq if s]
        t4 = load(f"{key}_t4_a")
        if not seq or not t4:
            continue
        st = t4["stages"]
        startup = round(t4["wall_s"] - st["bitstream"], 1)             # Vivado start-up and the runner's own work
        fresh = {"synth": round(st["synth_reports"] + startup, 1), "route": round(st["reports"] + startup, 1),
                 "bitstream": t4["wall_s"]}
        model = [fresh[s["stop"]] for s in seq]
        lines += [f"### {designs[key]}", "",
                  "| call | until | cache | wall s (measured, with cache) | wall s without cache (modelled) |", "|---|---|---|---|---|"]
        for i, (s, m) in enumerate(zip(seq, model), 1):
            lines.append(f"| {i} | {s['stop']} | {s['cache']} | "
                         f"{s['wall_s']} | {m} |")
        tot_c, tot_m = round(sum(s["wall_s"] for s in seq), 1), round(sum(model), 1)
        final = seq[-1]
        same = hashes(final) == hashes(t4) and final.get("wns_ns") == t4.get("wns_ns")
        lines += [f"| total | | | **{tot_c}** | **{tot_m}** |", "",
                  f"Saved: {round(tot_m - tot_c, 1)} s of {tot_m} s ({round(100 * (tot_m - tot_c) / tot_m)}%). "
                  f"The final (resumed) build's placement/routing hashes and WNS "
                  f"{'match' if same else 'DO NOT match'} the fresh 4-thread build {key}_t4_a "
                  f"({hashes(final)} vs {hashes(t4)}, WNS {final.get('wns_ns')} vs {t4.get('wns_ns')}). "
                  f"Gates of the final build: {'pass' if final.get('gates_pass') else 'FAIL'}.", "",
                  f"Model: a fresh build stopped at synth costs the fresh full build's time to `synth_reports` plus "
                  f"its start-up and runner overhead ({startup} s: wall time minus the last stage timestamp); stopped "
                  f"at route, its time to `reports` plus the same; to the bitstream, its measured wall time.", ""]
        summary["cache"][key] = {"with_cache_s": tot_c, "without_cache_model_s": tot_m, "same_result": same,
                                 "calls": [{"stop": s["stop"], "cache": s["cache"], "wall_s": s["wall_s"]} for s in seq]}

    inc = {lab: load(lab) for lab in ("c13inc_1_ref", "c13inc_2_small_incremental", "c13inc_3_small_default",
                                      "c13inc_4_large_incremental")}
    if any(inc.values()):
        lines += ["## 3. Incremental implementation (mid design, 4 threads, until route)", "",
                  "| run | change | wall s | opt+place+phys_opt s | route s | WNS ns | gates to route | reuse (report_incremental_reuse, current) |",
                  "|---|---|---|---|---|---|---|---|"]
        what = {"c13inc_1_ref": "reference build", "c13inc_2_small_incremental": "one constant (DESIGN_ID), incremental",
                "c13inc_3_small_default": "the same change, default flow",
                "c13inc_4_large_incremental": "core resized (W 80->64, H 60->48), incremental"}
        for lab, c in inc.items():
            if not c:
                continue
            sp = stage_split(c.get("stages", {}))
            rr = RAW / lab / "incremental_reuse.rpt"
            reuse = ""
            if rr.is_file():
                for l in rr.read_text().splitlines():
                    cols = [c.strip() for c in l.strip().strip("|").split("|")]
                    if cols and cols[0] in ("Cells", "Nets") and len(cols) >= 4:
                        reuse += f"{cols[0].lower()} {cols[3]}% reused; "
            g = c.get("gates") or {}
            upto = all(v for k, v in g.items() if k != "bitstream_present") if g else None
            lines.append(f"| {lab} | {what[lab]} | {c['wall_s']} | {sp.get('opt_place_physopt', '')} | {sp.get('route', '')} "
                         f"| {c.get('wns_ns')} | {'pass' if upto else 'FAIL'} | {reuse} |")
            summary["incremental"][lab] = {"wall_s": c["wall_s"], "split": sp, "wns_ns": c.get("wns_ns"), "reuse": reuse}
        lines.append("")

    lines += ["## 4. Report time per build (fresh 4-thread builds)", "", "| design | synth reports s | route reports s | "
              "wall s | reports share |", "|---|---|---|---|---|"]
    for key in ("c10", "c13", "rig"):
        c = load(f"{key}_t4_a") or load(f"{key}_t4") or load(f"{key}_t2")
        if not c:
            continue
        st = c["stages"]
        if key == "rig":
            rep = round(st["reports"] - (st.get("result_dump") or st["route"]), 1)
            srep = 0.0
            c = dict(c, wall_s=round(c["wall_s"] - ((st["result_dump"] - st["route"]) if "result_dump" in st else 0), 1))
        else:
            sp = stage_split(st)
            rep, srep = sp["route_reports"], sp["synth_reports"]
        lines.append(f"| {key} | {srep} | {rep} | {c['wall_s']} | {round(100 * (rep + srep) / c['wall_s'])}% |")
        summary["reports"][key] = {"synth_reports_s": srep, "route_reports_s": rep, "wall_s": c["wall_s"]}
    lines.append("")

    t1 = {lab: load(lab) for lab in ("t1_base", "t1_ila_resumed", "t1_ila_fresh")}
    if all(t1.values()):
        lines += ["## 5. The ILA variant started from the base build (designs/t1_dimmer_counter, 4 threads)", "",
                  "| run | cache | wall s | placement hash | routing hash | WNS ns | failed gates |", "|---|---|---|---|---|---|---|"]
        for lab, c in t1.items():
            g = json.loads((RAW / lab / "gates.json").read_text())
            cache = json.loads((RAW / lab / "cache.json").read_text())["action"] if (RAW / lab / "cache.json").is_file() else ""
            ph, rh = hashes(c)
            bad = ", ".join(k for k, v in g["gates"].items() if not v) or "none"
            lines.append(f"| {lab} | {cache} | {c['wall_s']} | {ph} | {rh} | {g['timing']['wns_ns']} | {bad} |")
            summary.setdefault("ila", {})[lab] = {"cache": cache, "wall_s": c["wall_s"], "placement": ph, "routing": rh,
                                                  "wns_ns": g["timing"]["wns_ns"], "failed": bad}
        lines += ["", "`exceptions_clean` fails on both ILA builds alike: the ILA core's own timing exceptions are reported "
                  "as ignored (non-existent path). It is a property of the ILA variant on main, not of the resume.", ""]
    (HERE / "results.md").write_text("\n".join(lines) + "\n")
    (HERE / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
