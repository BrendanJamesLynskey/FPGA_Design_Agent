#!/usr/bin/env python3
"""Brief 49: the FSM reference controller's tables and the site's summary numbers on Vivado 2026.1.

    python3 results/24_fsm_2026_1/make_tables.py

Reads synth/*.kv and impl/*.kv (written by flow/tests/fixtures/fsm_discipline/run_all.sh on 2026.1, xc7a100tcsg324-1,
2.5 ns, out of context) and writes synth_table.json, impl_table.json, impl_table.md and summary.json. The `fsm` field (the
encoding Vivado chose, from the synthesis log) is copied from results/24_fsm only where this run's synthesis key/values are
identical to the earlier release's (all 37 are). Coverage (simulation, no Vivado) is read from results/24_fsm/coverage.
"""
import json
from pathlib import Path

R = Path(__file__).resolve().parent
OLD = R.parent / "24_fsm"


def kv(p):
    return dict(l.split(None, 1) for l in p.read_text().splitlines() if len(l.split(None, 1)) == 2)


def table(kind):
    old = json.loads((OLD / f"{kind}_table.json").read_text())["variants"]
    oldsyn = json.loads((OLD / "synth_table.json").read_text())["variants"]
    out = {}
    for p in sorted((R / kind).glob("*.kv")):
        v = kv(p)
        n = p.stem
        o = oldsyn.get(n, {})
        if "fsm" in old.get(n, {}) and all(v.get(k) == o.get(k) for k in o if k != "fsm"):
            v["fsm"] = old[n]["fsm"]
        out[n] = v
    return {"vivado": "2026.1", "period_ns": 2.5, "variants": out}


s, i = table("synth"), table("impl")
(R / "synth_table.json").write_text(json.dumps(s, indent=1) + "\n")
(R / "impl_table.json").write_text(json.dumps(i, indent=1) + "\n")
cols = ["LUT_route", "FF_route", "CTRLSETS_route", "WNS_fsm_route", "WNS_in2r_route", "WNS_r2out_route", "WHS_route"]
md = ["# Reference controller, routed (Vivado 2026.1, out of context, xc7a100tcsg324-1)", "",
      "Clock 2.5 ns, input and output delay 0.5 ns. Slack in ns; negative = the path is longer than the budget. After opt_design,",
      "place_design and route_design. Generated by `make_tables.py` from `impl/*.kv`.", "",
      "| variant | encoding | " + " | ".join(cols) + " |", "|---|---|" + "---|" * len(cols)]
for n, v in i["variants"].items():
    md.append(f"| {n} | {v.get('fsm', '-')} | " + " | ".join(v.get(c, "-") for c in cols) + " |")
(R / "impl_table.md").write_text("\n".join(md) + "\n")
f = lambda n, k: float(i["variants"][n][k])  # noqa: E731
cov = json.loads((OLD / "coverage" / "summary.json").read_text())
summary = {
    "vivado": "2026.1",
    "separation": {"sep_states": 11, "mono_states": 23, "sep_transitions": 13, "mono_transitions": 39,
                   "sep_lut": int(f("sep_base", "LUT_route")), "mono_lut": int(f("mono_base", "LUT_route")),
                   "sep_ff": int(f("sep_base", "FF_route")), "mono_ff": int(f("mono_base", "FF_route"))},
    "outputs": {"comb_slack_ns": f("sep_base", "WNS_r2out_route"), "registered_slack_ns": f("sep_out1", "WNS_r2out_route"),
                "lookahead_slack_ns": f("sep_out2", "WNS_r2out_route"), "registered_latency_extra_clocks": 1, "lookahead_latency_extra_clocks": 0},
    "ratio": {"none": f("ratio_n4_nomc", "WNS_fsm_route"), "n2": f("ratio_n2_mc", "WNS_fsm_route"),
              "n4": f("ratio_n4_mc", "WNS_fsm_route"), "n8": f("ratio_n8_mc", "WNS_fsm_route"), "clock_period_ns": 2.5},
    "coverage": {"designs": len(cov), "designs_passing": sum(1 for r in cov if r["pass"]), "mutants": sum(len(r["mutants"]) for r in cov),
                 "mutants_caught": sum(1 for r in cov for m in r["mutants"] if not m["pass"])},
    "formal": {"sep_induction_depth": 6, "mono_induction_depth": 5},
}
(R / "summary.json").write_text(json.dumps(summary, indent=1) + "\n")
print(json.dumps(summary))
