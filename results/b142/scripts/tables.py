#!/usr/bin/env python3
"""Write tables.md from the Yosys records and the Vivado synthesis-stage reports (brief 142). Run after summarize.py's inputs exist."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
import summarize as s
from manifest import BENCH

HERE = s.HERE


def f(x):
    if x is None:
        return "n/a"
    if "error" in x:
        return "ERROR"
    parts = [f"LUT {x['lut']}", f"FF {x['ff']}"]
    if x["carry4"] or x["carry8"]:
        parts.append("CARRY " + "+".join(p for p in (f"{x['carry4']}x4" if x["carry4"] else "", f"{x['carry8']}x8" if x["carry8"] else "") if p))
    for k, lab in (("f7", "F7"), ("f8", "F8"), ("f9", "F9"), ("dsp", "DSP"), ("bram18", "B18"), ("bram36", "B36"), ("uram", "URAM"), ("srl", "SRL"), ("lutram", "LUTRAM")):
        if x[k]:
            parts.append(f"{lab} {x[k]}")
    if x.get("levels") is not None:
        parts.append(f"lvl {x['levels']}")
    return ", ".join(parts)


def main():
    y, v = s.yosys_all(), s.vivado_all()
    out = ["# brief 142 tables (generated by scripts/tables.py; do not edit)\n",
           "Counts are synthesis-stage cell counts: Yosys `stat -tech xilinx` on the top module; Vivado `report_utilization` Primitives table after `synth_design -mode out_of_context`.",
           "CARRY is cells by width (`8x4` = eight CARRY4). `lvl` is Vivado's logic levels on the worst path at the synthesis stage (2.0 ns on K26, 3.5 ns on xc7a100t; unplaced).",
           "Yosys variants: def, flat (-flatten), tuned (-flatten -widemux 5, plus -uram on xcup), dff (-flatten -dff), c8 (flat + draft CARRY8 techmap).\n"]
    for part, fam, label in (("k26", "xcup", "K26 (xck26) against Yosys -family xcup"), ("a7", "xc7", "xc7a100t (control) against Yosys -family xc7")):
        out += [f"\n## {label}\n", "| design | Vivado 2026.1 synth | Yosys def | Yosys flat | Yosys tuned | Yosys dff |" + (" Yosys c8 |" if fam == "xcup" else ""),
                "|---|---|---|---|---|---|" + ("---|" if fam == "xcup" else "")]
        for n in BENCH:
            vv = v.get((part, "viv_default", n), {}).get("synth")
            if vv is None and fam == "xc7" and not n.startswith(("m", "r0", "r10")):
                continue
            row = [n, f(vv)] + [f(y.get((fam, var, n))) for var in ("def", "flat", "tuned", "dff")]
            if fam == "xcup":
                row.append(f(y.get((fam, "c8", n))))
            out.append("| " + " | ".join(row) + " |")
    (HERE / "tables.md").write_text("\n".join(out) + "\n")
    print("tables.md written")


main()
