#!/usr/bin/env python3
"""Write impl_table.md: Vivado 2026.1 place and route on xck26 of Vivado's own synthesis (viv_impl), the Yosys netlist (ys_flat) and the Yosys netlist with the draft CARRY8 map (ys_c8) (brief 142)."""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
V = HERE / "vivado" / "k26"
CLK = 2.5


def grab(text, label):
    m = re.search(r"^\|\s*" + re.escape(label) + r"\*?\s*\|\s*(\d+)", text, re.M)
    return int(m.group(1)) if m else 0


def rec(arm, name):
    d = V / arm / name
    if not (d / "utilization_impl.rpt").exists():
        return None
    u = (d / "utilization_impl.rpt").read_text()
    t = (d / "timing_summary.rpt").read_text()
    m = re.search(r"WNS\(ns\).*\n\s*-+.*\n\s*(-?[\d.]+)", t)
    wns = float(m.group(1)) if m else None
    return {"lut": grab(u, "CLB LUTs"), "ff": grab(u, "CLB Registers"), "c8": grab(u, "CARRY8"), "dsp": grab(u, "DSPs"),
            "wns": wns, "fmax": (1000 / (CLK - wns)) if wns is not None else None}


def cell(r):
    if r is None:
        return "n/a"
    return f"LUT {r['lut']}, FF {r['ff']}, CARRY8 {r['c8']}, DSP {r['dsp']}, WNS {r['wns']:+.3f}, Fmax {r['fmax']:.0f}"


names = sorted({p.name for a in ("viv_impl", "ys_flat", "ys_c8") if (V / a).exists() for p in (V / a).iterdir()})
out = ["# brief 142: Vivado 2026.1 place and route on xck26-sfvc784-2LV-c (generated by scripts/impl_table.py)\n",
       f"Out of context, clock period {CLK} ns (so Fmax = 1000 / ({CLK} - WNS) MHz, the unconstrained-port limit of an OOC run), default directives, one thread. WNS in ns.\n",
       "| design | Vivado synthesis | Yosys flat (CARRY4 netlist) | Yosys flat + draft CARRY8 map |", "|---|---|---|---|"]
for n in names:
    out.append(f"| {n} | {cell(rec('viv_impl', n))} | {cell(rec('ys_flat', n))} | {cell(rec('ys_c8', n))} |")
(HERE / "impl_table.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
