#!/usr/bin/env python3
"""Writes results.md from the committed records of brief 107 (level1_probe*.json, replay_proof.json). No model call."""

import json
from pathlib import Path

D = Path(__file__).resolve().parent
out = ["# 107 deterministic mode: measurements (generated by analyse.py)", ""]
out += ["## Level 1: identical-output rate at temperature 0 (OpenRouter)", "",
        "Pre-registered in `preregistration.md` (model 1); the second model was added after seeing the first (amendment in that file).",
        "Identical-output rate of a prompt = the share of its calls whose reply equals the most common reply. Each prompt was sent 10 times.", "",
        "| model | arm | mean identical-output rate | prompts with 10 of 10 identical | rate per prompt (5 prompts) | providers |", "|---|---|---|---|---|---|"]
for f in sorted(D.glob("level1_probe*.json")):
    d = json.loads(f.read_text())
    for arm, v in d["arms"].items():
        provs: dict = {}
        for p in v["prompts"]:
            for k, n in p["providers"].items():
                provs[k] = provs.get(k, 0) + n
        out.append(f"| {d['model']} | {arm} | {v['mean_identical_rate']} | {v['fully_identical_prompts']} of {len(v['prompts'])} | "
                   + ", ".join(str(p["identical_rate"]) for p in v["prompts"]) + " | " + ", ".join(f"{k} {n}" for k, n in sorted(provs.items())) + " |")
    fails = sum(p["failed"] for v in d["arms"].values() for p in v["prompts"])
    out.append(f"| {d['model']} | (calls that failed twice and were excluded) | {fails} | | | |")
r = json.loads((D / "replay_proof.json").read_text())
out += ["", "## Level 2: a recorded run and its replay (scripted T1 episode through the whole stage graph)", "",
        f"- Recorded run: {r['record']['tape']['calls_recorded']} model calls, {r['record']['core_tool_calls']} tool calls dispatched by the core, "
        f"{r['record']['files_written']} files written by the model.",
        f"- Replay with no model client: served {r['replay']['tape']['served_from_tape']} calls from the tape, "
        f"live calls {r['replay']['tape']['live_calls']}, misses {r['replay']['tape']['replay_misses']}, unused recordings {r['replay']['tape']['unused_recordings']}.",
        f"- Same tool calls (SHA-256 equal): {r['identical']['core_tool_calls_sha256']}; same files written (SHA-256 equal): {r['identical']['files_sha256']}; "
        f"exact: {r['exact']}.",
        f"- Level recorded in the replay run's `config.json`: {r['replay_run_record_determinism']['level']} ({r['replay_run_record_determinism']['level_meaning']}).",
        "", "## Plan repeatability (brief 106's score) on the record and its replay", ""]
t = r["plan_repeatability"]["total"]
out += [f"- Stage plan: {t['plan']['equal_pairs']} of {t['plan']['pairs']} pairs equal (rate {t['plan']['rate']}); full visit sequence: "
        f"{t['visits']['equal_pairs']} of {t['visits']['pairs']} (rate {t['visits']['rate']}). The episode includes a rewind, so the sequence is not a straight line.",
        "- For contrast, brief 106 measured the full visit sequence equal in 6 of 14 pairs across live runs of the same request (`results/106_orchestrator/results.md`).", ""]
(D / "results.md").write_text("\n".join(out))
