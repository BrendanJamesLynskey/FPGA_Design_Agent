#!/usr/bin/env python3
"""A smoke design for a catalogue board, built from the board's own file (brief 95).

    python3 tools/board_smoke.py gen <board>       # write boards/<board>/smoke/{top.sv,design.xdc,build.yaml}
    python3 tools/board_smoke.py check <board>     # fail if the committed smoke files differ from what the board file generates
    python3 tools/board_smoke.py record <board>    # results/95_boards/<board>/smoke.json from the finished build's gates.json
    python3 tools/board_smoke.py boards            # the boards that have a smoke design

The design is a free-running counter on the board clock that drives the LEDs (the slowest LED blinks about once a second), a
slide switch per LED that inverts it, a button that inverts LED 0, and, where the board has a PL UART, a banner sent at 115200
baud every ~1.3 s with the UART's receive line flipping the top LED. Its pins come only from the board file: the constraints are
written by the agent's own ``board_constraints`` tool (``agent.core.constraints.generate_xdc``) from the board's master XDC and its
``resources:`` map, so building it exercises the board file in context. Nothing in it depends on LED or button polarity.

Inputs and outputs have no timing relationship to the clock, so the inputs go through two-flop synchronisers and every I/O has a
zero delay with a false path, as in the other generated designs; no reset input is used (flops have initial values), because the
polarity of a button is not known for most boards.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from agent.core import constraints as con  # noqa: E402


def _board(board: str) -> dict:
    return yaml.safe_load((ROOT / "boards" / board / "board.yaml").read_text())


def has_smoke(board: str) -> bool:
    y = _board(board)
    return bool(y.get("smoke")) and bool(y.get("master_xdc")) and (y.get("resources") or {}).get("led") is not None


def plan(board: str) -> dict:
    y = _board(board)
    res = y["resources"]
    diff = "clk_p" in res
    leds = res["led"] if isinstance(res["led"], list) else [res["led"]]
    sws = res.get("sw") or []
    sws = sws if isinstance(sws, list) else [sws]
    return {"y": y, "diff": diff, "nled": len(leds), "nsw": len(sws), "btn": "btn" in res, "uart": "uart_rx" in res and "uart_tx" in res,
            "clk_hz": int(y["smoke"]["clk_hz"]), "banner": y["smoke"]["banner"]}


def mapping(p: dict) -> list[dict[str, str]]:
    m = [{"resource": "clk_p", "port": "clk_p"}, {"resource": "clk_n", "port": "clk_n"}] if p["diff"] else [{"resource": "clk", "port": "clk"}]
    m.append({"resource": f"led[0:{p['nled'] - 1}]" if p["nled"] > 1 else "led[0]", "port": "led"})
    if p["btn"]:
        m.append({"resource": "btn", "port": "btn"})
    if p["nsw"]:
        m.append({"resource": f"sw[0:{p['nsw'] - 1}]" if p["nsw"] > 1 else "sw[0]", "port": "sw"})
    if p["uart"]:
        m += [{"resource": "uart_rx", "port": "uart_rx"}, {"resource": "uart_tx", "port": "uart_tx"}]
    return m


def make_top(board: str, p: dict) -> str:
    n, ns, hz = p["nled"], p["nsw"], p["clk_hz"]
    msg = f"FDA smoke {p['banner']} ok\r\n"
    topb = (hz - 1).bit_length() - 1                    # $clog2(hz) - 1: bit TOPB toggles about every 0.7 to 1.4 s
    ports = [("input  logic clk_p,\n    input  logic clk_n," if p["diff"] else "input  logic clk,")]
    ports.append(f"output logic [{n - 1}:0] led" if n > 1 else "output logic led")
    if p["btn"]:
        ports.append("input  logic btn")
    if ns:
        ports.append(f"input  logic [{ns - 1}:0] sw" if ns > 1 else "input  logic sw")
    if p["uart"]:
        ports += ["input  logic uart_rx", "output logic uart_tx"]
    head = ",\n    ".join(q.rstrip(",") for q in ports)
    L = [f"// b95_smoke_top: smoke design for the {p['y']['display_name']} ({p['y']['part']}).",
         f"// Generated by tools/board_smoke.py from boards/{board}/board.yaml. Do not edit: change the board file and regenerate.",
         "// A counter on the board clock drives the LEDs; switches invert LEDs, a button inverts LED 0; where the board has a PL UART",
         "// a banner is sent at 115200 baud about every 1.3 s and the receive line flips the top LED. No LED or button polarity is assumed.",
         "", "module b95_smoke_top (", f"    {head}", ");",
         f"    localparam int CLK_HZ       = {hz};",
         "    localparam int CLKS_PER_BIT = (CLK_HZ + 57600) / 115200;",
         f"    localparam int TOPB         = {topb};   // $clog2(CLK_HZ) - 1: this counter bit toggles about once a second"]
    if p["diff"]:
        L += ["", "    logic clk;", "    IBUFDS u_clk_ibuf (.I(clk_p), .IB(clk_n), .O(clk));"]
    L += ["", "    logic [TOPB:0] cnt = '0;", "    always_ff @(posedge clk) cnt <= cnt + 1'b1;", ""]
    if ns:
        L += [f"    logic [{ns - 1}:0] sw_s;", f"    sync2 #(.WIDTH({ns})) u_sw (.clk(clk), .rst(1'b0), .d(sw), .q(sw_s));"]
    if p["btn"]:
        L += ["    logic btn_s;", "    sync2 #(.WIDTH(1)) u_btn (.clk(clk), .rst(1'b0), .d(btn), .q(btn_s));"]
    if p["uart"]:
        L += ["    logic rx_s, rx_prev = 1'b1, rx_flip = 1'b0;", "    sync2 #(.WIDTH(1), .RESET_VALUE(1'b1)) u_rx (.clk(clk), .rst(1'b0), .d(uart_rx), .q(rx_s));",
              "    always_ff @(posedge clk) begin", "        rx_prev <= rx_s;", "        if (rx_prev && !rx_s) rx_flip <= ~rx_flip;   // a start bit arrived", "    end"]
    L += ["", "    always_comb begin"]
    for i in range(n):
        e = f"cnt[TOPB - {i}]"
        if i < ns:
            e += f" ^ sw_s[{i}]" if ns > 1 else " ^ sw_s"
        if i == 0 and p["btn"]:
            e += " ^ btn_s"
        if i == n - 1 and p["uart"]:
            e += " ^ rx_flip"
        L.append(f"        led[{i}] = {e};" if n > 1 else f"        led = {e};")
    L += ["    end"]
    if p["uart"]:
        data = [ord(c) for c in msg]
        L += ["", f"    localparam int MSGLEN = {len(data)};", "    function automatic logic [7:0] msg_byte(input logic [5:0] i);",
              "        case (i)"]
        names = {13: "CR", 10: "LF"}
        L += [f"            6'd{i}: msg_byte = 8'h{b:02x};   // {names.get(b, chr(b))}" for i, b in enumerate(data)]
        L += ["            default: msg_byte = 8'h00;", "        endcase", "    endfunction", "",
              "    logic       go = 1'b0, sending = 1'b0, tx_start = 1'b0, tx_busy;", "    logic [5:0] idx = '0;", "    logic [7:0] tx_data = '0;",
              "    always_ff @(posedge clk) begin", "        go       <= (cnt == '0);", "        tx_start <= 1'b0;",
              "        if (!sending) begin", "            if (go) begin sending <= 1'b1; idx <= '0; end",
              "        end else if (!tx_busy && !tx_start) begin", "            if (idx == 6'(MSGLEN)) sending <= 1'b0;",
              "            else begin tx_data <= msg_byte(idx); tx_start <= 1'b1; idx <= idx + 1'b1; end", "        end", "    end", "",
              "    uart_tx #(.CLKS_PER_BIT(CLKS_PER_BIT)) u_tx (.clk(clk), .rst(1'b0), .start(tx_start), .data(tx_data), .busy(tx_busy), .tx(uart_tx));"]
    L += ["endmodule", ""]
    return "\n".join(L)


def make_xdc(board: str, p: dict) -> str:
    y = p["y"]
    r = con.generate_xdc(ROOT / "boards" / board, mapping(p))
    if not r["ok"]:
        raise SystemExit(f"{board}: board_constraints refused the smoke mapping: {r['errors']}")
    t = r["xdc"].replace("## design.xdc: generated by the core's board_constraints tool", f"## design.xdc: smoke design for the {y['display_name']}, generated by tools/board_smoke.py through the core's board_constraints tool")
    cfg = y.get("config")
    if cfg:
        t += f"\n## Configuration bank voltage ({'unconfirmed for this board: see board.yaml config' if cfg.get('status') else 'from the vendor XDC'})\n"
        t += f"set_property CFGBVS {cfg['cfgbvs']} [current_design];\nset_property CONFIG_VOLTAGE {cfg['config_voltage']} [current_design];\n"
    ins = (["btn"] if p["btn"] else []) + (["sw[*]"] if p["nsw"] and p["nsw"] > 1 else ["sw"] if p["nsw"] else []) + (["uart_rx"] if p["uart"] else [])
    outs = ["led[*]" if p["nled"] > 1 else "led"] + (["uart_tx"] if p["uart"] else [])
    if ins:
        t += ("\n## Asynchronous inputs: each is synchronised by two ASYNC_REG flops (sync2.sv); a zero input delay marks them\n"
              "## constrained for check_timing and the false path removes them from timing analysis.\n"
              f"set async_in [get_ports {{{' '.join(ins)}}}]\nset_input_delay -clock sys_clk_pin 0.000 $async_in\nset_false_path -from $async_in\n")
    t += (f"\n## Slow outputs: LEDs{' and the UART transmit line' if p['uart'] else ''} are registered and nothing outside samples them against the clock.\n"
          f"set slow_out [get_ports {{{' '.join(outs)}}}]\nset_output_delay -clock sys_clk_pin 0.000 $slow_out\nset_false_path -to $slow_out\n")
    return t


def make_build(board: str, p: dict) -> str:
    return (f"# How flow/run_vivado.sh builds the smoke design for {p['y']['display_name']} (paths are relative to the repo root).\n"
            f"# Generated by tools/board_smoke.py; do not edit.\ntop: b95_smoke_top\npart: {p['y']['part']}\nboard: {board}\nsources:\n"
            f"  - shell/rtl/sync2.sv\n" + ("  - shell/rtl/uart_tx.sv\n" if p["uart"] else "") + f"  - boards/{board}/smoke/top.sv\n"
            f"constraints:\n  - boards/{board}/smoke/design.xdc\ngenerics: {{}}\n")


def files(board: str) -> dict[str, str]:
    p = plan(board)
    return {"top.sv": make_top(board, p), "design.xdc": make_xdc(board, p), "build.yaml": make_build(board, p)}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def record(board: str) -> Path:
    d = ROOT / "boards" / board / "smoke"
    g = json.loads((d / "build" / "base" / "gates.json").read_text())
    run = json.loads((d / "build" / "base" / "run.json").read_text()) if (d / "build" / "base" / "run.json").is_file() else {}
    gg = g["gates"]
    gates = {"post_route_timing": bool(gg.get("setup") and gg.get("hold") and gg.get("pulse_width")),
             "drc": bool(gg.get("drc_clean") and gg.get("post_synth_drc_clean")),
             "methodology": bool(gg.get("methodology_no_critical") and gg.get("post_synth_methodology_no_critical") and gg.get("rtl_methodology_no_critical")),
             "bitstream": bool(gg.get("bitstream_present")), "all_gates": bool(g["pass"])}
    p = plan(board)
    rec = {"board": board, "part": p["y"]["part"], "vivado_version": g.get("vivado_version"), "passed": bool(g["pass"] and all(gates.values())),
           "gates": gates, "xdc_sha256": sha256(d / "design.xdc"), "top_sha256": sha256(d / "top.sv"),
           "ports": {"led": p["nled"], "sw": p["nsw"], "btn": int(p["btn"]), "uart": bool(p["uart"]), "differential_clock": p["diff"]},
           "timing": g.get("timing"), "utilization": g.get("utilization"), "power": g.get("power"), "bitstream": g.get("bitstream"),
           "build_stamp": g.get("build_stamp"), "run": {k: run.get(k) for k in ("wall_s", "peak_rss_kb", "scope_peak_anon_mb", "threads") if k in run},
           "method": "flow/run_vivado.sh boards/%s/smoke base; board facts from boards/%s/board.yaml; nothing was run on a board" % (board, board)}
    out = ROOT / "results" / "95_boards" / board
    out.mkdir(parents=True, exist_ok=True)
    (out / "smoke.json").write_text(json.dumps(rec, indent=1, sort_keys=True) + "\n")
    return out / "smoke.json"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["gen", "check", "record", "boards"])
    ap.add_argument("board", nargs="?")
    a = ap.parse_args(argv)
    if a.cmd == "boards":
        print("\n".join(sorted(p.parent.name for p in (ROOT / "boards").glob("*/board.yaml") if has_smoke(p.parent.name))))
        return 0
    if not a.board:
        ap.error("a board id is needed")
    if a.cmd == "record":
        print(record(a.board))
        return 0
    want = files(a.board)
    d = ROOT / "boards" / a.board / "smoke"
    if a.cmd == "gen":
        d.mkdir(parents=True, exist_ok=True)
        for n, t in want.items():
            (d / n).write_text(t)
        print(f"wrote boards/{a.board}/smoke/ ({', '.join(want)})")
        return 0
    bad = [n for n, t in want.items() if not (d / n).is_file() or (d / n).read_text() != t]
    for n in bad:
        print(f"boards/{a.board}/smoke/{n} differs from what the board file generates", file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
