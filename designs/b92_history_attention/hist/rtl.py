"""SystemVerilog for the stateful arms: a front end (state or window, one event a clock) in front of the common head.

Every arm module has the ports of stream.py: clk, rst, in_v, in_f[50:0], out_v, out_cls[1:0]. `rst` is synchronous, active high and
clears the valid pipeline AND the front end's state (sums, window): after a reset the first events see zero state, as the twin does.
State advances only on in_v. LATENCY (clocks from in_v to out_v) is fixed: 2 for a1, a2, a4; 3 for a3 (an extra stage for the scores).

The head is the generated brief 91 (or 89) module `<name>_net` (one clock, comb) fed with the 7 features and the front end's
columns, all registered by the front end; so LATENCY = front stages + 1.
"""
from __future__ import annotations

import numpy as np

from designs.b91_lowbit.lowbit import formats as F
from designs.b91_lowbit.lowbit import rtl as R91
from designs.b89_lutnet_gen.lutgen import rtl as R89
from . import stream as S

_sw = R91._sw


class Sums:
    """Signed linear combinations of signed wires with constant integer weights (CSD shift-add trees)."""

    def __init__(self, out: list, tag: str):
        self.o, self.tag, self.n = out, tag, 0

    def _w(self, lo, hi, rhs):
        self.n += 1
        nm = f"{self.tag}_{self.n}"
        w = _sw(lo, hi)
        self.o.append(f"    wire logic signed [{w - 1}:0] {nm} = {rhs.replace('@W', str(w))};")
        return (nm, lo, hi)

    def lin(self, terms):
        """terms: [((name, lo, hi), weight)] -> (name, lo, hi) of the exact sum (0 if no term)."""
        ts = []
        for (nm, lo, hi), w in terms:
            for sg, d in F.csd(abs(int(w))):
                s = sg if w > 0 else -sg
                a, b = lo << d, hi << d
                lo2, hi2 = (a, b) if s > 0 else (-b, -a)
                sh = f" <<< {d}" if d else ""
                ts.append(self._w(lo2, hi2, f"{'-' if s < 0 else ''}@W'({nm}){sh}"))
        if not ts:
            return self._w(0, 0, "@W'sd0")
        while len(ts) > 1:
            nx = []
            for i in range(0, len(ts) - 1, 2):
                (a, la, ha), (b, lb, hb) = ts[i], ts[i + 1]
                nx.append(self._w(la + lb, ha + hb, f"@W'({a}) + @W'({b})"))
            if len(ts) % 2:
                nx.append(ts[-1])
            ts = nx
        return ts[0]

    def clip(self, x, sh, lo, hi):
        """clip(x >>> sh, lo, hi) as a signed wire of the output range."""
        nm, l, h = x
        w = max(_sw(l, h), _sw(lo, hi))
        self.n += 1
        t = f"{self.tag}_{self.n}"
        self.o.append(f"    wire logic signed [{w - 1}:0] {t} = {w}'({nm}) >>> {sh};")
        ow = _sw(lo, hi)
        self.n += 1
        c = f"{self.tag}_{self.n}"
        self.o.append(f"    wire logic signed [{ow - 1}:0] {c} = ({t} > {w}'sd{hi}) ? {ow}'sd{hi} : ({t} < -{w}'sd{-lo}) ? -{ow}'sd{-lo} : {ow}'({t});"
                      if lo < 0 else
                      f"    wire logic signed [{ow - 1}:0] {c} = ({t} > {w}'sd{hi}) ? {ow}'sd{hi} : ({t} < {w}'sd0) ? {ow}'sd0 : {ow}'({t});")
        return (c, lo, hi)


def _head_ports(net: str, fbits: list[int], extra_w: int) -> list[str]:
    return [f"    {net} u_net (.clk, .rst, .in_v(vn), .in_f(netf), .out_v, .out_cls);"]


def _header(name, arm, lat, desc):
    return [f"// {name}.sv: GENERATED by designs/b92_history_attention/hist/rtl.py. Do not edit.",
            f"// {desc} LATENCY {lat}. One event a clock; out_v follows in_v by exactly LATENCY clocks.",
            "// rst is synchronous, active high, and clears the valid pipeline and the front end's state.",
            "/* verilator lint_off UNUSEDSIGNAL */", "`default_nettype none",
            f"module {name} (", "    input  wire logic        clk,", "    input  wire logic        rst,", "    input  wire logic        in_v,",
            f"    input  wire logic [{S.IN_W - 1}:0] in_f,", "    output logic             out_v,", "    output logic [1:0]       out_cls", ");",
            f"    localparam int LATENCY = {lat};"]


def _feat(j):          # raw 87 feature j of the port
    return f"in_f[{S.FLO[j] + S.FBITS_CUR[j] - 1}:{S.FLO[j]}]"


TS_RAW, SV_RAW, OFI_RAW = "in_f[39:38]", "in_f[44:40]", "in_f[50:45]"


def _tokens(L):
    """Signed token wires from the port: ts, sv, ofi, imb2 = 2 imb - 7."""
    L.append(f"    wire logic signed [2:0] t_ts = $signed({{1'b0, {TS_RAW}}}) - 3'sd1;")
    L.append(f"    wire logic signed [5:0] t_sv = $signed({{1'b0, {SV_RAW}}}) - 6'sd8;")
    L.append(f"    wire logic signed [6:0] t_ofi = $signed({{1'b0, {OFI_RAW}}}) - 7'sd31;")
    L.append(f"    wire logic signed [4:0] t_imb2 = $signed({{1'b0, {_feat(3)}, 1'b0}}) - 5'sd7;")
    L.append(f"    wire logic signed [3:0] t_imb = $signed({{1'b0, {_feat(3)}}});")
    return [("t_ts", -1, 1), ("t_sv", -8, 8), ("t_ofi", -31, 31), ("t_imb2", -7, 7)]


