def emit_a1(rec: dict, name: str, net_name: str) -> str:
    fr = rec["front"]
    rates, sh = fr["rates"], fr["shifts"]
    L = _header(name, "a1_decay", 2, f"Decaying sums: 4 channels x rates {rates} (s <= s - (s >> k) + x), cut to 8-bit columns, then the head.")
    tk = _tokens(L)
    cols = []
    for ci, (tn, lo, hi) in enumerate(tk):
        for ri, k in enumerate(rates):
            w = _sw(-(max(abs(lo), abs(hi)) << k) - 4, (max(abs(lo), abs(hi)) << k) + 4)
            nm = f"s{ci}_{ri}"
            L.append(f"    logic signed [{w - 1}:0] {nm};")
            L.append(f"    wire logic signed [{w - 1}:0] {nm}_n = {nm} - ({nm} >>> {k}) + {w}'({tn});")
            sc = sh[ci * len(rates) + ri]
            L.append(f"    wire logic signed [{w + 1}:0] {nm}_c = ({w + 2}'({nm}_n) >>> {sc}) + {w + 2}'sd128;")
            L.append(f"    wire logic [7:0] {nm}_u = {nm}_c < {w + 2}'sd0 ? 8'd0 : {nm}_c > {w + 2}'sd255 ? 8'd255 : {nm}_c[7:0];")
            cols.append(nm)
    L.append("    logic v1;")
    L.append("    logic [37:0] f1;")
    for nm in cols:
        L.append(f"    logic [7:0] {nm}_q;")
    L.append("    always_ff @(posedge clk) begin")
    L.append("        v1 <= rst ? 1'b0 : in_v;")
    L.append("        if (rst) begin")
    for nm in cols:
        L.append(f"            {nm} <= '0;")
    L.append("        end else if (in_v) begin")
    L.append("            f1 <= in_f[37:0];")
    for nm in cols:
        L.append(f"            {nm} <= {nm}_n;")
        L.append(f"            {nm}_q <= {nm}_u;")
    L.append("        end")
    L.append("    end")
    cat = ", ".join(f"{nm}_q" for nm in reversed(cols))
    L.append(f"    wire logic [{38 + 8 * len(cols) - 1}:0] netf = {{{cat}, f1}};")
    L.append(f"    {net_name} u_net (.clk, .rst, .in_v(v1), .in_f(netf), .out_v, .out_cls);")
    L += ["endmodule", "`default_nettype wire", "/* verilator lint_on UNUSEDSIGNAL */"]
    return "\n".join(L) + "\n"


def emit_a2(rec: dict, name: str, net_name: str, n: int) -> str:
    fr = rec["front"]
    th, bits = fr["thresholds"], fr["bits"]
    L = _header(name, "a2", 2, f"Fixed window: the last {n} token codes (codes {bits} bits per field) feed the head.")
    tk = _tokens(L)
    tk = tk[:3] + [("t_imb", 0, 7)]          # the window codes the raw bucket 0..7 (the attention uses 2 imb - 7)
    cw = sum(bits)
    for j, (tn, lo, hi) in enumerate(tk):
        t = th[j]
        if not t:
            L.append(f"    wire logic [{bits[j] - 1}:0] code{j} = '0;")
        else:
            terms = " + ".join(f"{bits[j]}'({tn} > {_sw(lo, hi)}'sd{x})" if x >= 0 else f"{bits[j]}'({tn} > -{_sw(lo, hi)}'sd{-x})" for x in t)
            L.append(f"    wire logic [{bits[j] - 1}:0] code{j} = {terms};")
    L.append(f"    wire logic [{cw - 1}:0] code = {{{', '.join(f'code{j}' for j in reversed(range(4)))}}};")
    L.append(f"    logic [{cw - 1}:0] win [0:{n - 1}];")
    L.append("    logic v1;")
    L.append("    logic [37:0] f1;")
    L.append("    always_ff @(posedge clk) begin")
    L.append("        v1 <= rst ? 1'b0 : in_v;")
    L.append("        if (rst) begin")
    L.append(f"            for (int i = 0; i < {n}; i++) win[i] <= '0;")
    L.append("        end else if (in_v) begin")
    L.append("            f1 <= in_f[37:0];")
    L.append("            win[0] <= code;")
    L.append(f"            for (int i = 1; i < {n}; i++) win[i] <= win[i-1];")
    L.append("        end")
    L.append("    end")
    cat = ", ".join(f"win[{i}]" for i in reversed(range(n)))
    L.append(f"    wire logic [{38 + n * cw - 1}:0] netf = {{{cat}, f1}};")
    L.append(f"    {net_name} u_net (.clk, .rst, .in_v(v1), .in_f(netf), .out_v, .out_cls);")
    L += ["endmodule", "`default_nettype wire", "/* verilator lint_on UNUSEDSIGNAL */"]
    return "\n".join(L) + "\n"


def emit_a3(rec: dict, name: str, net_name: str) -> str:
    fr = rec["front"]
    form = fr["form"]
    N, D, MV = 16, 4, 4
    L = _header(name, "a3", 3, f"Tiny attention ({form}), N = {N}, key size {D}, value size {MV}, then the head.")
    tk = _tokens(L)
    # stage A: current-feature codes -> q ; token -> k, v
    cth = fr["cth"]
    cs = []
    for j in range(7):
        t = cth[j]
        w = max(1, len(t).bit_length())
        if not t:
            L.append(f"    wire logic [3:0] c{j} = 4'd0;")
        else:
            terms = " + ".join(f"4'({_feat(j)} > {S.FBITS_CUR[j]}'d{x})" for x in t)
            L.append(f"    wire logic [3:0] c{j} = {terms};")
        L.append(f"    wire logic signed [4:0] cs{j} = $signed({{1'b0, c{j}}});")
        cs.append((f"cs{j}", 0, len(t)))
    sm = Sums(L, "a")
    qs = []
    for d in range(D):
        acc = sm.lin([(cs[j], fr["Eq"][d][j]) for j in range(7)])
        qs.append(sm.clip(acc, fr["sq"], -8, 7))
    ks, vs = [], []
    for d in range(D):
        ks.append(sm.clip(sm.lin([(tk[j], fr["Ek"][d][j]) for j in range(4)]), fr["sk"], -8, 7))
    for m in range(MV):
        vs.append(sm.clip(sm.lin([(tk[j], fr["Ev"][m][j]) for j in range(4)]), fr["sv"], -8, 7))
    L.append("    logic v1, v2;")
    L.append("    logic [37:0] f1, f2;")
    L.append(f"    logic signed [3:0] qr [0:{D - 1}];")
    L.append(f"    logic signed [3:0] kr [0:{N - 1}][0:{D - 1}];")
    L.append(f"    logic signed [3:0] vr [0:{N - 1}][0:{MV - 1}];")
    L.append("    always_ff @(posedge clk) begin")
    L.append("        v1 <= rst ? 1'b0 : in_v;")
    L.append("        v2 <= rst ? 1'b0 : v1;")
    L.append("        f2 <= f1;")
    L.append("        if (rst) begin")
    L.append(f"            for (int d = 0; d < {D}; d++) qr[d] <= '0;")
    L.append(f"            for (int i = 0; i < {N}; i++) begin")
    L.append(f"                for (int d = 0; d < {D}; d++) kr[i][d] <= '0;")
    L.append(f"                for (int m = 0; m < {MV}; m++) vr[i][m] <= '0;")
    L.append("            end")
    L.append("        end else if (in_v) begin")
    L.append("            f1 <= in_f[37:0];")
    for d in range(D):
        L.append(f"            qr[{d}] <= {qs[d][0]};")
    for d in range(D):
        L.append(f"            kr[0][{d}] <= {ks[d][0]};")
    for m in range(MV):
        L.append(f"            vr[0][{m}] <= {vs[m][0]};")
    L.append(f"            for (int i = 1; i < {N}; i++) begin")
    L.append(f"                for (int d = 0; d < {D}; d++) kr[i][d] <= kr[i-1][d];")
    L.append(f"                for (int m = 0; m < {MV}; m++) vr[i][m] <= vr[i-1][m];")
    L.append("            end")
    L.append("        end")
    L.append("    end")
    # stage B: scores
    pos = fr["pos"]
    for i in range(N):
        prods = " + ".join(f"qr[{d}] * kr[{i}][{d}]" for d in range(D))
        L.append(f"    (* use_dsp = \"no\" *) wire logic signed [10:0] s{i} = {prods} + 11'sd{pos[i]}" if pos[i] >= 0 else
                 f"    (* use_dsp = \"no\" *) wire logic signed [10:0] s{i} = {prods} - 11'sd{-pos[i]}")
        L[-1] += ";"
    L.append(f"    logic [{MV * 4 - 1}:0] o_q;")
    if form == "top1":
        # tournament with ties to the lower index (the more recent event): the left node wins on >=
        nodes = [(f"s{i}", [f"vr[{i}][{m}]" for m in range(MV)]) for i in range(N)]
        lvl = 0
        while len(nodes) > 1:
            nx = []
            for i in range(0, len(nodes), 2):
                (sa, va), (sb, vb) = nodes[i], nodes[i + 1]
                t = f"w{lvl}_{i // 2}"
                L.append(f"    wire logic signed [10:0] {t}_s = ({sa} >= {sb}) ? {sa} : {sb};")
                for m in range(MV):
                    L.append(f"    wire logic signed [3:0] {t}_v{m} = ({sa} >= {sb}) ? {va[m]} : {vb[m]};")
                nx.append((f"{t}_s", [f"{t}_v{m}" for m in range(MV)]))
            nodes, lvl = nx, lvl + 1
        win = nodes[0][1]
        L.append("    always_ff @(posedge clk) begin")
        L.append("        o_q <= {" + ", ".join(f"4'(5'({w}) + 5'sd8)" for w in reversed(win)) + "};")
        L.append("    end")
    else:
        sa_, so_ = fr["sa"], fr["so"]
        for i in range(N):
            L.append(f"    wire logic signed [10:0] sh{i} = s{i} >>> {sa_};")
            L.append(f"    wire logic [2:0] a{i} = sh{i} < 11'sd0 ? 3'd0 : sh{i} > 11'sd7 ? 3'd7 : sh{i}[2:0];")
        outs = []
        for m in range(MV):
            prods = " + ".join(f"$signed({{1'b0, a{i}}}) * vr[{i}][{m}]" for i in range(N))
            L.append(f"    (* use_dsp = \"no\" *) wire logic signed [11:0] z{m} = {prods};")
            L.append(f"    wire logic signed [11:0] zs{m} = z{m} >>> {so_};")
            L.append(f"    wire logic signed [3:0] o{m} = zs{m} < -12'sd8 ? -4'sd8 : zs{m} > 12'sd7 ? 4'sd7 : zs{m}[3:0];")
            outs.append(f"4'(5'(o{m}) + 5'sd8)")
        L.append("    always_ff @(posedge clk) begin")
        L.append("        o_q <= {" + ", ".join(reversed(outs)) + "};")
        L.append("    end")
    L.append(f"    wire logic [{38 + MV * 4 - 1}:0] netf = {{o_q, f2}};")
    L.append(f"    {net_name} u_net (.clk, .rst, .in_v(v2), .in_f(netf), .out_v, .out_cls);")
    L += ["endmodule", "`default_nettype wire", "/* verilator lint_on UNUSEDSIGNAL */"]
    return "\n".join(L) + "\n"


def emit_arm(arm: str, rec: dict, name: str, source: str = "") -> dict[str, str]:
    """{module name: text} for an arm: the net (head) module and the front-end/top module."""
    net = name + "_net"
    fb = S.FBITS_CUR + rec["front_bits"]
    if arm in ("a4_lut", "ref_lut"):
        net_txt = R89.emit(rec["head"], net, fb, pipe="comb", source=source)
    else:
        net_txt = R91.emit(rec["head"], net, fb, pipe="comb", source=source)
    if arm in ("a1_decay", "a4_lut"):
        top = emit_a1(rec, name, net)
    elif arm == "a2_win16":
        top = emit_a2(rec, name, net, 16)
    elif arm == "a2_win8":
        top = emit_a2(rec, name, net, 8)
    elif arm in ("a3_top1", "a3_relu"):
        top = emit_a3(rec, name, net)
    else:
        raise ValueError(arm)
    return {net: net_txt, name: top}
