"""Writes results/190_refstream/results.md: order-table refusals on the realistic reference stream (brief 190, item 18).

    python3 -m designs.b110_itch_ouch.scripts.refstream_measure

Pure Python, a few seconds. Every number in the file comes from this run (seeds 1 to 5)."""
from __future__ import annotations

import statistics
from pathlib import Path

from designs.b110_itch_ouch.model import refstream as R

OUT = Path(__file__).resolve().parents[3] / "results" / "190_refstream" / "results.md"
SEEDS = (1, 2, 3, 4, 5)
BITS = (8, 10, 12, 14)


def sweep(mode: str, label: str = "", **kw) -> list[str]:
    rows = []
    for b in BITS:
        d, t, peaks = [], [], []
        for s in SEEDS:
            ev = R.events(R.StreamCfg(seed=s, reference_mode=mode, **kw))
            a, c = R.replay_direct(ev, b), R.replay_two_slot(ev, b)
            d.append(100 * a["refused"] / a["adds"])
            t.append(100 * c["refused"] / c["adds"])
            peaks.append(a["peak_live"])
        rows.append(f"| {label or mode} | {1 << b} | {statistics.mean(peaks):.0f} | {statistics.mean(d):.2f} | {max(d):.2f} | {statistics.mean(t):.2f} | {max(t):.2f} |")
    return rows


def main() -> None:
    cfg = R.StreamCfg()
    lines = ["# Order-table refusals on a realistic reference stream (brief 190)", "",
             "Generated by `designs/b110_itch_ouch/scripts/refstream_measure.py`; do not edit by hand. Python models only: no RTL, no synthesis, no board.", "",
             f"Stream: {cfg.n_orders} adds per run, gap_mean {cfg.gap_mean}, lifetime log-normal (median {cfg.life_median} adds, sigma {cfg.life_sigma}), "
             f"{cfg.day_long:.0%} never deleted. Seeds {SEEDS[0]} to {SEEDS[-1]}. Refused = an add whose candidate slot or slots are all held by other live "
             "references (the b110 RTL counts this as `oovf` and marks the instrument inexact).", "",
             "## Refused adds, percent of adds", "",
             "| reference mode | slots | peak live (mean) | one slot, mean % | one slot, worst % | two slots, mean % | two slots, worst % |", "|---|---|---|---|---|---|---|"]
    lines += sweep("sequential", "sequential, gap 30") + sweep("sequential", "sequential, dense (gap 0)", gap_mean=0.0) + sweep("random")
    lines += ["", "## Closed form against a uniform-random Monte Carlo (2000 trials)", "",
              "| n items | m slots | exact | approximation | Monte Carlo |", "|---|---|---|---|---|"]
    for n, m in ((10, 256), (100, 4096), (100, 65536), (500, 262144)):
        lines.append(f"| {n} | {m} | {R.p_any_collision(n, m):.4f} | {R.p_any_collision_approx(n, m):.4f} | {R.uniform_monte_carlo(n, m, 2000):.4f} |")
    lines += ["", "## Slots needed for a chance of any collision", "", "| n items | target | slots (approximation) | next power of two |", "|---|---|---|---|"]
    for n in (100, 1000, 10000):
        for p in (0.5, 0.01):
            m = R.slots_for_collision_probability(n, p)
            lines.append(f"| {n} | {p:.0%} | {m} | {R.pow2_at_least(m)} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT)


if __name__ == "__main__":
    main()
