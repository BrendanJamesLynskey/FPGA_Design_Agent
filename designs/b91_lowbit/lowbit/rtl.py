"""Emit SystemVerilog for a lowbit model (model.py). The RTL is read from the exported integers alone, as the twin is.

Ports (the brief 87 arm interface, so the 87 test bench and the 87 out-of-context wrapper take it unchanged):
clk; rst (synchronous, active high, clears the valid pipeline only); in_v, in_f (packed unsigned features, feature 0 in
the least significant bits, widths `fbits`); out_v, out_cls[1:0] (argmax of the class scores, ties to the lowest class).

Datapath, per neuron: every weight is a signed element e; it is written as its non-adjacent signed-digit terms
(+-2^s, at most two per element of any of our formats), so a neuron is a balanced tree of adds and subtracts of shifted
inputs plus one constant (the bias), with every intermediate wire sized from interval arithmetic (never truncated). A
power-of-two weight is a shift, i.e. wiring. The hidden activation is the arithmetic shift of the sum by the neuron's
constant `sh`, then clipped to 0 .. amax. The score layer has no shift or clip (the left shifts are folded into the
terms), and the argmax compares the scores.

Pipelining (`pipe`), in clocks from in_v to out_v = the module's LATENCY localparam:
    "comb"   one register, at the output: LATENCY 1
    "layer"  a register after every layer (hidden and score) and at the output: LATENCY = layers + 1
The encoder (a ROM per feature, or thermometer compares) sits in front of layer 1 in the same clock. The latency is
fixed: no stage depends on the data. Verilator's UNUSEDSIGNAL is waived for the generated file: the sum wires carry
low and high bits that the shift and the clip legitimately ignore.
"""
from __future__ import annotations

import math

import numpy as np

from . import formats as F
from . import model as M


def _bl(n: int) -> int:
    return max(1, int(n).bit_length())


def _sw(lo: int, hi: int) -> int:
    """Signed width holding lo..hi."""
    return max(2, max(_bl(hi), _bl(-lo - 1) if lo < 0 else 1) + 1)


class _Tree:
    def __init__(self, tag: str, out: list):
        self.tag, self.out, self.n = tag, out, 0

    def wire(self, lo, hi, rhs):
        self.n += 1
        nm = f"{self.tag}_w{self.n}"
        w = _sw(lo, hi)
        self.out.append(f"    wire logic signed [{w - 1}:0] {nm} = {rhs.replace('@W', str(w))};")
        return nm, w

    def term(self, x, xw, xhi, sign, sh):
        hi = xhi << sh
        nm, w = self.wire(0, hi, f"@W'($signed({{1'b0, {x}}})) <<< {sh}" if sh else f"@W'($signed({{1'b0, {x}}}))")
        return (nm, 0, hi, sign)

    def const(self, v):
        nm, w = self.wire(abs(v), abs(v), f"@W'sd{abs(v)}")
        return (nm, abs(v), abs(v), v >= 0)

    def add(self, a, b):
        (na, la, ha, pa), (nb, lb, hb, pb) = a, b
        if pa and pb or (not pa and not pb):
            lo, hi, op, x, y, pos = la + lb, ha + hb, "+", na, nb, pa
        elif pa:
            lo, hi, op, x, y, pos = la - hb, ha - lb, "-", na, nb, True
        else:
            lo, hi, op, x, y, pos = lb - ha, hb - la, "-", nb, na, True
        w = _sw(lo, hi)
        self.n += 1
        nm = f"{self.tag}_w{self.n}"
        self.out.append(f"    wire logic signed [{w - 1}:0] {nm} = {w}'({x}) {op} {w}'({y});")
        return (nm, lo, hi, pos)

    def sum(self, terms):
        """Balanced tree; returns (wire, lo, hi) of the exact signed sum."""
        q = list(terms)
        while len(q) > 1:
            q = [self.add(q[i], q[i + 1]) if i + 1 < len(q) else q[i] for i in range(0, len(q), 2)]
        nm, lo, hi, pos = q[0]
        if pos:
            return nm, lo, hi
        w = _sw(-hi, -lo)
        self.n += 1
        n2 = f"{self.tag}_w{self.n}"
        self.out.append(f"    wire logic signed [{w - 1}:0] {n2} = -{w}'({nm});")
        return n2, -hi, -lo


def emit(m: dict, name: str, fbits: list[int], pipe="comb", source: str = "") -> str:
    if pipe not in ("comb", "layer"):
        raise ValueError("pipe must be 'comb' or 'layer'")
    cfg, inp, layers = m["config"], m["input"], m["layers"]
    th = inp["thresholds"]
    fw = sum(fbits)
    flo = [sum(fbits[:i]) for i in range(len(fbits))]
    if len(th) != len(fbits):
        raise ValueError(f"fbits has {len(fbits)} widths; the model has {len(th)} features")
    nL = len(layers)
    latency = 1 + (nL if pipe == "layer" else 0)
    L = []
    a = L.append
    a(f"// {name}.sv: GENERATED by designs/b91_lowbit/lowbit (rtl.py){' from ' + source if source else ''}. Do not edit.")
    a(f"// Low-bit network: format {cfg['fmt']}, {'thermometer' if inp['kind'] == 'thermo' else str(cfg['act_bits']) + '-bit code'} inputs, "
      f"layers {[l['n_in'] for l in layers][0]} -> " + " -> ".join(str(l['n']) for l in layers) + f"; activations {layers[0]['amax'].bit_length()} bit; pipe {pipe}; LATENCY {latency}.")
    a("// out_v follows in_v by exactly LATENCY clocks for every input (no data-dependent path); one input a clock.")
    a("// rst is synchronous, active high, and clears only the valid pipeline.")
    a("/* verilator lint_off UNUSEDSIGNAL */")
    a("`default_nettype none")
    a(f"module {name} (")
    a("    input  wire logic        clk,")
    a("    input  wire logic        rst,")
    a("    input  wire logic        in_v,")
    a(f"    input  wire logic [{fw - 1}:0] in_f,")
    a("    output logic             out_v,")
    a("    output logic [1:0]       out_cls")
    a(");")
    a(f"    localparam int LATENCY = {latency};")
    # ---- encoder
    cols = []                                              # (name, width, max value)
    if inp["kind"] == "code":
        a("    // input encoder: code = number of thresholds the feature exceeds, as a ROM indexed by the feature value")
        for j, t in enumerate(th):
            amax = len(t)
            cb = _bl(amax)
            f = f"in_f[{flo[j] + fbits[j] - 1}:{flo[j]}]"
            if not t:
                a(f"    wire logic [{cb - 1}:0] e{j} = '0;")
            else:
                a(f"    wire logic [{cb - 1}:0] e{j};")
                codes = np.array([sum(1 for x in t if v > x) for v in range(1 << fbits[j])])
                n = 1 << fbits[j]
                for bit in range(cb):
                    v = sum(1 << i for i in range(n) if (codes[i] >> bit) & 1)
                    a(f"    localparam logic [{n - 1}:0] E{j}_{bit} = {n}'h{v:0{max(1, n // 4)}x};")
                    a(f"    assign e{j}[{bit}] = E{j}_{bit}[{f}];")
            cols.append((f"e{j}", cb, amax))
    else:
        a("    // input encoder: one thermometer bit per threshold (feature > threshold)")
        for j, t in enumerate(th):
            for k, x in enumerate(t):
                a(f"    wire logic t{j}_{k} = in_f[{flo[j] + fbits[j] - 1}:{flo[j]}] > {fbits[j]}'d{x};")
                cols.append((f"t{j}_{k}", 1, 1))
    bnd = M.bounds(m)
    src = cols
    for li, Ld in enumerate(layers):
        hid = Ld["kind"] == "hidden"
        a(f"    // layer {li + 1}: {Ld['n']} neurons x {Ld['n_in']} inputs, " + ("clipped activations" if hid else "class scores (signed)"))
        outs = []
        Wm = np.asarray(Ld["W"], dtype=np.int64).reshape(Ld["n"], Ld["n_in"])
        for j in range(Ld["n"]):
            tr = _Tree(f"l{li}n{j}", L)
            terms = []
            k = Ld["k"][j] if not hid else 0
            for i in range(Ld["n_in"]):
                w = int(Wm[j, i])
                nm, xw, xhi = src[i]
                if w == 0 or xhi == 0:
                    continue
                for s, d in F.csd(abs(w)):
                    terms.append(tr.term(nm, xw, xhi, (s > 0) == (w > 0), d + k))
            if Ld["B"][j] != 0 or not terms:
                terms.append(tr.const(int(Ld["B"][j])))
            acc, lo, hi = tr.sum(terms)
            aw = _sw(lo, hi)
            if hid:
                sh, A, amax = Ld["sh"][j], Ld["amax"].bit_length(), Ld["amax"]
                rw = max(aw, A + 1)
                a(f"    wire logic signed [{rw - 1}:0] r{li}_{j} = {rw}'({acc}) >>> {sh};")
                rl, rh = lo >> sh, hi >> sh
                body = f"r{li}_{j}[{A - 1}:0]"
                if rh > amax:
                    body = f"(r{li}_{j} > {rw}'sd{amax}) ? {{{A}{{1'b1}}}} : {body}"
                if rl < 0:
                    body = f"r{li}_{j}[{rw - 1}] ? {A}'d0 : ({body})"
                a(f"    wire logic [{A - 1}:0] n{li}_{j} = {body};")
                outs.append((f"n{li}_{j}", A, amax))
            else:
                a(f"    wire logic signed [{aw - 1}:0] n{li}_{j} = {acc};")
                outs.append((f"n{li}_{j}", aw, (lo, hi)))
        if pipe == "layer":
            for nm, wd, mx in outs:
                a(f"    logic {'signed ' if not hid else ''}[{wd - 1}:0] q{nm};")
            a("    always_ff @(posedge clk) begin")
            for nm, wd, mx in outs:
                a(f"        q{nm} <= {nm};")
            a("    end")
            outs = [(f"q{nm}", wd, mx) for nm, wd, mx in outs]
        src = outs
    nc = cfg["n_classes"]
    if nc != 3:
        raise ValueError("the RTL argmax is written for 3 classes")
    sw = max(w for _, w, _ in src)
    a("    // class scores and argmax, ties to the lowest class index")
    for c in range(nc):
        a(f"    wire logic signed [{sw - 1}:0] s{c} = {sw}'({src[c][0]});")
    a("    wire logic       ge10 = s1 > s0;")
    a(f"    wire logic signed [{sw - 1}:0] m01 = ge10 ? s1 : s0;")
    a("    wire logic [1:0] c01 = ge10 ? 2'd1 : 2'd0;")
    a("    wire logic [1:0] cls = (s2 > m01) ? 2'd2 : c01;")
    a("    logic [LATENCY-1:0] vpipe;")
    a("    always_ff @(posedge clk) begin")
    a("        out_cls <= cls;")
    a("        if (rst) vpipe <= '0; else vpipe <= {vpipe[LATENCY-2:0], in_v};" if latency > 1 else
      "        if (rst) vpipe <= '0; else vpipe <= in_v;")
    a("    end")
    a("    assign out_v = vpipe[LATENCY-1];")
    a("endmodule")
    a("`default_nettype wire")
    a("/* verilator lint_on UNUSEDSIGNAL */")
    return "\n".join(L) + "\n"
