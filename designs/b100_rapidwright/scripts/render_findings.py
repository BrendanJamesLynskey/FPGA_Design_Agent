"""Render docs/what_we_found.md from its template and results/b100/summary.json, so that every number in it is read from the record
(brief 100). Usage: render_findings.py   (from the repository root). The template (docs/what_we_found.tmpl.md) uses {{table:NAME}} for a
table and {{v:path}} for one value (a dotted path into summary.json; list indexes as [i]). Pure Python."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
D = ROOT / "designs" / "b100_rapidwright" / "docs"
S = json.loads((ROOT / "results" / "b100" / "summary.json").read_text())


def get(path):
    cur = S
    for part in re.findall(r"[^.\[\]]+|\[\d+\]", path):
        cur = cur[int(part[1:-1])] if part.startswith("[") else cur[part]
    return cur


def fmt(v):
    return f"{v:.3f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def md(rows, head):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(map(fmt, r)) + " |" for r in rows])


def table(name):
    if name == "c1":
        rows = []
        for label, run in sorted(S["capability1"]["blocks"].items()):
            for c, x in sorted(run["copies"].items()):
                rows.append([label, f"copy {c}", x["worst_delay_ns"], x["worst_slack_ns"], f'{x["endpoints_identical"]} of {x["common_with_copy0"]}', x["mean_abs_diff_ps"], x["max_abs_diff_ps"]])
        return md(rows, ["run", "block", "worst internal path (ns)", "worst internal slack (ns)", "endpoints with the same delay as copy 0", "mean difference (ps)", "largest difference (ps)"])
    if name == "c1_whole":
        rows = [[k, v["period_ns"], v["wns_ns"], v["whs_ns"], v["lut"], v["ff"], v["times_s"].get("synth", ""), v["times_s"].get("place", ""), v["times_s"].get("route", "")]
                for k, v in sorted(S["capability1"]["whole_design_runs"].items())]
        return md(rows, ["run", "target (ns)", "WNS (ns)", "WHS (ns)", "LUT", "FF", "synth (s)", "place (s)", "route (s)"])
    if name == "c23_rows":
        rows = [[r["arm"], r["seed"], r["target_ns"], r["wns_all_ns"], r["wns_mac_to_pcs_ns"], r["wns_pcs_to_gt_ns"], r["whs_ns"], r["achieved_period_ns"],
                 r["chain_latency_ns_2clk"], r["lut"], r["ff"], r["vivado_times_s"].get("place", ""), r["vivado_times_s"].get("route", ""),
                 r["rapidwright"].get("route_s", r["rapidwright"].get("seconds", ""))]
                for r in S["capabilities23"]["rows"]]
        return md(rows, ["arm", "seed", "target (ns)", "WNS all (ns)", "WNS MAC to PCS (ns)", "WNS PCS to GT (ns)", "WHS (ns)", "achieved period (ns)",
                         "2-clock chain latency (ns)", "LUT", "FF", "Vivado place (s)", "Vivado route (s)", "RapidWright (s)"])
    if name == "c23_arms":
        rows = [[a, S["capabilities23"]["arms"][a], v["n"], v["achieved_period_ns_mean"], v["min"], v["max"], v["stdev"], v["wns_closed"]] for a, v in S["capabilities23"]["by_arm"].items()]
        return md(rows, ["arm", "what", "runs", "mean achieved period (ns)", "min", "max", "std dev", "runs that closed"])
    if name == "agent":
        rows = []
        for a, v in sorted(S["stage2"].items()):
            r = v.get("result", {})
            rows.append([f"arm {a.upper()}", "with" if a == "a" else "without", v["tool_calls"], r.get("num_turns", ""), round(v["wall_s"] / 60, 1), json.dumps(v["tool_counts"])])
        return md(rows, ["arm", "RapidWright tools", "tool calls", "turns", "wall time (min)", "tool calls by name"])
    raise KeyError(name)


tmpl = (D / "what_we_found.tmpl.md").read_text()
out = re.sub(r"\{\{table:(\w+)\}\}", lambda m: table(m.group(1)), tmpl)
out = re.sub(r"\{\{v:([^}]+)\}\}", lambda m: fmt(get(m.group(1))), out)
(D / "what_we_found.md").write_text("<!-- Generated by designs/b100_rapidwright/scripts/render_findings.py from what_we_found.tmpl.md and results/b100/summary.json. Edit the template. -->\n" + out)
print("wrote", D / "what_we_found.md")
