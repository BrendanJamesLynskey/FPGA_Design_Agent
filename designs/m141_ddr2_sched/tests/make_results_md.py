#!/usr/bin/env python3
"""make_results_md.py (brief 141): writes designs/m141_ddr2_sched/docs/results.md from results/b141/sim_summary.json and results/b141/formal_full.json, so that no number in it is typed.

    python3 designs/m141_ddr2_sched/tests/make_results_md.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SIM = ROOT / "results" / "b141" / "sim_summary.json"
FORMAL = ROOT / "results" / "b141" / "formal_full.json"
OUT = ROOT / "designs" / "m141_ddr2_sched" / "docs" / "results.md"


def apc(r: dict) -> float:
    return r['act'] / (r['reads'] + r['writes'])


def lat(r: dict, key: str = '') -> str:
    c, n = r.get("lat_clk" + key), r.get("lat_ns" + key)
    if not c:
        return "-"
    return f"{c['p50']} / {c['p99']} / {c['p999']} / {c['max']} clk ({n['p50']:.0f} / {n['p99']:.0f} / {n['p999']:.0f} / {n['max']:.0f} ns)"


def main() -> None:
    sim = json.loads(SIM.read_text())
    runs = sim["runs"]
    L = ["# Results of phase 0 (generated by tests/make_results_md.py from results/b141; do not edit)", ""]
    L += ["Profile `nexys_650` (tCK 3077 ps, CL 5) unless a row says otherwise. Latency = request accepted to first data beat, in command clocks, with nanoseconds at the profile's clock.",
          "Median / p99 / p99.9 / max are over the reads of one run (fixed seed). Utilisation = data-bus clocks / elapsed clocks. ACT per column = ACTIVATE commands / column commands: below 1 means rows were reused, above 1 means rows were opened and closed again before their column command (a refresh or a direction change closed them).", ""]
    L += ["## Read latency, light load (policy 0 latency-first, policy 1 bandwidth-first)", "", "| Run | Policy | Reads | Median / p99 / p99.9 / max | ACT per column | Violations |", "|---|---|---|---|---|---|"]
    for k, r in runs.items():
        if k.startswith(("lat_", "xcheck_")):
            L.append(f"| {k} | {r['policy']} | {r['reads']} | {lat(r)} | {apc(r):.3f} | {r['violations']} |")
    L += ["", "## Bandwidth", "", "| Run | Policy | Map | Pattern | Utilisation | GB/s of a peak | ACT per column | Median read latency | Violations |", "|---|---|---|---|---|---|---|---|---|"]
    for k, r in runs.items():
        if k.startswith(("bw_", "qd_sweep", "age_sweep", "hazard")):
            m = r.get("lat_clk", {}).get("p50", "-")
            L.append(f"| {k} | {r['policy']} | {r['map']} | {r['pat']} | {r['util']:.3f} | {r['gbps']:.3f} of {r['peak_gbps']:.3f} | {apc(r):.3f} | {m} | {r['violations']} |")
    L += ["", "## Refresh placement (policy 0, random reads, light load)", "", "| Run | REF_POST | ref_defer | Median / p99 / p99.9 / max | Refreshes | Longest gap between refreshes (clk) |", "|---|---|---|---|---|---|"]
    for k, r in runs.items():
        if k.startswith("refresh_"):
            L.append(f"| {k} | {r['refpost']} | {r['defer']} | {lat(r)} | {r['ref']} | {r['max_ref_gap']} |")
    L += ["", "## Refresh in a latency-critical window (policy 0, random reads, ref_defer high for 5000 of every 12000 clocks)", "", "Reads accepted while ref_defer is high are \"in window\", the rest \"outside\".", "",
          "| Run | REF_POST | In window: median / p99 / p99.9 / max | Outside: median / p99 / p99.9 / max | Refreshes |", "|---|---|---|---|---|"]
    for k, r in runs.items():
        if k.startswith("refresh_window"):
            L.append(f"| {k} | {r['refpost']} | {lat(r, '_win')} | {lat(r, '_out')} | {r['ref']} |")
    L += ["", "## Longest wait of any request (accepted to column command), clocks", "", "| Run | wait_max |", "|---|---|"]
    for k, r in runs.items():
        L.append(f"| {k} | {r['wait_max']} |")
    if FORMAL.exists():
        f = json.loads(FORMAL.read_text())
        L += ["", "## Formal runs (verif/formal/run_formal.py --set full)", "", f"Tool: {f['tool']}. Proved response bound at the small parameters: {f['bounds']['tiny']} clocks; the same formula at the real parameters of `bound(REAL)`: {f['bounds']['real']} clocks.", "",
              "| Job | Task | Engine | Depth | Verdict | Seconds | Assertions that failed (mutants) |", "|---|---|---|---|---|---|---|"]
        for r in f["results"]:
            L.append(f"| {r['name']} | {r['task']} | {r.get('engine', '')} | {r.get('depth', '')} | {r.get('verdict')} | {r.get('seconds', '')} | {', '.join(r.get('failed_assertions', []))} |")
    OUT.write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
