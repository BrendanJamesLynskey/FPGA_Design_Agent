"""Generate the partial-evaluation ("table") decision blocks for the 87 boosted trees and the 89 `lg_small` network.

    python3 -m designs.b93_precompute.model.gen_rtl            # write designs/b93_precompute/rtl/gen/*.sv
    python3 -m designs.b93_precompute.model.gen_rtl --check    # fail if a committed file is out of date

One feature (the "late" feature, index LATE = 5, the 8-bit order-flow imbalance) is split off. While it is still being
computed, the block evaluates the whole model once for every interval of its value that the model can tell apart
(every distinct threshold the model compares it with makes a boundary), and keeps the class of each interval in a
small table of registers. When the late value arrives, it only selects a table entry.

Ports (the 87 arm ports, with the packed features split into an early vector and a late value):

    clk, rst (synchronous, active high; clears the valid pipeline only)
    e_v, e_f[37:0]   the early features, packed as the 87 arm takes them; the bits of the late feature are ignored
    l_v, l_x[7:0]    the late feature's value
    out_v, out_cls   the class; out_v follows l_v by exactly 1 clock

Timing contract (LATENCY_LATE = 1; FILL is the number of clocks from e_v to a valid table, 1 or 2):
    l_v may be asserted from the clock FILL after e_v, up to the clock before the table is overwritten by the next
    e_v (that is, up to FILL - 1 clocks after the next e_v). A late value before the table is ready, or after the
    table was overwritten, gives the class of another message. Ties between class scores go to the lower class index.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from designs.b87_ml_trading.model import gen_rtl as G87
from designs.b89_lutnet_gen.lutgen import model as M89
from designs.b89_lutnet_gen.lutgen.rtl import _w

ROOT = G87.ROOT
OUT = Path(__file__).resolve().parents[1] / "rtl" / "gen"
LATE = 5
FBITS = G87.FBITS
FLO = G87.FLO
LG_MODEL = ROOT / "results" / "b89" / "models" / "lg_small_seed2.json"


def _head(name: str, what: str, src: str, fill: int, ni: int) -> list[str]:
    return [
        f"// {name}.sv: GENERATED by designs/b93_precompute/model/gen_rtl.py from {src}. Do not edit.",
        f"// {what}",
        f"// The late feature (packed bits [{FLO[LATE] + FBITS[LATE] - 1}:{FLO[LATE]}] of the 87 features) is supplied on l_x; its",
        f"// {ni} value intervals each have a class in a table filled FILL = {fill} clock(s) after e_v; l_v selects an entry: out_v",
        "// follows l_v by exactly 1 clock. l_v may come from FILL clocks after e_v until the next e_v + FILL - 1 clocks.",
        "// rst is synchronous, active high, and clears only the valid pipeline. Ties between classes: lower index.",
        f"module {name} (",
        "    input  logic        clk,", "    input  logic        rst,",
        "    input  logic        e_v,", "    input  logic [37:0] e_f,",
        "    input  logic        l_v,", "    input  logic [7:0]  l_x,",
        "    output logic        out_v,", "    output logic [1:0]  out_cls",
        ");",
        f"    localparam int FILL = {fill};", "    localparam int LATENCY_LATE = 1;",
        f"    localparam int NI = {ni};",
    ]


def _select(th: list[int], strict_gt_encoder: bool) -> list[str]:
    """Late path: an interval hit vector from the thresholds, then the registered AND-OR of the table.
    Interval i (0..len(th)): x <= th[0] for 0; th[i-1] < x <= th[i]; x > th[-1] for the last. (Both models: an
    interval is the set of x with the same set of compares `x > t` true.)"""
    n = len(th)
    L = []
    for i in range(n):
        L.append(f"    wire logic gt{i} = l_x > 8'd{th[i]};")
    L.append(f"    wire logic [NI-1:0] hit;")
    L.append("    assign hit[0] = !gt0;")
    for i in range(1, n):
        L.append(f"    assign hit[{i}] = gt{i-1} && !gt{i};")
    L.append(f"    assign hit[NI-1] = gt{n-1};")
    L.append("    logic [1:0] pick;")
    L.append("    always_comb begin")
    L.append("        pick = '0;")
    L.append("        for (int i = 0; i < NI; i++) pick = pick | ({2{hit[i]}} & tab[i]);")
    L.append("    end")
    L.append("    logic [0:0] vp;")
    L.append("    always_ff @(posedge clk) begin")
    L.append("        out_cls <= pick;")
    L.append("        if (rst) vp <= '0; else vp <= l_v;")
    L.append("    end")
    L.append("    assign out_v = vp[0];")
    return L


def _table_regs(fill: int, ni: int, classes: list[str], stage_regs: list[str] | None) -> list[str]:
    """classes[i]: the SV expression of interval i's class (a function of the early features)."""
    L = ["    logic [1:0] tab [NI];"]
    if fill == 1:
        L.append("    always_ff @(posedge clk) if (e_v) begin")
        for i, c in enumerate(classes):
            L.append(f"        tab[{i}] <= {c};")
        L.append("    end")
    else:
        L += stage_regs or []
        L.append("    logic e_v1;")
        L.append("    always_ff @(posedge clk) e_v1 <= e_v && !rst;")
        L.append("    always_ff @(posedge clk) if (e_v1) begin")
        for i, c in enumerate(classes):
            L.append(f"        tab[{i}] <= {c};")
        L.append("    end")
    return L


# ------------------------------------------------------------------------------------------------- trees
def gbt_pe(q: dict, name: str, fill: int) -> str:
    trees = q["trees"]
    per_cls = [[i for i, t in enumerate(trees) if t["cls"] == k] for k in range(3)]
    leaves = [n["leaf"] for t in trees for n in t["nodes"] if "leaf" in n]
    lw = G87.sw(leaves)
    tot = [abs(q["prior"][k]) + sum(max(abs(n["leaf"]) for n in trees[i]["nodes"] if "leaf" in n) for i in per_cls[k])
           for k in range(3)]
    W = G87.sw([max(tot)])
    fb = FBITS[LATE]
    top = (1 << fb) - 1

    def eff(x):                                   # the threshold as the base RTL writes it; None: always right
        return None if x["t"] < 0 else max(0, min(x["t"], top))

    ths = sorted({eff(x) for t in trees for x in t["nodes"] if "leaf" not in x and x["f"] == LATE and eff(x) is not None
                  and eff(x) < top})
    ni = len(ths) + 1
    rep = [ths[i] if i < len(ths) else ths[-1] + 1 for i in range(ni)]   # a value inside each interval

    def expr(nd, n, v, ti):
        x = nd[n]
        if "leaf" in x:
            return f"{lw}'sd{x['leaf']}" if x["leaf"] >= 0 else f"-{lw}'sd{-x['leaf']}"
        e = eff(x)
        if e is None:
            return expr(nd, x["r"], v, ti)
        if x["f"] == LATE:                        # resolved at generation time for this interval
            return expr(nd, x["l"] if v <= e else x["r"], v, ti)
        return f"(c{ti}_{n} ? {expr(nd, x['l'], v, ti)} : {expr(nd, x['r'], v, ti)})"

    s = _head(name, f"Arm (a) trees, partial evaluation on the late feature: {len(trees)} boosted trees, {ni} intervals of the "
              "late feature.", "results/b87/models/gbt.json", fill, ni)
    s.append(f"    localparam int W = {W};")
    shared, per = [], []
    for i, t in enumerate(trees):
        for n, x in enumerate(t["nodes"]):          # each comparison once, however many intervals use it
            if "leaf" not in x and x["f"] != LATE and eff(x) is not None:
                s.append(f"    wire logic c{i}_{n} = {G87.fsel(x['f']).replace('in_f', 'e_f')} <= {FBITS[x['f']]}'d{eff(x)};")
        ex = [expr(t["nodes"], 0, v, i) for v in rep]
        if all(e == ex[0] for e in ex):
            shared.append(i)
            s.append(f"    logic signed [{lw-1}:0] t{i};\n    assign t{i} = {ex[0]};")
        else:
            per.append(i)
            for v in range(ni):
                s.append(f"    logic signed [{lw-1}:0] t{i}_{v};\n    assign t{i}_{v} = {ex[v]};")
    s.append(f"    // {len(shared)} trees do not use the late feature (computed once); {len(per)} do (once per interval)")
    stage = []
    classes = []
    for v in range(ni):
        for k in range(3):
            terms = " + ".join(f"W'(t{i})" if i in shared else f"W'(t{i}_{v})" for i in per_cls[k])
            s.append(f"    logic signed [W-1:0] s{k}_{v};\n    assign s{k}_{v} = W'({q['prior'][k]}) + {terms};")
        if fill == 2:
            for k in range(3):
                stage.append(f"    logic signed [W-1:0] r{k}_{v};")
            stage.append("    always_ff @(posedge clk) begin")
            stage += [f"        r{k}_{v} <= s{k}_{v};" for k in range(3)]
            stage.append("    end")
            classes.append(G87.argmax3(f"r0_{v}", f"r1_{v}", f"r2_{v}"))
        else:
            classes.append(G87.argmax3(f"s0_{v}", f"s1_{v}", f"s2_{v}"))
    s += _table_regs(fill, ni, classes, stage)
    # late path: x <= th (base) is the complement of x > th, intervals are the same sets
    s += _select(ths, False)
    s.append("endmodule")
    return "\n".join(s) + "\n"


# ------------------------------------------------------------------------------------------ LUT network
def lgs_pe(m: dict, name: str, fill: int) -> str:
    specs, wiring, tables, th = m["layers"], m["wiring"], m["tables"], m["thresholds"]
    assert len(specs) == 1 and m["config"]["output"] == "additive"
    sp = specs[0]
    b = sp["bits"]
    nc = m["config"]["n_classes"]
    pc = m["config"]["per_class"]
    cb = M89.code_bits(th)
    sw = b + _w(pc - 1)
    tl = th[LATE]
    ni = len(tl) + 1
    s = _head(name, f"Arm (c) LUT network lg_small, partial evaluation on the late feature: {len(wiring[0])} neurons, "
              f"{ni} codes of the late feature.", "results/b89/models/lg_small_seed2.json", fill, ni)
    s.append("    // input encoder: code = number of thresholds the feature exceeds (the late feature is not encoded here)")
    for j, t in enumerate(th):
        if j == LATE:
            continue
        f = f"e_f[{FLO[j] + FBITS[j] - 1}:{FLO[j]}]"
        if not t:
            s.append(f"    wire logic [{cb[j]-1}:0] e{j} = '0;")
        else:
            terms = " + ".join(f"{cb[j]}'({f} > {FBITS[j]}'d{x})" for x in t)
            s.append(f"    wire logic [{cb[j]-1}:0] e{j} = {terms};")
    neurons = wiring[0]
    uses = [LATE in w for w in neurons]
    # one table constant per neuron bit
    for j, w in enumerate(neurons):
        ab = sum(cb[c] for c in w)
        for bit in range(b):
            v = 0
            for a, o in enumerate(tables[0][j]):
                if (o >> bit) & 1:
                    v |= 1 << a
            hexw = max(1, (1 << ab) // 4)
            s.append(f"    localparam logic [{(1 << ab) - 1}:0] T{j}_{bit} = {1 << ab}'h{v:0{hexw}x};")
    for j, w in enumerate(neurons):
        ab = sum(cb[c] for c in w)
        variants = range(ni) if uses[j] else [None]
        for v in variants:
            sfx = "" if v is None else f"_{v}"
            addr = ", ".join((f"{cb[c]}'d{v}" if c == LATE else f"e{c}") for c in w)
            s.append(f"    wire logic [{ab-1}:0] a{j}{sfx} = {{{addr}}};")
            s.append(f"    wire logic [{b-1}:0] n{j}{sfx};")
            for bit in range(b):
                s.append(f"    assign n{j}{sfx}[{bit}] = T{j}_{bit}[a{j}{sfx}];")
    stage, classes = [], []
    for v in range(ni):
        for c in range(nc):
            ext = []
            for i in range(pc):
                j = c * pc + i
                nn = f"n{j}_{v}" if uses[j] else f"n{j}"
                s.append(f"    wire logic signed [{sw-1}:0] x{c}_{i}_{v} = {{{{{sw-b}{{{nn}[{b-1}]}}}}, {nn}}};")
                ext.append(f"x{c}_{i}_{v}")
            s.append(f"    wire logic signed [{sw-1}:0] s{c}_{v} = {' + '.join(ext)};")
        if fill == 2:
            for c in range(nc):
                stage.append(f"    logic signed [{sw-1}:0] r{c}_{v};")
            stage.append("    always_ff @(posedge clk) begin")
            stage += [f"        r{c}_{v} <= s{c}_{v};" for c in range(nc)]
            stage.append("    end")
            sc = [f"r{c}_{v}" for c in range(nc)]
        else:
            sc = [f"s{c}_{v}" for c in range(nc)]
        # the base RTL: class 1 if s1 > s0 else 0; then 2 if s2 > that max (strict compares)
        s.append(f"    wire logic g10_{v} = {sc[1]} > {sc[0]};")
        s.append(f"    wire logic signed [{sw-1}:0] m01_{v} = g10_{v} ? {sc[1]} : {sc[0]};")
        s.append(f"    wire logic [1:0] k_{v} = ({sc[2]} > m01_{v}) ? 2'd2 : (g10_{v} ? 2'd1 : 2'd0);")
        classes.append(f"k_{v}")
    # k_v wires are combinational from r/s; with FILL=2 the table fill sees the staged scores
    s += _table_regs(fill, ni, classes, stage)
    s += _select(tl, True)
    s.append("endmodule")
    return "\n".join(s) + "\n"


def build() -> dict[str, str]:
    q = json.loads((G87.MODELS / "gbt.json").read_text())
    m = json.loads(LG_MODEL.read_text())
    return {k: _wrap(v) for k, v in _build(q, m).items()}


def _wrap(txt: str) -> str:
    """Lint pragmas: the packed late bits of e_f are ignored by design, and FILL / LATENCY_LATE are documentation."""
    a = txt.index("module ")
    return (txt[:a] + "// verilator lint_off UNUSEDSIGNAL\n// verilator lint_off UNUSEDPARAM\n" + txt[a:]
            + "// verilator lint_on UNUSEDPARAM\n// verilator lint_on UNUSEDSIGNAL\n")


def _build(q, m) -> dict[str, str]:
    return {"gbt_pe": gbt_pe(q, "gbt_pe", 1), "gbt_pe2": gbt_pe(q, "gbt_pe2", 2),
            "lgs_pe": lgs_pe(m, "lgs_pe", 1), "lgs_pe2": lgs_pe(m, "lgs_pe2", 2)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    files = build()
    bad = 0
    OUT.mkdir(parents=True, exist_ok=True)
    for n, txt in files.items():
        p = OUT / f"{n}.sv"
        if a.check:
            if not p.exists() or p.read_text() != txt:
                print(f"out of date: {p}")
                bad += 1
        else:
            p.write_text(txt)
            print("wrote", p)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
