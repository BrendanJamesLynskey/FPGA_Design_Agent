"""The ML registers of build rm_gp_ml (brief 113) as data; `python3 designs/b96_kr260_10g/rm_gp_ml/regmap_ml.py --write` regenerates docs/ml_registers.md.

These registers come on top of the register map of the base design (docs/register_map.md, same bus, same rules: unmapped addresses read 0 and ignore writes, reserved bits read 0 and are ignored
on write, reads have no side effects). They exist only in build rm_gp_ml; FEATURES (0x008) bit 8 reads 1 there and 0 in every other build.
"""

from __future__ import annotations

import sys
from pathlib import Path

#: (address, name, access, reset, description)
REGS = [
    (0x300, "ML_CTRL", "RW (bit 1 W1P)", "0",
     "bit 0 VETO: 0 = shadow (the rule decides alone; a decision the model would have stopped is only counted, MLV6); 1 = veto (a rule decision for the tracked instrument sends no order unless the model's class "
     "for the message is \"up\"; a vetoed decision takes no order number and is counted, MLV5). bit 1 RESET_STATE: write 1 to clear the stage's state (book, windows, snapshot, pending message) and its counters; reads 0. "
     "Other bits reserved."),
    (0x304, "ML_INST", "RW", "1", "bits 15:0 the tracked instrument (reset 1, the generator's instrument). Messages for other instruments are never classified and never move the stage's state; the rule's decisions for them pass unchanged."),
    (0x308, "ML_ID", "RO", "0x01130001", "Identifier of the ML registers: 0x0113 (brief 113), version 1."),
]
RANGES = [(0x310, 14, "MLV", "Status snapshot of the ML stage, 14 words (MLV0 is 0x310), taken by CMD bit 2 together with RXV and TXV. See the table below.")]
MLV = ["n_obs: frames the rule path accepted whose message is for the tracked instrument (the stage observed it at the price word)",
       "n_cls_down: observed messages whose class was 0 (down)", "n_cls_flat: observed messages whose class was 1 (flat)", "n_cls_up: observed messages whose class was 2 (up)",
       "n_dec: decisions the rule wanted to act on (armed, not killed, TRADE_EN, price test passed) for the tracked instrument",
       "n_veto: decisions stopped by the model (veto mode only)", "n_would_veto: decisions the model would have stopped (shadow mode only)",
       "n_late: observations made before the class had settled (must be 0; with frames at least 10 clocks apart it cannot happen)",
       "n_apply: good frames whose message moved the state", "n_drop: bad frames (FCS, length or error character) whose message was observed and then discarded",
       "n_race: a state update arrived before the class pipeline had settled from the previous one (must be 0)",
       "last_feat[31:0]: the 38-bit feature vector of the last observed message, low word (dir[37:36] ofi[35:28] trades[27:23] imb[22:20] spread[19:16] ask[15:8] bid[7:0])",
       "bits 7:6 the last observed message's class, bits 5:0 last_feat[37:32]",
       "debug view: the low bytes of the tracked instrument's book: [31:24] best bid price, [23:16] best bid size, [15:8] best ask price, [7:0] best ask size"]


def render() -> str:
    o = ["# rm_gp_ml: ML decision stage registers (generated by regmap_ml.py; do not edit)", "",
         "Added to the base design's map (docs/register_map.md, whose rules apply: **unmapped addresses** read 0 and ignore writes, **reserved bits** read 0 and are ignored on write, **reads have no side effects**, "
         "the status words are read from a **snapshot** taken by CMD bit 2). Present only in build rm_gp_ml: FEATURES (0x008) **bit 8 reads 1** there. The stage lives in the core clock (TXUSRCLK2); the configuration "
         "crosses by the same request/acknowledge handshake as the other configuration (hs_vec) and the status words come back the same way, a few clocks old.", "",
         "| Address | Name | Access | Reset | Description |", "|---|---|---|---|---|"]
    for a, n, acc, rst, d in REGS:
        o.append(f"| 0x{a:03X} | {n} | {acc} | {rst} | {d} |")
    for a, n, name, d in RANGES:
        o.append(f"| 0x{a:03X} to 0x{a + 4 * (n - 1):03X} | {name}0 to {name}{n - 1} | RO | 0 | {d} |")
    o += ["", "## MLV words", "", "| Word | Address | Content |", "|---|---|---|"]
    o += [f"| MLV{i} | 0x{0x310 + 4 * i:03X} | {t} |" for i, t in enumerate(MLV)]
    o += ["", "## What a user could guess wrong", "",
          "- **Shadow is the reset state.** ML_CTRL resets to 0: the rule decides exactly as in build rm_gp and the model only counts. Veto mode must be switched on.",
          "- **Counters clear with CMD bit 0 (the base counters' clear) and with ML_CTRL bit 1.** Only ML_CTRL bit 1 also clears the stage's state (book, order-flow window, trade window, previous snapshot). "
          "The state is also cleared whenever the transmit side restarts (any GT reset that drops TX_DONE).",
          "- **Messages move the state only when their frame ends good.** A frame with a bad FCS, a length different from its IPv4 length plus 18, or a cut by an error character is observed (counted in n_obs and by class) "
          "but changes nothing (n_drop). A message in a frame longer than 60 bytes of IPv4 length (two or more messages), for another port, another MAC address or with a bad header is not observed at all: the rule path does not act on it either.",
          "- **The class is of the book BEFORE the message.** No input of the model depends on the message's own price, size, type or side; the message moves the state after the decision. So the first message after a reset or a "
          "restart is classified on an empty book.",
          "- **The stage sees the first message of a frame only**, like the rule.",
          "- **A decision for another instrument is never vetoed** (it passes as if the stage were not there), whatever the class.",
          "- **A buy needs \"up\".** The base design only sends buys. Class 2 = up, 1 = flat, 0 = down; ties between class scores go to the lower index (gbt_comb).",
          "- **n_late is a fail-closed counter.** If a decision ever came before the class had settled, in veto mode it is vetoed (counted in n_late and n_veto).",
          "- **Changing ML_INST** changes which messages are tracked from the next message on; the state (a book of the previous instrument) is not cleared, write ML_CTRL bit 1 as well.",
          "- **Latency.** The model adds no clock to the tick-to-trade in either mode (docs/ml_stage.md); this holds only while frames are at least 10 clocks apart.", ""]
    return "\n".join(o)


if __name__ == "__main__":
    out = Path(__file__).parent / "docs" / "ml_registers.md"
    if "--write" in sys.argv:
        out.write_text(render())
        print("wrote", out)
    else:
        print(render())
