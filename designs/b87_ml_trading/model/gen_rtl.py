"""Generate the hand-RTL arms from the integer models in results/b87/models/.

    python3 -m designs.b87_ml_trading.model.gen_rtl            # write designs/b87_ml_trading/rtl/gen/*.sv
    python3 -m designs.b87_ml_trading.model.gen_rtl --check    # fail if a committed file is out of date

Every arm has the same ports:

    clk, rst (synchronous, active high; resets the valid pipeline only), in_v, in_f[37:0] (the packed features,
    registered by the producer), out_v, out_cls[1:0] (0 down, 1 flat, 2 up)

and a `LATENCY` localparam: out_v follows in_v by exactly LATENCY clocks, whatever the features (no data-dependent
path; initiation interval 1). Features are packed f0 in the least significant bits: f0[7:0] f1[15:8] f2[19:16]
f3[22:20] f4[27:23] f5[35:28] f6[37:36]. Ties between class scores go to the lower class index.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MODELS = ROOT / "results" / "b87" / "models"
OUT = Path(__file__).resolve().parents[1] / "rtl" / "gen"
FBITS = [8, 8, 4, 3, 5, 8, 2]
FLO = [sum(FBITS[:i]) for i in range(7)]

HEAD = """// {name}.sv: GENERATED by designs/b87_ml_trading/model/gen_rtl.py from results/b87/models/{model}.json. Do not edit.
// {what}
// Ports: features in (registered by the producer), class out (registered). LATENCY = {lat} clocks, initiation
// interval 1, no data-dependent path. Ties between class scores go to the lower class index.
"""


def fsel(j: int) -> str:
    return f"in_f[{FLO[j] + FBITS[j] - 1}:{FLO[j]}]"


def ports(name: str, lat: int) -> str:
    return (f"module {name} (\n    input  logic        clk,\n    input  logic        rst,\n    input  logic        in_v,\n"
            f"    input  logic [37:0] in_f,\n    output logic        out_v,\n    output logic [1:0]  out_cls\n);\n"
            f"    localparam int LATENCY = {lat};\n"
            f"    logic [LATENCY-1:0] vpipe;\n"
            f"    always_ff @(posedge clk) begin\n        if (rst) vpipe <= '0;\n"
            + ("        else     vpipe <= in_v;\n" if lat == 1 else "        else     vpipe <= {vpipe[LATENCY-2:0], in_v};\n")
            + "    end\n    assign out_v = vpipe[LATENCY-1];\n")


def argmax3(a: str, b: str, c: str) -> str:
    return f"(({a} >= {b}) && ({a} >= {c})) ? 2'd0 : (({b} >= {c}) ? 2'd1 : 2'd2)"


def sw(vals) -> int:
    m = max(abs(int(v)) for v in vals) if vals else 1
    return max(2, math.ceil(math.log2(m + 1)) + 1)


# ------------------------------------------------------------------------------------------------------- trees
def gbt(q: dict, pipelined: bool) -> str:
    name = "gbt_pipe" if pipelined else "gbt_comb"
    trees = q["trees"]
    ntr = len(trees)
    per_cls = [[i for i, t in enumerate(trees) if t["cls"] == k] for k in range(3)]
    leaves = [n["leaf"] for t in trees for n in t["nodes"] if "leaf" in n]
    lw = sw(leaves)
    tot = [abs(q["prior"][k]) + sum(max(abs(n["leaf"]) for n in trees[i]["nodes"] if "leaf" in n) for i in per_cls[k])
           for k in range(3)]
    W = sw([max(tot)])
    depth = q["depth"]
    nadd = math.ceil(math.log2(len(per_cls[0]) + 1))
    lat = 1 if not pipelined else 1 + depth + 1 + nadd + 1
    what = (f"Arm (a): {ntr} boosted trees (3 classes x {len(per_cls[0])} rounds, depth {depth}), "
            + ("fully combinational between the input and output registers." if not pipelined else
               "one clock for all comparisons, one clock per tree level, one for the leaf values, one per adder level, "
               "one for the argmax."))
    s = [HEAD.format(name=name, model="gbt", what=what, lat=lat), ports(name, lat)]
    s.append(f"    localparam int W = {W};   // class score width (signed): prior plus the largest leaf of every tree\n")
    if not pipelined:
        for i, t in enumerate(trees):
            nd = t["nodes"]

            def expr(n):
                x = nd[n]
                if "leaf" in x:
                    return f"{lw}'sd{x['leaf']}" if x["leaf"] >= 0 else f"-{lw}'sd{-x['leaf']}"
                return f"(({fsel(x['f'])} <= {FBITS[x['f']]}'d{max(0, min(x['t'], (1 << FBITS[x['f']]) - 1))}) ? " \
                       f"{expr(x['l'])} : {expr(x['r'])})" if x["t"] >= 0 else expr(x["r"])
            s.append(f"    logic signed [{lw-1}:0] t{i};\n    assign t{i} = {expr(0)};\n")
        for k in range(3):
            terms = " + ".join([f"W'(t{i})" for i in per_cls[k]])
            s.append(f"    logic signed [W-1:0] s{k};\n    assign s{k} = W'({q['prior'][k]}) + {terms};\n")
        s.append(f"    always_ff @(posedge clk) out_cls <= {argmax3('s0', 's1', 's2')};\nendmodule\n")
        return "".join(s)
    # pipelined: stage 1 all comparisons; stages 2..depth+1 walk one level per clock; then leaf values; adder tree
    for i, t in enumerate(trees):
        nd = t["nodes"]
        nb = max(1, math.ceil(math.log2(len(nd))))
        inner = [j for j, x in enumerate(nd) if "leaf" not in x]
        s.append(f"    // tree {i}\n    logic [{len(nd)-1}:0] c{i}_0;\n")
        cmp = []
        for j in range(len(nd)):
            x = nd[j]
            if "leaf" in x:
                cmp.append("1'b0")
            elif x["t"] < 0:
                cmp.append("1'b0")
            else:
                cmp.append(f"({fsel(x['f'])} <= {FBITS[x['f']]}'d{min(x['t'], (1 << FBITS[x['f']]) - 1)})")
        s.append(f"    always_ff @(posedge clk) c{i}_0 <= {{{', '.join(reversed(cmp))}}};\n")
        for lv in range(depth):
            s.append(f"    logic [{len(nd)-1}:0] c{i}_{lv+1};\n    logic [{nb-1}:0] n{i}_{lv+1};\n")
            prev = f"n{i}_{lv}" if lv else f"{nb}'d0"
            cases = "".join(f"            {nb}'d{j}: n{i}_{lv+1} <= c{i}_{lv}[{j}] ? {nb}'d{nd[j]['l']} : {nb}'d{nd[j]['r']};\n"
                            for j in inner)
            s.append(f"    always_ff @(posedge clk) begin\n        c{i}_{lv+1} <= c{i}_{lv};\n        case ({prev})\n"
                     f"{cases}            default: n{i}_{lv+1} <= {prev};\n        endcase\n    end\n")
        lcases = "".join(f"            {nb}'d{j}: l{i} <= {lw}'sd{x['leaf']};\n" if x["leaf"] >= 0 else
                         f"            {nb}'d{j}: l{i} <= -{lw}'sd{-x['leaf']};\n" for j, x in enumerate(nd) if "leaf" in x)
        s.append(f"    logic signed [{lw-1}:0] l{i};\n    always_ff @(posedge clk) begin\n        case (n{i}_{depth})\n{lcases}"
                 f"            default: l{i} <= '0;\n        endcase\n    end\n")
    for k in range(3):
        terms = [f"W'(l{i})" for i in per_cls[k]] + [f"W'({q['prior'][k]})"]
        lvl = 0
        while len(terms) > 1:
            nxt = []
            for j in range(0, len(terms), 2):
                nm = f"a{k}_{lvl}_{j//2}"
                rhs = " + ".join(terms[j:j + 2])
                s.append(f"    logic signed [W-1:0] {nm};\n    always_ff @(posedge clk) {nm} <= {rhs};\n")
                nxt.append(nm)
            terms, lvl = nxt, lvl + 1
        assert lvl == nadd, (lvl, nadd)
        s.append(f"    logic signed [W-1:0] s{k};\n    assign s{k} = {terms[0]};\n")
    s.append(f"    always_ff @(posedge clk) out_cls <= {argmax3('s0', 's1', 's2')};\nendmodule\n")
    return "".join(s)


# ---------------------------------------------------------------------------------------------------------- MLP
def mlp(q: dict) -> str:
    name = "mlp_hand"
    nl = len(q["W"])
    lat = 2 * nl + 1
    what = (f"Arm (b), hand RTL: MLP {'-'.join(map(str, q['sizes']))}, int8 weights, uint8 activations; per layer one "
            "clock for the products and one for the sum, bias, shift and saturation; one clock for the argmax.")
    s = [HEAD.format(name=name, model="mlp", what=what, lat=lat), ports(name, lat)]
    off = q["offsets"]
    s.append("    // layer 0 input: the features minus their offsets, signed\n")
    for j in range(7):
        s.append(f"    logic signed [9:0] x0_{j};\n    assign x0_{j} = $signed({{2'b00, {fsel(j)}}}) - 10'sd{off[j]};\n"
                 if FBITS[j] == 8 else
                 f"    logic signed [9:0] x0_{j};\n    assign x0_{j} = $signed(10'({fsel(j)})) - 10'sd{off[j]};\n")
    nin = 7
    for li in range(nl):
        W, b = q["W"][li], q["b"][li]
        nout = len(W)
        xw = 10 if li == 0 else 9
        pw = xw + 8
        aw = pw + math.ceil(math.log2(nin)) + 1
        bw = sw(b)
        aw = max(aw, bw) + 1
        s.append(f"    // layer {li}: {nin} -> {nout}\n")
        for o in range(nout):
            for i in range(nin):
                w = W[o][i]
                s.append(f"    logic signed [{pw-1}:0] p{li}_{o}_{i};\n"
                         f"    always_ff @(posedge clk) p{li}_{o}_{i} <= x{li}_{i} * {'-' if w < 0 else ''}{pw}'sd{abs(w)};\n")
            terms = " + ".join(f"{aw}'(p{li}_{o}_{i})" for i in range(nin))
            bias = f"{'-' if b[o] < 0 else ''}{aw}'sd{abs(b[o])}"
            if li < nl - 1:
                sh = q["fw"][li] + q["fin"][li] - q["fa"][li]
                s.append(f"    logic signed [{aw-1}:0] acc{li}_{o};\n    assign acc{li}_{o} = {terms} + {bias};\n"
                         f"    logic signed [{aw-1}:0] sh{li}_{o};\n"
                         f"    assign sh{li}_{o} = {'acc%d_%d >>> %d' % (li, o, sh) if sh >= 0 else 'acc%d_%d <<< %d' % (li, o, -sh)};\n"
                         f"    logic signed [8:0] x{li+1}_{o};   // uint8 activation in a signed container\n"
                         f"    always_ff @(posedge clk) x{li+1}_{o} <= sh{li}_{o} < 0 ? 9'sd0 : "
                         f"(sh{li}_{o} > {aw}'sd255 ? 9'sd255 : 9'(sh{li}_{o}));\n")
            else:
                s.append(f"    logic signed [{aw-1}:0] z{o};\n    always_ff @(posedge clk) z{o} <= {terms} + {bias};\n")
        nin = nout
    s.append(f"    always_ff @(posedge clk) out_cls <= {argmax3('z0', 'z1', 'z2')};\nendmodule\n")
    return "".join(s)


# --------------------------------------------------------------------------------------------------- LUT network
def lutnet(q: dict) -> str:
    name = "lutnet"
    layers = q["layers"]
    lat = len(layers)
    what = ("Arm (c): LUT network from our generator: 2-bit input codes, layers "
            + ", ".join(f"{n}x{k}" for n, k, _ in layers)
            + " (neurons x fan-in), each neuron a truth table; one clock per layer, the argmax with the last.")
    s = [HEAD.format(name=name, model="lutnet", what=what, lat=lat), ports(name, lat)]
    th = q["thresholds"]
    for j in range(7):
        bits = FBITS[j]
        cmps = " + ".join(f"2'({fsel(j)} > {bits}'d{min(t, (1 << bits) - 1)})" for t in th[j])
        s.append(f"    logic [1:0] c0_{j};\n    assign c0_{j} = {cmps};\n")
    for li, (n, k, ob) in enumerate(layers):
        ib = 2 if li == 0 else layers[li - 1][2]
        last = li == len(layers) - 1
        for jn in range(n):
            tab = q["tables"][li][jn]
            ins = ", ".join(f"c{li}_{c}" for c in q["wiring"][li][jn])
            aw = ib * k
            fn = f"f{li}_{jn}"
            items = []
            for a, v in enumerate(tab):
                vv = v & ((1 << ob) - 1)
                items.append(f"            {aw}'d{a}: {fn} = {ob}'d{vv};\n")
            s.append(f"    function automatic logic [{ob-1}:0] {fn}(input logic [{aw-1}:0] a);\n        case (a)\n"
                     + "".join(items) + f"            default: {fn} = '0;\n        endcase\n    endfunction\n")
            if not last:
                s.append(f"    logic [{ob-1}:0] c{li+1}_{jn};\n    always_ff @(posedge clk) c{li+1}_{jn} <= {fn}({{{ins}}});\n")
            else:
                s.append(f"    logic signed [{ob-1}:0] o{jn};\n    assign o{jn} = $signed({fn}({{{ins}}}));\n")
    s.append(f"    always_ff @(posedge clk) out_cls <= {argmax3('o0', 'o1', 'o2')};\nendmodule\n")
    return "".join(s)


def imb_rule(r: dict) -> str:
    name = "imb_rule"
    what = f"The trivial rule in RTL: up if the imbalance bucket >= {r['hi']}, down if <= {r['lo']}, else flat."
    s = [HEAD.format(name=name, model="imbalance_rule", what=what, lat=1), ports(name, 1)]
    b = fsel(3)
    lo = f"($signed({{1'b0, {b}}}) <= 4'sd{r['lo']})" if r["lo"] >= 0 else f"($signed({{1'b0, {b}}}) <= -4'sd{-r['lo']})"
    s.append(f"    always_ff @(posedge clk) out_cls <= ({{1'b0, {b}}} >= 4'd{r['hi']}) ? 2'd2 : ({lo} ? 2'd0 : 2'd1);\n"
             "endmodule\n")
    return "".join(s)


def generate() -> dict[str, str]:
    g = json.loads((MODELS / "gbt.json").read_text())
    m = json.loads((MODELS / "mlp.json").read_text())
    lt = json.loads((MODELS / "lutnet.json").read_text())
    r = json.loads((MODELS / "imbalance_rule.json").read_text())
    return {"imb_rule.sv": imb_rule(r), "gbt_comb.sv": gbt(g, False), "gbt_pipe.sv": gbt(g, True), "mlp_hand.sv": mlp(m), "lutnet.sv": lutnet(lt)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    bad = 0
    for fn, txt in generate().items():
        p = OUT / fn
        if a.check:
            if not p.exists() or p.read_text() != txt:
                print(f"out of date: {p}")
                bad += 1
        else:
            p.write_text(txt)
            print(f"wrote {p}")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
