"""The reference point: TreeLUT (Khataei and Bazargan, FPGA '25, arXiv 2501.01511; github.com/kiabuzz/TreeLUT, MIT,
pinned at commit ad9e70a9ba1a74ccf8df97a3f7fcdc9137e68b21) run on the brief 87 data. TreeLUT is used as a tool,
from its own virtual environment; none of its code is in this repository, only the Verilog it generated
(rtl/treelut/, with its licence notice) and our measurements.

    <treelut venv>/bin/python -m designs.b89_lutnet_gen.treelut_ref.run_treelut tune      # validation grid
    <treelut venv>/bin/python -m designs.b89_lutnet_gen.treelut_ref.run_treelut build     # 3 seeds, RTL of seed 0
    <treelut venv>/bin/python -m designs.b89_lutnet_gen.treelut_ref.run_treelut score     # test split (after prereg)
    <treelut venv>/bin/python -m designs.b89_lutnet_gen.treelut_ref.run_treelut random    # random inputs (RTL test)

Features go in unchanged: every 87 feature is already an unsigned integer of at most 8 bits, so w_feature = 8 and no
input quantisation is applied (TreeLUT's first step is that quantisation).
"""
from __future__ import annotations

import itertools
import json
import shutil
import sys
from pathlib import Path

import numpy as np

from designs.b89_lutnet_gen.lutgen import data as Dm

ROOT = Dm.ROOT
OUT = ROOT / "results" / "b89" / "treelut"
RTL = ROOT / "designs" / "b89_lutnet_gen" / "rtl" / "treelut"
BUILD = ROOT / "build" / "b89" / "treelut"
COMMIT = "ad9e70a9ba1a74ccf8df97a3f7fcdc9137e68b21"
PIPELINE = [0, 1, 1]          # TreeLUT pipeline: no register after the compares, one after the trees, one in the adders
SEEDS = (0, 1, 2)


WRAP = """// treelut_arm.sv: GENERATED by designs/b89_lutnet_gen/treelut_ref/run_treelut.py (our code). Do not edit.
// The brief 87 arm interface around the TreeLUT-generated module (TreeLUT.v, commit {commit}, MIT): each 87
// feature zero-extended to 8 bits, TreeLUT's unsigned class scores, argmax (ties to the lowest class) into the
// output register. LATENCY = TreeLUT pipeline registers (2) + the output register.
`default_nettype none
module treelut_arm (
    input  wire logic        clk,
    input  wire logic        rst,
    input  wire logic        in_v,
    input  wire logic [37:0] in_f,
    output logic             out_v,
    output logic [1:0]       out_cls
);
    localparam int LATENCY = {lat};
    localparam int SW = {sw};
    wire logic [55:0] i = {{6'd0, in_f[37:36], in_f[35:28], 3'd0, in_f[27:23], 5'd0, in_f[22:20],
                            4'd0, in_f[19:16], in_f[15:8], in_f[7:0]}};
    wire logic [3*SW-1:0] o;
    TreeLUT u_tl (.clk(clk), .i(i), .o(o));
    wire logic [SW-1:0] s0 = o[SW-1:0], s1 = o[2*SW-1:SW], s2 = o[3*SW-1:2*SW];
    wire logic [SW-1:0] m01 = (s1 > s0) ? s1 : s0;
    wire logic [1:0] c01 = (s1 > s0) ? 2'd1 : 2'd0;
    logic [LATENCY-1:0] vpipe;
    always_ff @(posedge clk) begin
        out_cls <= (s2 > m01) ? 2'd2 : c01;
        if (rst) vpipe <= '0; else vpipe <= {{vpipe[LATENCY-2:0], in_v}};
    end
    assign out_v = vpipe[LATENCY-1];
endmodule
`default_nettype wire
"""

NOTICE = """# TreeLUT-generated Verilog

`TreeLUT.v` here was generated by TreeLUT (Alireza Khataei and Kia Bazargan, "TreeLUT: An Efficient Alternative to
Deep Neural Networks for Inference Acceleration Using Gradient Boosted Decision Trees", FPGA '25, arXiv 2501.01511),
https://github.com/kiabuzz/TreeLUT at commit `{commit}`, MIT licence (Copyright (c) 2024 Kia Bazargan), from an
XGBoost model we trained on the brief 87 synthetic data. Only the generated output is committed; TreeLUT itself is
installed in its own virtual environment (designs/b89_lutnet_gen/docs/treelut.md). `treelut_arm.sv` is ours.
"""


def fit(X, y, n, depth, eta, seed):
    import xgboost as xgb
    m = xgb.XGBClassifier(n_estimators=n, max_depth=depth, learning_rate=eta, objective="multi:softmax",
                          subsample=0.8, random_state=seed, n_jobs=2, tree_method="exact")
    m.fit(X, y)
    return m


def load(seed, c):
    """A saved model; load_model does not restore n_estimators, which TreeLUT reads, so it is set again."""
    from xgboost import XGBClassifier
    m = XGBClassifier()
    m.load_model(str(BUILD / f"xgb_seed{seed}.json"))
    m.set_params(n_estimators=c["n_estimators"], max_depth=c["max_depth"], objective="multi:softmax")
    return m


def treelut(m, w_tree, d=BUILD / "tmp"):
    from treelut import TreeLUTClassifier
    d.mkdir(parents=True, exist_ok=True)
    t = TreeLUTClassifier(xgb_model=m, w_feature=8, w_tree=w_tree, pipeline=list(PIPELINE), dir_path=str(d))
    t.convert()
    return t


def tune():
    d = Dm.load(("train", "val"))
    (Xtr, ytr, _), (Xv, yv, _) = d["train"], d["val"]
    rows = []
    for n, depth, eta, wt in itertools.product((10, 20, 40), (2, 3, 4), (0.3,), (2, 3, 4)):
        m = fit(Xtr, ytr, n, depth, eta, 0)
        t = treelut(m, wt)
        rows.append({"n_estimators": n, "max_depth": depth, "eta": eta, "w_tree": wt,
                     "val_float": round(float((m.predict(Xv) == yv).mean()), 4),
                     "val_treelut": round(float((t.predict(Xv) == yv).mean()), 4)})
        print(rows[-1], flush=True)
    # choose: best TreeLUT validation accuracy; among those within 0.002 of it, the smallest model (trees x depth)
    best = max(r["val_treelut"] for r in rows)
    pick = min((r for r in rows if r["val_treelut"] >= best - 0.002),
               key=lambda r: (r["n_estimators"] * 2 ** r["max_depth"], r["w_tree"]))
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "tuning.json").write_text(json.dumps({"treelut_commit": COMMIT, "grid": rows, "chosen": pick,
                                                 "rule": "best validation accuracy of the TreeLUT-quantised model; "
                                                         "within 0.002 of it, the smallest trees x 2^depth"}, indent=1))
    print("chosen", pick)


def build():
    d = Dm.load(("train", "val"))
    (Xtr, ytr, _), (Xv, yv, _) = d["train"], d["val"]
    c = json.loads((OUT / "tuning.json").read_text())["chosen"]
    runs = []
    for s in SEEDS:
        m = fit(Xtr, ytr, c["n_estimators"], c["max_depth"], c["eta"], s)
        BUILD.mkdir(parents=True, exist_ok=True)
        m.save_model(str(BUILD / f"xgb_seed{s}.json"))
        t = treelut(m, c["w_tree"], BUILD / f"seed{s}")
        runs.append({"seed": s, "val_treelut": round(float((t.predict(Xv) == yv).mean()), 4)})
        if s == 0:
            t.verilog()
            RTL.mkdir(parents=True, exist_ok=True)
            for f in sorted((BUILD / f"seed{s}" / "TreeLUT" / "verilog").glob("*.v")):
                shutil.copy(f, RTL / f.name)
            (RTL / "treelut_arm.sv").write_text(WRAP.format(sw=t._sum_bit_length, lat=sum(PIPELINE) + 1,
                                                            commit=COMMIT))
            (RTL / "NOTICE.md").write_text(NOTICE.format(commit=COMMIT))
    (OUT / "build.json").write_text(json.dumps({"treelut_commit": COMMIT, "config": c, "pipeline": PIPELINE,
                                                "runs": runs}, indent=1))
    print(runs)


def score():
    """Test-split predictions of the three seeds (TreeLUT's own integer predict), written for evaluate.py; seed 0's
    are also the expected classes of the RTL test."""
    d = Dm.load(("train", "test"))
    (Xtr, ytr, _), (Xte, yte, gte) = d["train"], d["test"]
    c = json.loads((OUT / "tuning.json").read_text())["chosen"]
    preds = {}
    for s in SEEDS:
        m = load(s, c)
        t = treelut(m, c["w_tree"], BUILD / f"score{s}")
        preds[f"seed{s}"] = t.predict(Xte).astype(np.uint8)
    np.savez_compressed(OUT / "test_predictions.npz", **preds)
    print({k: round(float((v == yte).mean()), 4) for k, v in preds.items()})


def random_inputs():
    """Seed 0's predictions on the lutgen RTL test's random packed inputs (for the TreeLUT RTL test off the data)."""
    c = json.loads((OUT / "tuning.json").read_text())["chosen"]
    from designs.b89_lutnet_gen.lutgen import sim as S      # the same random inputs as the lutgen RTL test
    m = load(0, c)
    np.savez_compressed(OUT / "random_predictions.npz",
                        seed0=treelut(m, c["w_tree"], BUILD / "random0").predict(S.random_features(20000, 89)).astype(np.uint8))


if __name__ == "__main__":
    {"tune": tune, "build": build, "score": score, "random": random_inputs}[sys.argv[1]]()
