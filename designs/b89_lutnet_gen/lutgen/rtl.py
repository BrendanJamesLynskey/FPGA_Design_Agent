"""Emit SystemVerilog for a lutgen model (model.py). The RTL is read from the tables alone, as the twin is.

Ports (the brief 87 arm interface, so the 87 test bench and out-of-context wrapper take it unchanged):

    clk; rst (synchronous, active high; clears the valid pipeline only, never the datapath);
    in_v, in_f[FW-1:0] (packed unsigned features, feature 0 in the least significant bits, widths `fbits`);
    out_v, out_cls[1:0] (argmax of the class scores, ties to the lowest class index).

Pipelining (`pipe`), counted in clocks from in_v to out_v, which is the module's `LATENCY` localparam:

    "comb"     one register, at the output (encoder, every LUT layer, the adder and the argmax in one clock): LATENCY 1
    "layer"    a register after every LUT layer and at the output: LATENCY = LUT layers + 1
    N (int)    a register after every N-th LUT layer and at the output (N >= 1; "layer" is N = 1)

The input encoder's compares sit in front of the first LUT layer in the same clock; `reg_encoder=True` adds a
register after them (LATENCY + 1). The latency is fixed: no stage depends on the data. The feature inputs are not
registered here (the producer's register; the 87 out-of-context wrapper adds one).

Each neuron output bit is a constant vector indexed by the neuron's packed input codes (first wired input in the most
significant bits), which synthesis maps to LUTs.
"""
from __future__ import annotations

import math

from . import model as M


def _w(n):
    return max(1, math.ceil(math.log2(n + 1)))


def emit(m: dict, name: str, fbits: list[int], pipe="layer", reg_encoder: bool = False, source: str = "") -> str:
    specs, wiring, tables, th = m["layers"], m["wiring"], m["tables"], m["thresholds"]
    cfg = m["config"]
    nl = len(specs)
    if pipe == "comb":
        regs_after = set()
    elif pipe == "layer":
        regs_after = set(range(nl - 1))
    elif isinstance(pipe, int) and pipe >= 1:
        regs_after = {i for i in range(nl - 1) if (i + 1) % pipe == 0}
    else:
        raise ValueError("pipe must be 'comb', 'layer' or a positive integer")
    latency = 1 + len(regs_after) + (1 if reg_encoder else 0)
    fw = sum(fbits)
    flo = [sum(fbits[:i]) for i in range(len(fbits))]
    cb = M.code_bits(th)
    L = []
    a = L.append
    a(f"// {name}.sv: GENERATED by designs/b89_lutnet_gen/lutgen (rtl.py){' from ' + source if source else ''}. Do not edit.")
    a(f"// LUT network: {len(th)} inputs -> " + " -> ".join(f"{s['n']}x(fan-in {s['k']}, {s['bits']}b{' signed' if s['signed'] else ''})" for s in specs)
      + f"; output {cfg['output']}; pipe {pipe}{', encoder registered' if reg_encoder else ''}; LATENCY {latency}.")
    a("// out_v follows in_v by exactly LATENCY clocks for every input (no data-dependent path); one input a clock.")
    a("// rst is synchronous, active high, and clears only the valid pipeline.")
    a("`default_nettype none")
    a(f"module {name} (")
    a("    input  wire logic        clk,")
    a("    input  wire logic        rst,")
    a("    input  wire logic        in_v,")
    a(f"    input  wire logic [{fw - 1}:0] in_f,")
    a("    output logic             out_v,")
    a("    output logic [1:0]       out_cls")
    a(");")
    a(f"    localparam int LATENCY = {latency};")
    # ---- encoder
    a("    // input encoder: code = number of thresholds the feature exceeds")
    for j, t in enumerate(th):
        f = f"in_f[{flo[j] + fbits[j] - 1}:{flo[j]}]"
        if not t:
            a(f"    wire logic [{cb[j] - 1}:0] e{j} = '0;")
            continue
        terms = " + ".join(f"{cb[j]}'({f} > {fbits[j]}'d{x})" for x in t)
        a(f"    wire logic [{cb[j] - 1}:0] e{j} = {terms};")
    src = [f"e{j}" for j in range(len(th))]
    srcb = cb
    if reg_encoder:
        for j in range(len(th)):
            a(f"    logic [{cb[j] - 1}:0] r{j};")
        a("    always_ff @(posedge clk) begin")
        for j in range(len(th)):
            a(f"        r{j} <= e{j};")
        a("    end")
        src = [f"r{j}" for j in range(len(th))]
    # ---- LUT layers
    for li, sp in enumerate(specs):
        b = sp["bits"]
        a(f"    // layer {li + 1}: {sp['n']} neurons, {b}-bit {'signed scores' if sp['signed'] else 'codes'}")
        outs = []
        for j, w in enumerate(wiring[li]):
            ab = sum(srcb[c] for c in w)
            addr = "{" + ", ".join(src[c] for c in w) + "}"
            tab = tables[li][j]
            a(f"    wire logic [{ab - 1}:0] a{li}_{j} = {addr};")
            a(f"    wire logic [{b - 1}:0] n{li}_{j};")
            for bit in range(b):
                v = 0
                for addr_i, o in enumerate(tab):
                    if (o >> bit) & 1:                     # two's complement for signed scores
                        v |= 1 << addr_i
                hexw = max(1, (1 << ab) // 4)
                a(f"    localparam logic [{(1 << ab) - 1}:0] T{li}_{j}_{bit} = {1 << ab}'h{v:0{hexw}x};")
                a(f"    assign n{li}_{j}[{bit}] = T{li}_{j}_{bit}[a{li}_{j}];")
            outs.append(f"n{li}_{j}")
        if li in regs_after:
            for j in range(sp["n"]):
                a(f"    logic [{b - 1}:0] q{li}_{j};")
            a("    always_ff @(posedge clk) begin")
            for j in range(sp["n"]):
                a(f"        q{li}_{j} <= n{li}_{j};")
            a("    end")
            outs = [f"q{li}_{j}" for j in range(sp["n"])]
        src, srcb = outs, [b] * sp["n"]
    # ---- scores, argmax, output register
    last = specs[-1]
    nc = cfg["n_classes"]
    pc = cfg["per_class"] if cfg["output"] == "additive" else 1
    sw = last["bits"] + _w(pc - 1) if pc > 1 else last["bits"]
    a("    // class scores (signed) and argmax, ties to the lowest class index")
    for c in range(nc):
        ext = []
        for i in range(pc):
            v = src[c * pc + i]
            if sw > last["bits"]:
                a(f"    wire logic signed [{sw - 1}:0] x{c}_{i} = {{{{{sw - last['bits']}{{{v}[{last['bits'] - 1}]}}}}, {v}}};")
                ext.append(f"x{c}_{i}")
            else:
                ext.append(f"$signed({v})")
        a(f"    wire logic signed [{sw - 1}:0] s{c} = {' + '.join(ext)};")
    a("    wire logic       ge10 = s1 > s0;")
    a("    wire logic signed [" + str(sw - 1) + ":0] m01 = ge10 ? s1 : s0;")
    a("    wire logic [1:0] c01 = ge10 ? 2'd1 : 2'd0;")
    a("    wire logic [1:0] cls = (s2 > m01) ? 2'd2 : c01;")
    a("    logic [LATENCY-1:0] vpipe;")
    a("    always_ff @(posedge clk) begin")
    a("        out_cls <= cls;")
    a("        if (rst) vpipe <= '0; else vpipe <= {vpipe[LATENCY-2:0], in_v};" if latency > 1 else
      "        if (rst) vpipe <= '0; else vpipe <= in_v;")
    a("    end")
    a("    assign out_v = vpipe[LATENCY-1];")
    a("endmodule")
    a("`default_nettype wire")
    if nc != 3:
        raise ValueError("the RTL argmax is written for 3 classes")
    return "\n".join(L) + "\n"
