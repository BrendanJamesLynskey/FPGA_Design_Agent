"""Test-bench wrapper for a generated register block (brief 64A): the block, the brief 59A AXI4-Lite checker on the same
wires, and every field port packed into two flat vectors (hw_in driven by the bench, hw_out read by it), so one cocotb
module (regmap_cocotb.py) can test any register map. layout() says where each port sits in the vectors."""
from __future__ import annotations

import json
from pathlib import Path

from hwsw import regmap

ROOT = Path(__file__).resolve().parents[2]
CHECKER_SRC = [ROOT / "axi_tx" / "rtl" / n for n in ("axil_checker.sv", "axil_rules.sv", "axi_viol_log.sv")]


def layout(m: regmap.RegMap) -> dict:
    """{'in': {port: [lsb, width]}, 'out': {...}, 'in_w': N, 'out_w': M}."""
    lay = {"in": {}, "out": {}}
    pos = {"input": 0, "output": 0}
    for d, n, w in regmap.ports(m):
        k = "in" if d == "input" else "out"
        lay[k][n] = [pos[d], w]
        pos[d] += w
    lay["in_w"], lay["out_w"] = max(1, pos["input"]), max(1, pos["output"])
    return lay


def tb_text(m: regmap.RegMap) -> str:
    lay = layout(m)
    aw = m.addr_width
    L = [f"// Bench wrapper for {m.name}_regs (generated by hwsw/tests/regmap_tb.py for the tests; not a design file)",
         f"module {m.name}_regs_tb;",
         "    logic aclk = 1'b0;",
         "    logic aresetn = 1'b0;",
         f"    logic [{aw - 1}:0] s_axil_awaddr = '0, s_axil_araddr = '0;",
         "    logic [2:0] s_axil_awprot = 3'b000, s_axil_arprot = 3'b000;",
         "    logic s_axil_awvalid = 1'b0, s_axil_wvalid = 1'b0, s_axil_bready = 1'b0, s_axil_arvalid = 1'b0, s_axil_rready = 1'b0;",
         "    logic [31:0] s_axil_wdata = '0;",
         "    logic [3:0] s_axil_wstrb = 4'hf;",
         "    logic s_axil_awready, s_axil_wready, s_axil_bvalid, s_axil_arready, s_axil_rvalid;",
         "    logic [1:0] s_axil_bresp, s_axil_rresp;",
         "    logic [31:0] s_axil_rdata;",
         f"    logic [{lay['in_w'] - 1}:0] hw_in = '0;",
         f"    logic [{lay['out_w'] - 1}:0] hw_out;",
         "    logic [31:0] now = 32'd0;",
         "    always @(posedge aclk) now <= now + 32'd1;",
         "    logic [9:0] viol;",
         "    logic chk_trig, chk_any;",
         "    logic [31:0] chk_rd;"]
    conn = []
    for d, n, w in regmap.ports(m):
        if d == "input":
            lsb, ww = lay["in"][n]
            conn.append(f"        .{n}(hw_in[{lsb + ww - 1}:{lsb}])")
        else:
            lsb, ww = lay["out"][n]
            conn.append(f"        .{n}(hw_out[{lsb + ww - 1}:{lsb}])")
    if not lay["out"]:
        L.append("    assign hw_out = '0;")
    axi = ["aclk", "aresetn", "s_axil_awaddr", "s_axil_awprot", "s_axil_awvalid", "s_axil_awready", "s_axil_wdata",
           "s_axil_wstrb", "s_axil_wvalid", "s_axil_wready", "s_axil_bresp", "s_axil_bvalid", "s_axil_bready",
           "s_axil_araddr", "s_axil_arprot", "s_axil_arvalid", "s_axil_arready", "s_axil_rdata", "s_axil_rresp",
           "s_axil_rvalid", "s_axil_rready"]
    L.append(f"    {m.name}_regs u_dut (")
    L.append(",\n".join([f"        .{s}({s})" for s in axi] + conn))
    L.append("    );")
    L.append(f"    axil_checker #(.ADDR_W({aw}), .DATA_W(32)) u_chk (")
    L.append("        .aclk(aclk), .aresetn(aresetn), .clear(1'b0), .en(10'h3ff), .now(now),")
    L.append("        .awaddr(s_axil_awaddr), .awprot(s_axil_awprot), .awvalid(s_axil_awvalid), .awready(s_axil_awready),")
    L.append("        .wdata(s_axil_wdata), .wstrb(s_axil_wstrb), .wvalid(s_axil_wvalid), .wready(s_axil_wready),")
    L.append("        .bresp(s_axil_bresp), .bvalid(s_axil_bvalid), .bready(s_axil_bready),")
    L.append("        .araddr(s_axil_araddr), .arprot(s_axil_arprot), .arvalid(s_axil_arvalid), .arready(s_axil_arready),")
    L.append("        .rdata(s_axil_rdata), .rresp(s_axil_rresp), .rvalid(s_axil_rvalid), .rready(s_axil_rready),")
    L.append("        .viol(viol), .trig(chk_trig), .any(chk_any), .rd_sel(6'd0), .rd_data(chk_rd));")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def write(m: regmap.RegMap, out: Path) -> tuple[Path, Path]:
    out.mkdir(parents=True, exist_ok=True)
    tb = out / f"{m.name}_regs_tb.sv"
    tb.write_text(tb_text(m))
    lay = out / f"{m.name}_layout.json"
    lay.write_text(json.dumps(layout(m), indent=1))
    return tb, lay
