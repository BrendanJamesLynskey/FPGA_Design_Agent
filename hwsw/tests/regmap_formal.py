"""Formal check of a generated register block's AXI4-Lite handshake (brief 64A), with SymbiYosys.

The harness makes every master-side signal and every hardware input a free input, assumes the master keeps the
master's rules of the brief 59A checker (axi_tx/rtl/axil_rules.sv: AW/W/AR held until READY, no VALID in or straight
out of reset), and asserts the slave's rules on the block: B and R held until READY, no B before both AW and W, no R
before AR, no EXOKAY, no VALID during reset. A bounded proof (bmc with ABC's bmc3, default depth 20), a cover task
(smtbmc: a write and a read response are reachable, so the proof is not vacuous), and `prove` (ABC's PDR: an unbounded
proof when it converges).

    python3 -m hwsw.tests.regmap_formal hwsw/examples/demo_accel.yaml [--depth 20] [--mode bmc|prove|cover]

Needs yosys, z3 and sby on PATH (locally: source ~/.local/opt/formal-deb/env.sh; CI installs them)."""
from __future__ import annotations

import argparse
import os
import shutil
import signal
import subprocess
import sys
from pathlib import Path

from hwsw import regmap
from hwsw.tests.regmap_tb import CHECKER_SRC, layout

ROOT = Path(__file__).resolve().parents[2]
RULES = ROOT / "axi_tx" / "rtl" / "axil_rules.sv"


def harness(m: regmap.RegMap) -> str:
    aw = m.addr_width
    lay = layout(m)
    conn = []
    for d, n, w in regmap.ports(m):
        if d == "input":
            lsb, ww = lay["in"][n]
            conn.append(f"        .{n}(hw_in[{lsb + ww - 1}:{lsb}])")
        else:
            lsb, ww = lay["out"][n]
            conn.append(f"        .{n}(hw_out[{lsb + ww - 1}:{lsb}])")
    return f"""// formal harness for {m.name}_regs (generated by hwsw/tests/regmap_formal.py)
module formal_{m.name}_regs (
    input logic clk,
    input logic aresetn,
    input logic [{aw - 1}:0] awaddr, input logic [2:0] awprot, input logic awvalid,
    input logic [31:0] wdata, input logic [3:0] wstrb, input logic wvalid,
    input logic bready,
    input logic [{aw - 1}:0] araddr, input logic [2:0] arprot, input logic arvalid,
    input logic rready,
    input logic [{lay['in_w'] - 1}:0] hw_in
);
    logic awready, wready, bvalid, arready, rvalid;
    logic [1:0] bresp, rresp;
    logic [31:0] rdata;
    logic [{lay['out_w'] - 1}:0] hw_out;
    {m.name}_regs dut (
        .aclk(clk), .aresetn(aresetn),
        .s_axil_awaddr(awaddr), .s_axil_awprot(awprot), .s_axil_awvalid(awvalid), .s_axil_awready(awready),
        .s_axil_wdata(wdata), .s_axil_wstrb(wstrb), .s_axil_wvalid(wvalid), .s_axil_wready(wready),
        .s_axil_bresp(bresp), .s_axil_bvalid(bvalid), .s_axil_bready(bready),
        .s_axil_araddr(araddr), .s_axil_arprot(arprot), .s_axil_arvalid(arvalid), .s_axil_arready(arready),
        .s_axil_rdata(rdata), .s_axil_rresp(rresp), .s_axil_rvalid(rvalid), .s_axil_rready(rready){',' if conn else ''}
{(',' + chr(10)).join(conn)}
    );
    logic [9:0] viol;
    axil_rules #(.ADDR_W({aw}), .DATA_W(32), .CW(4)) chk (
        .aclk(clk), .aresetn(aresetn), .awaddr(awaddr), .awprot(awprot), .awvalid(awvalid), .awready(awready),
        .wdata(wdata), .wstrb(wstrb), .wvalid(wvalid), .wready(wready), .bresp(bresp), .bvalid(bvalid),
        .bready(bready), .araddr(araddr), .arprot(arprot), .arvalid(arvalid), .arready(arready), .rdata(rdata),
        .rresp(rresp), .rvalid(rvalid), .rready(rready), .viol(viol));

    reg f_past_valid = 1'b0;
    always @(posedge clk) f_past_valid <= 1'b1;
    always @(*) begin
        if (!f_past_valid) assume (!aresetn);               // start in reset
        // the master keeps its side: AW, W, AR held until READY (rules 0, 1, 3), no VALID out of or in reset (7, 9)
        assume (!viol[0]); assume (!viol[1]); assume (!viol[3]); assume (!viol[7]);
        if (!aresetn) assume (!awvalid && !wvalid && !arvalid);
    end
    always @(*) begin
        if (f_past_valid) begin                             // the block keeps the slave's side
            assert (!viol[2]);                              // B held until BREADY
            assert (!viol[4]);                              // R held until RREADY
            assert (!viol[5]);                              // no B before both AW and W
            assert (!viol[6]);                              // no R before AR
            assert (!viol[8]);                              // no EXOKAY
            assert (!viol[9]);                              // no VALID during reset (from its second edge)
        end
    end
    always @(posedge clk) if (f_past_valid && aresetn) begin
        cover (bvalid && bready && bresp == 2'b00);         // a write is answered
        cover (rvalid && rready && rresp == 2'b00);         // a read is answered
    end
endmodule
"""


ENGINES = {"bmc": "smtbmc --unroll z3", "prove": "smtbmc --unroll z3", "cover": "smtbmc --unroll z3"}   # --unroll: z3 stalls on step 0 of the larger maps without it


def sby(m: regmap.RegMap, sv: Path, mode: str, depth: int) -> str:
    files = [sv, RULES]
    return f"""[options]
mode {mode}
depth {depth}

[engines]
{ENGINES[mode]}

[script]
read_verilog -formal -sv {' '.join(p.name for p in files)}
read_verilog -formal -sv formal_{m.name}_regs.sv
prep -top formal_{m.name}_regs

[files]
{chr(10).join(str(p) for p in files)}
formal_{m.name}_regs.sv
"""


def run(yaml_path: Path, out: Path, mode: str = "bmc", depth: int = 20, sv_text: str | None = None,
        timeout: float = 600) -> str:
    """Run one task; returns sby's verdict (PASS, FAIL, ERROR, ...)."""
    m = regmap.load(yaml_path)
    out.mkdir(parents=True, exist_ok=True)
    sv = out / f"{m.name}_regs.sv"
    sv.write_text(sv_text if sv_text is not None else regmap.emit_sv(m))
    (out / f"formal_{m.name}_regs.sv").write_text(harness(m))
    job = out / f"{mode}.sby"
    job.write_text(sby(m, sv, mode, depth))
    work = out / mode
    if work.exists():
        shutil.rmtree(work)
    p = subprocess.Popen(["sby", "-f", "-d", str(work), str(job)], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                         text=True, cwd=out, start_new_session=True)
    try:
        log, _ = p.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        os.killpg(p.pid, signal.SIGTERM)                    # sby, yosys-smtbmc and the solver together
        log, _ = p.communicate()
        (out / f"{mode}.log").write_text(log)
        return "TIMEOUT"
    (out / f"{mode}.log").write_text(log)
    status = work / "status"
    return status.read_text().split()[0] if status.exists() else "ERROR"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python3 -m hwsw.tests.regmap_formal")
    ap.add_argument("yaml")
    ap.add_argument("--depth", type=int, default=20)
    ap.add_argument("--mode", default="bmc", choices=["bmc", "prove", "cover"])
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    m = regmap.load(a.yaml)
    out = Path(a.out) if a.out else ROOT / "build" / "64a" / "formal" / m.name
    v = run(Path(a.yaml), out, a.mode, a.depth)
    print(f"{m.name} {a.mode} depth {a.depth}: {v} ({out / (a.mode + '.log')})")
    return 0 if v == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
